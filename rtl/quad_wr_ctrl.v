//=====================================================================
// quad_wr_ctrl.v   (Verilog-2001)  工作在 50MHz (DDR 写时钟域)
//---------------------------------------------------------------------
// v10  "带地址的块搬运器" —— 两路各自一队, 谁有整块就搬谁
//
// 布局(屏幕 1024x600, DDR 里是同一张图):
//
//        +-----------+-----------+
//        |   摄像头   |    PC     |   y <  300
//        +-----------+-----------+
//        |    PC     |    PC     |   y >= 300
//        +-----------+-----------+
//
// 基本单位: 一个"块" = 512 像素 = 屏幕的半个行 (行宽 1024/2)
//           DDR 地址 = 块号 * 64  (1 单位 = 8 像素, 见 ddr3_rw_ctrl)
//
// 每一路的数据流里, 块与块之间夹着一个"标签字"(bit16=1, bit[10:0]=块号),
// 后面紧跟 512 个像素字。所以:
//
//   看首字是不是标签 -> 是就把它变成地址压进地址 FIFO -> 再搬 512 个像素
//
// ★为什么这样不会错位★
//   标签和像素在同一条 FIFO 里, 位置关系是硬连的。上游"整块准入/整行准入"
//   保证不会写半块, 所以"标签 k + 紧随的 512 像素"永远属于同一块。
//   v9 用两条独立 FIFO, 一旦像素 FIFO 丢几个, 之后就永久错位(斜条纹)。
//
// ★为什么不会死锁★
//   起块的条件是"这一路已经有 513 个字"(见 UNIT), 所以一旦开始搬, 512 个
//   像素必然已经在 FIFO 里, 搬运过程中不会停下来等网络/等摄像头。
//
// v11  加了 gray_en: 落盘前把 RGB565 转成灰度
// v12  灰度开关扩成 5 档算法链 (mode_sel), 同一颗按键循环切换:
//         0 彩色      直通
//         1 灰度      Y = 0.299R + 0.587G + 0.114B
//         2 去噪      灰度 + 1x3 中值 (去掉横向椒盐/条纹噪点)
//         3 二值化    灰度 + 中值 + 自适应阈值 (min/max 中点, 分摄像头/PC)
//         4 YCbCr     Y/Cb/Cr 三个分量当 R/G/B 显示 (伪彩, 肤色最显眼)
//      所有算法都在【写通路】做, 读通路一行没动, 详见下面各段注释。
//
// v28  ★翻页必须"这一页写完整了"才允许★ (见 pg_ready / pg_last 那两段)
//       现场全屏 PC 顶部一条旧画面横带, 根因是翻页时机跟"帧写完没有"无关:
//       块 0 一到就请求翻页, 而块 0 那一拍同时被写进了上一页 —— 新页从块 1
//       开始, 屏幕最上面那半行永远是旧内容; 翻页再被"等地址排空"拖后几百块,
//       顶部就成了一条几百块宽的旧横带。
//       现在: 帧末块 1199 一开始写就请求翻页, 512 像素搬完才真翻, 一页一帧。
//=====================================================================
module quad_wr_ctrl(
    input  wire        clk            ,
    input  wire        rst_n          ,
    input  wire        init_done      ,   // DDR3 初始化完成
    // ---- 摄像头字流 (17bit, bit16=1 为标签) ----
    input  wire [16:0] cam_word       ,
    input  wire        cam_empty      ,
    output wire        cam_rd         ,
    input  wire [12:0] cam_level      ,
    // ---- PC 字流 ----
    input  wire [16:0] pc_word        ,
    input  wire        pc_empty       ,
    output wire        pc_rd          ,
    input  wire [13:0] pc_level       ,
    // ---- 换页 ----
    input  wire        cam_vs         ,   // 摄像头场同步(50MHz 域 1 拍脉冲)
    output reg         wr_page        ,   // 当前正在写的那一页
    output reg         wr_done_page   ,   // 刚写满的那一页(读侧在 rd_end 跟过去)
    // ---- 算法档位 (按钮循环切换, 已在顶层消抖) ----
    input  wire [2:0]  mode_sel       ,   // 0=彩色 1=灰度 2=去噪 3=二值 4=YCbCr
    // ---- 显示模式 (v15, v23 扩成三态) ----
    input  wire        full_scr       ,   // 1=PC 全屏(只用 PC, 1024x600) 0=其余
    input  wire        cam_full       ,   // 1=摄像头全屏(只用摄像头, 1200 块)
    // ---- 车道线检测结果 (v31, 已在 clk_50m 域锁存) ----
    //   [87:0]  8 个调试锚点 {有效, x[9:0]} x 8
    //   [109:88] {ltyp, rtyp, cdir, lstate, offl, offv}
    //   由 lane_detect 在 cam_pclk 域产生, 经 lane_cdc 翻转握手送过来。
    input  wire [127:0] lane_bus      ,
    input  wire         lane_vld      ,   // 车道结果更新单拍脉冲(每帧一次)
    input  wire         lane_en       ,   // 车道线图层开关(总闸, 恒 1)
    input  wire         lane_osd_en   ,   // v51: 车道识别【显示】开关 (PC 面板, 1=显示)
    // ---- v39 模拟强制命令 (顶层按键 k2/k3/k4, 互斥) ----
    input  wire         force_go      ,   // 强制直行
    input  wire         force_l       ,   // 强制左变道
    input  wire         force_r       ,   // 强制右变道
    output wire         alarm         ,   // 报警灯(危险指令冲突)
    // ---- v44 车辆行驶状态 (给顶层的 3 个状态灯) ----
    //   0 = 直行  1 = 左转  2 = 右转   (三态互斥, 顶层一态点一颗灯)
    output wire [1:0]   drv_state     ,
    // ---- 写地址流 (给 ddr3 的地址 FIFO) ----
    output reg  [27:0] ad_data        ,
    output reg         ad_wr          ,
    input  wire [4:0]  ad_level       ,   // 地址 FIFO 里还有几个块没落盘
    // ---- DDR3 写口 ----
    output reg  [15:0] wd_data        ,
    output reg         wd_en          ,
    // ---- 诊断 ----
    output reg  [31:0] cam_px         ,   // 摄像头已落盘像素
    output reg  [31:0] pc_px          ,   // PC 已落盘像素
    output reg  [15:0] chunk_cnt      ,   // 已落盘块数
    output reg         frame_live     ,   // v23: DDR 里已经有真实画面了
    output wire        busy
);

    localparam [2:0]  ST_IDLE = 3'd0;
    localparam [2:0]  ST_RUN  = 3'd1;
    // ★v25: 丢掉一个"不该出现在块首的字"。正常情况下永远进不来, 一旦进了
    //   说明字流错位(少字/多字), 丢掉它就能在下一个标签处自动对齐。
    localparam [2:0]  ST_SKIP = 3'd2;
    // ★v27: 整块丢弃。翻页以后, FIFO 队首还可能是"上一帧的尾巴"(块号接在
    //   后半段), 这时候如果照写, 新的一页前 900 块里绝大部分会保持上一页的
    //   旧内容 —— 屏幕上就是一大片"定格", 只有末尾那一小条在动。
    //   进这个状态就把这一整块(标签 513 字)读走扔掉, 一直丢到看见帧首块。
    localparam [2:0]  ST_DROP = 3'd3;

    localparam [9:0]  CHUNK   = 10'd512;    // 一块的像素数
    localparam [13:0] UNIT    = 14'd513;    // 标签 + 512 像素

    // ---- 算法档位编码 (和顶层 key 的循环顺序一致) ----
    localparam [2:0]  M_COLOR  = 3'd0;
    localparam [2:0]  M_GRAY   = 3'd1;
    localparam [2:0]  M_DENOIS = 3'd2;
    localparam [2:0]  M_BINARY = 3'd3;
    localparam [2:0]  M_YCBCR  = 3'd4;

    reg [2:0]  st;
    reg [9:0]  pcnt;         // v12: 本块已走几拍 (0..512, 共 513 拍)
    reg        src;          // 0 = 摄像头, 1 = PC
    reg [10:0] cur_dst;      // v13: 当前块的块号 (起块那拍从标签字里锁存)
    reg        flip_pend;    // 有换页请求
    reg        page_dirty;   // 本页写过东西(否则不翻, 免得翻到空白页)
    // v26: PC 帧与翻页对齐用的闸门 + "错位丢字"记着丢的是哪一路
    reg        pc_gate;      // 1 = 允许消费 PC 块
    reg        pc_seen;      // 本页已经消费过 PC 块
    reg [22:0] gate_to;      // 闸门兜底超时(摄像头掉线时不至于把 PC 饿死)
                             // ★23 位: 100ms = 5,000,000, 22 位装不下会截断成 16ms★
    reg        skip_pc;      // ST_SKIP 这一拍丢的是 PC 字(否则是摄像头字)
    reg        full_d;       // full_scr 打一拍, 用来抓模式切换
    // v27: 翻页后"等帧首块"。
    //   只要这一位是 1, 写侧只认块号 == tl_start_blk 的标签, 其余整块丢掉。
    //   这样每一页的 PC 内容一定从"画面顶部"开始, 即使 PC 供不上, 缺的也是
    //   末尾(屏幕最底部), 不会变成"上半页是旧内容"。
    reg        pc_align;
    reg [9:0]  drop_cnt;     // ST_DROP 里还要丢多少个字
    reg [22:0] align_to;     // 等帧首的兜底超时(100ms)
    //------------------------------------------------------------------
    // ★v28: "这一页到底写完整了没有"★
    //   现场(烧了 v27 之后)全屏 PC 还剩一条: 屏幕**最上面**一条横带是旧画面,
    //   下面全是新画面, 带子高度不定、时有时无。
    //
    //   根因不是丢包, 也不是对齐 —— 是**翻页翻早了**:
    //     写侧翻页的时机只有两个条件: 块边界(st==ST_IDLE) + 地址 FIFO 排空。
    //     这两个条件跟"这一页的 PC 帧写完没有"毫无关系。只要 PC 那一帧还没
    //     写完(比如发送端抖了一下、或下一帧的块 0 已经到了而现场还在排地址),
    //     翻页照样发生 —— 被翻出去的那一页就是"上半截新帧 + 下半截上一帧",
    //     或者反过来"顶部几百块还是上上帧的内容"。屏幕上看就是一条横带。
    //
    //   做法: 翻页再加一道硬条件 —— 本页必须已经写到帧末块(dst==1199)。
    //     没写完整就不翻, 屏幕上继续显示上一张**完整**的帧(短暂定格),
    //     定格比撕裂好一百倍: 撕裂是"每帧都在错", 定格只在发送端抖的那一下。
    //   兜底: 本页超过 100ms 还没写完整就强制翻 —— 万一真丢了一个包,
    //     不能把画面永久冻住(那种情况下宁可偶尔撕裂一次)。
    //------------------------------------------------------------------
    reg        pg_started;   // 本页已经起过"帧首块"
    reg        pg_last;      // 本页已经写到帧末块(两种模式最后一包都是 1199)
    reg [23:0] pg_to;        // 本页"写完整"的兜底超时 (100ms = 5,000,000)
    // ★v29★ 本页有没有 PC 块进来(不管是不是帧首)。
    //   用来区分"这一页压根没有 PC(纯摄像头页, 该显示)"和"这一页有 PC 但
    //   不是从帧首开始的(残页, 不能显示)"。只有 pg_started 一个标志分不开这两种。
    reg        pg_pc_any;
    // ★v33: 本页写进来的 PC 块计数★
    //   只靠 pg_started / pg_last 抓不到"中间缺几块": UDP 丢一个包, 那个块
    //   压根没写, DDR 里保留的是上一页的旧像素 —— 切到二值化时那条旧像素
    //   还是彩色的, 屏幕上就是一条彩色条纹。而 pg_last 照样置起, page_ok
    //   判不出来。加了这个计数, 缺几块就是少几个数, 一眼可见。
    reg [10:0] pg_cnt;
    // ★v35: 本页写的第一个 PC 块是不是"帧首块"★
    //   pg_started 只说明"本页出现过 dst==tl_start_blk", 挡不住"先写了半帧、
    //   后来又撞上下一帧的帧首块"这种跨两帧的页 —— 那种页块数能凑够, 但
    //   顶上那一段是上一帧的, 屏幕上就是一条横带。这里单独记第一位。
    reg        pg_head_ok;
    // ★v29★ 连续几页被判残。残页被丢掉不显示是安全的, 但真丢了帧末包时
    //   可能连着几页都残, 那样画面会永久定格。数到 4 页就强制发布一次,
    //   宁可露一帧半页, 也不能冻住不动。
    reg  [2:0] bad_cnt;

    // 地址 FIFO 深度 16, 每块 64 个 128bit 字 -> 最多压 8 块(512 字)
    // 就停一下, 保证写数据 FIFO(深度 1024 字)永远不溢出。
    //
    // ★v29: 再与上 ~flip_pend★ 这一条是"顶部一条旧画面横带"的根治点。
    //   翻页请求(flip_pend)置起后, do_flip 还要等 flip_ok(地址排空 / 页写完 /
    //   20ms 超时)才成立。这段等待时间可能是几十微秒, 也可能到 20ms。
    //   原来这段时间里写侧**照样起新块**, 于是下一帧最前面的一批块被写进了
    //   **还没翻过去的旧页**(页号还是旧的), 新页从中间某个块开始 —— 屏幕顶部
    //   那一段就永远保留着旧页的内容(现场看到的就是顶部一条旧模式横带)。
    //   加上之后: 一旦有翻页请求, 当前块写完就停住, 等翻页完成再从下一块
    //   (也就是新帧的块 0)开始写, 一页必定从块 0 起头。
    //   ★v30: 这条"停手"只对**全屏**成立★
    //   全屏的翻页请求是"这一帧写完了"(pg_last), 此时 PC 帧已经到队尾, 停手
    //   正好把下一帧的块 0 留在 FIFO 里。
    //   四宫格的翻页请求是 cam_vs(45.4ms 一拍), 而 PC 帧是 41.7ms —— 请求
    //   常常落在 PC 帧写到一半的时候。这时如果停手, 写侧就再也写不到块 1199,
    //   pg_ready 永远不成立, 只能等 pg_to 的 100ms 超时, 而且这一页被判残不
    //   上屏 -> 屏幕就**卡在切换前那一帧**(tb_full2quad: 431ms 才翻一次)。
    wire can_start = (ad_level <= 5'd5) & (~flip_pend | ~full_scr);

    // ★关键: 够一整块(标签 + 512 像素)才开工, 搬的过程中不会中途停下
    // ★全屏模式把摄像头整路关掉★ 不是"优先级降低"而是完全不参与:
    //   否则全屏时 PC 发满 1200 块, 摄像头还想写它那 300 个块, 两边抢同一块
    //   地址, 屏幕上会出现左上角一块摄像头画面糊在 PC 画面上面。
    wire cam_have = init_done & (cam_level >= UNIT[12:0]) & ~cam_empty & ~full_scr
                  & cam_word[16];          // ★v25: 块首必须是标签字
    // ★v25 自愈★ 块首都该是标签字(bit16=1)。如果来的是像素, 说明上游的字流
    //   少了一个/多了一个, 已经错位了。这时候绝不能把它当块号用 —— 那会拿到
    //   一个垃圾块号(像素值), 写到画面外面去, 然后**整个后续字流永久错位**:
    //   每一次"读标签"读到的都是像素, 可见画面区一个块都不再更新, 屏幕上表
    //   现为"定格不动", 偶尔撞进 0..1199 的垃圾块号就变成"画面长条"。
    //   把错位的字丢掉, 下一个标签字一到就自动对齐, 最多丢 1 块。
    wire cam_badtag = init_done & (cam_level != 13'd0) & ~cam_empty & ~full_scr
                    & ~cam_word[16];
    // ★v23★ 摄像头全屏时把 PC 整路关掉: 这一屏 1200 块全归摄像头, PC 要是
    //   还在往里写, 两边抢同一批块号, 屏幕上就是两种画面互相覆盖。
    //   PC 端收到遥测里的模式位后也会主动停发, 这里是第二道保险。
    // ★v26★ 下面对 PC 也做了块首标签校验和自愈, 和摄像头完全对称 ——
    //   v25 只给了摄像头, PC 这一路一旦错位就是**永久**错位(它没有丢字恢复的
    //   机会), 表现比摄像头那一路更糟: 每个"块号"都是像素值, 垃圾块号撒得
    //   满屏都是, 连左上角摄像头那一格也会被糊掉。

    // 新一帧的起点(PC 包里的块号):
    //   四宫格 -> 右上格第 0 行右半 = 块号 1 (左上格是摄像头, PC 不发这一块)
    //   全屏   -> 块号 0 (PC 发满 1200 块, 从第 0 行左半开始)
    wire [10:0] tl_start_blk = full_scr ? 11'd0 : 11'd1;

    wire pc_avail  = init_done & (pc_level >= UNIT) & ~pc_empty & ~cam_full;
    // ★v26 闸门★ 一页只写一整帧 PC。理由:
    //   摄像头是 22fps、PC 是 24fps, 两个节拍谁也不跟谁。翻页是按 cam_vs 走的,
    //   如果翻页那一刻 PC 正好写到一帧中间, 那新一页里就是"上半截新帧 + 下半截
    //   上一帧" —— 屏幕上就是一条慢慢移动的横向接缝(现场看到的就是这个)。
    //   做法: PC 帧的**下一帧首块**一到就关闸, 等下一次翻页再开闸。这样每一帧
    //   PC 都从翻页那一拍开始写, 接缝自然没了。PC 端的节奏由信用窗口自动
    //   跟着板子走(积压够了它自己就等), 发送端一行都不用改。
    //   全屏模式不闸: 全屏的翻页本来就是 PC 帧首块触发的, 天生对齐。
    wire pc_gate_eff = full_scr | pc_gate;
    wire pc_is_tag   = pc_word[16];
    // ★只能在"块首"判帧首块★ 块中间 pc_word 是像素, 像素值低 11 位碰巧等于
    //   tl_start_blk 时就会误判成"新一帧开始了" -> 闸门关上, 这一路就停住。
    //   仿真里正是 16'h1000+1 这个像素把闸门关掉的(第一个块之后就不再动了)。
    wire pc_blk_first = (st == ST_IDLE) & can_start & pc_avail & pc_gate_eff
                      & ~cam_have & pc_is_tag;
    wire pc_wrap     = pc_blk_first & ~full_scr & pc_seen
                     & (pc_word[10:0] == tl_start_blk);
    // v27: 帧首块 = 标签 + 块号正好是这一帧的起点
    wire pc_is_start = pc_is_tag & (pc_word[10:0] == tl_start_blk);
    // ★v29: "上一帧的尾巴断了, 下一帧已经来了"检测★ (只用于全屏)
    //   场景: 帧末块 dst==1199 那一包丢了。这时 pg_last 永远不置 1,
    //   而数据还在流(pg_to 被每个块清 0) -> pg_force 也永远不超时 ->
    //   flip_req 一路为 0 -> 画面**永久定格**, 只能复位。
    //   仿真读数(tb_droplast, 每帧故意不发 1199): flips=0, 一个字都不翻。
    //   判据: 本页已经起过帧首块(pg_started), 队首却又是一个帧首块 ->
    //   说明这一页就这么长了, 底下那一块属于下一页。
    //   ★这一块必须留在 FIFO 里★(下面 pc_have 会把它挡掉), 翻页之后
    //   新页正好从它开始写, 一页还是从块 0 起头。
    //   只给全屏用: 四宫格若按 PC 帧翻页, 摄像头那格会被拦腰切断。
    //   ★注意这里不能用 can_start★ can_start 里含 ~flip_pend, 而这个信号正是
    //   用来"拉高 flip_pend"的 —— 用它就成了自锁: flip_pend 一置起, pc_next_frame
    //   立刻变 0, pg_ready 又跟着变 0, 翻页永远等不到。仿真里表现就是
    //   每 100ms 才动一下(靠 pg_to 超时)。所以这里只判"地址不忙"。
    wire pc_next_frame = (st == ST_IDLE) & (ad_level <= 5'd5)
                       & pc_avail & pc_gate_eff & ~cam_have & pc_is_tag & pg_started
                       & (pc_word[10:0] == tl_start_blk);
    // 等帧首期间一律不写(交给 ST_DROP 整块扔掉)
    wire pc_have     = pc_avail & pc_gate_eff & pc_is_tag & ~pc_wrap & ~pc_align
                     & ~pc_next_frame;
    wire pc_badtag   = pc_avail & pc_gate_eff & ~pc_is_tag;

    // ★v35: 闸门关着时也要把 PC 字读走扔掉★
    //   为什么必须这么做(现场遥测 + 推算):
    //     一页 PC 写完后 pc_gate 关闸, 一直等到 cam_vs(约 3.7ms)才翻页。
    //     这 3.7ms 里写侧一个块都不消费, 而 PC 端还在按 44us/包 发, 于是
    //     PC FIFO(8192 字 = 16 块)在 700us 内就灌满, 之后到的包被
    //     udp_video_rx 整包丢掉(room=0, pkt_cnt 根本不加) —— 板子遥测里
    //     "收包率 92.4%" 就是这么来的, 丢的 7.6% 全挤在每页的末尾,
    //     也就是**下一帧的开头**(dst=1,3,5,...) = 右上格最上面那几十行。
    //     丢完 pc_align 等不到 dst==1, 100ms 超时硬对齐, 这一页从帧中间起头,
    //     顶上那一段永远写不到 —— 切二值化后它们仍是彩色, 屏幕上就是那条
    //     横带, 而且每页都这样, 所以永远不消失。
    //   修法: 等翻页的时候边等边丢, FIFO 就不会满, 包一个也不会丢,
    //     翻页后 dst==1 稳稳地在队首, 每页都从帧首起头。
    //   代价: 这一页的 PC 内容会比原来晚一帧(丢掉的那半帧本来就是上一帧的
    //     尾巴, 显示它反而会撕裂), 肉眼看不出来。
    //   ★只在 FIFO 快满的时候才丢★ 平时一个块都不多丢 —— 这条通路只是
    //   "泄压阀", 不是常开的水龙头。否则写侧会白白多占带宽, 摄像头那一格
    //   会跟着变慢(仿真里 tb_page_align 就是这么露出来的: cam 300->276)。
    //   阈值 6900: FIFO 深度 8192, RX 侧的 ROOM_MAX = 8192-512-8 = 7672,
    //   留 ~770 字(1.5 块)给"已经在路上"的包, 保证 room 不会掉。
    wire pc_near_full = (pc_level >= 13'd6900);
    wire pc_drain    = (st == ST_IDLE) & (ad_level <= 5'd5) & init_done
                     & (pc_level >= UNIT) & ~pc_empty & ~cam_full
                     & ~pc_gate_eff & pc_near_full & ~cam_have;
    //   (do_flip 在这里还没声明, 用不上 —— ST_IDLE 里 `if (do_flip)` 本来就排在
    //    这条分支前面, 优先级已经保证了)

    // 换页只在"块边界 + 地址 FIFO 基本排空"时做, 这样翻页点严格落在块边界上
    //
    // ★v16 修"卡死"★ 原来要求 ad_level == 0。
    //   ad_level 是地址 FIFO 水位, 只有 DDR 那边每消费一个地址才会降; 而 DDR
    //   消费的条件是"写数据 FIFO 里够一个完整突发"。PC 一断流, 写侧没有新
    //   数据进去, 数据 FIFO 被抽干, DDR 停下不再消费地址 —— ad_level 就停在
    //   原处不动。于是 flip_pend 永远等不到 flip_ok, wr_page 再也不翻转,
    //   屏幕定格在最后一页, 按键换档/换模式全都没反应, 只能按复位。
    //   两条一起上:
    //     (a) 地址基本排空(<=2)就允许翻 —— 地址字里自带页号, 晚一拍落盘也
    //         只会写进它自己那一页, 不会把翻页点弄错;
    //     (b) 20ms 超时兜底 —— 万一还是凑不上就强制翻过去, 保证画面永远
    //         不会永久定格。
    reg  [19:0] flip_to;                    // 50MHz 下 20 位约 21ms
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            flip_to <= 20'd0;
        else if (!flip_pend)
            flip_to <= 20'd0;
        else if (flip_to != 20'd999_999)
            flip_to <= flip_to + 20'd1;
    end
    wire flip_timeout = (flip_to == 20'd999_999);

    //------------------------------------------------------------------
    // ★v28: 翻页的第三个条件 —— 这一页的 PC 帧必须已经写完★
    //   pg_started = 本页起过帧首块(说明这一页是 PC 参与写的)
    //   pg_last    = 本页写到了帧末块 1199
    //   没起过帧首块(纯摄像头页) -> 不拦, 否则摄像头全屏/摄像头独跑会冻住
    //   pg_to 100ms 兜底: 真丢了一个包也不能永久冻屏
    //------------------------------------------------------------------
    wire [10:0] last_blk   = 11'd1199;      // 全屏 1200 块 / 四宫格 900 块, 最后一包都是 1199
    //   ★v29: pc_next_frame 也算"写完了"★ 它表示"下一帧的首块已经在队首",
    //   本页不可能再来数据了。不加这一条的话, 只要帧末块那一包丢一次,
    //   pg_ready 就要干等 pg_to 的 100ms 超时 —— 现场就是每 100ms 才动一帧,
    //   看起来像"切模式后画面半天不变"(tb_droplast: 588ms 只翻了 4 次)。
    //
    //   ★v30: 四宫格的翻页节拍是 cam_vs, 但不能"请求一来就翻"★
    //   四宫格一页必须装下一整帧 PC(否则页里一半是上一帧, 屏幕下半截就是
    //   旧内容 —— 现场"切到四宫格下面卡住"就是这个)。所以四宫格**也要**
    //   等到块 1199 写过才翻: 页率自然被 PC 帧(24fps)带住, 而摄像头那格
    //   22fps 比它慢, 每页最多少刷一两行, 看不出来。
    //   (曾经把这条改成只对全屏生效, 结果每页只写 424 块: cam_vs 在 PC 帧
    //    中途触发, pc_align 把后面 476 块全丢掉, 页里只剩半帧。)
    wire        pg_ready   = (~pg_started) | pg_last | pc_next_frame
                           | (pg_to == 24'd4_999_999);

    //------------------------------------------------------------------
    // ★v29: 页级"能不能上屏"门禁★
    //   这一条是现场"切到二值化后屏幕上还留着一块彩色 / 切回彩色又留着一块
    //   二值化"的直接解药。原因:
    //     翻页的三条兜底(beat_req / pg_force / flip_timeout)都会在"这一页的
    //     PC 只写了一半"的时候强行翻过去。翻过去的这一页里, 写到的部分是
    //     新帧(新模式), 没写到的部分仍然是**上一页的旧内容**(旧模式)。读侧
    //     到 rd_end 就把这一页整体显示出来 —— 于是同一屏里两种模式并存,
    //     而且这个残页会一直留在 DDR 里, 下一轮 ping-pong 转回来时还是它。
    //   判据(三种页):
    //     ① 纯摄像头页(pg_pc_any=0)      -> 可以显示
    //     ② PC 从帧首写到帧末(两个都=1)  -> 可以显示(完整的一帧)
    //     ③ 其余(有 PC 但缺头或缺尾)     -> 判残, **不更新 wr_done_page**
    //   残页不发布时读侧继续读上一个完整页, 屏幕表现为"停一帧", 而不是"半屏
    //   旧画面"。bad_cnt>=3 是保险: 真丢了帧末包时不能永远不翻牌。
    //   ★v29: pc_next_frame 也算"写完了"★ 它保证的是"缺的只可能是最后一包",
    //   也就是屏幕最底下半行 —— 那半行是旧内容没人看得出来。而"缺头"
    //   (pg_started=0) 是顶部一大片, 那种页仍然必须丢掉。
    //
    //   ★v30: 四宫格只要求"从帧首块开始写"★
    //   四宫格的页节拍是 cam_vs, PC 24fps 与它不同步, 常常刚写到一半就翻页。
    //   这时 pg_last=0 —— 若照全屏的标准判残, 四宫格会**每页都残、永不发布**,
    //   屏幕就定格在切换前那一帧(现场现象)。四宫格缺尾只是屏幕最下面一小条,
    //   可以接受; 缺头才是大问题(顶部一大片旧画面), 所以只保留 pg_started 这一条。
    //
    //   ★v33: 只有 pg_started 一个条件还是太松 —— 它挡不住"中间缺块"★
    //   UDP 丢几个包时, 那几块压根没写, DDR 里保留的是**上一页**的旧像素。
    //   如果上一页是彩色、这一页切成了二值化, 那几块就还是彩色 —— 现场看到的
    //   "右上角画面大部分正常, 但夹着几条彩色条纹"就是这个。而 pg_started 和
    //   pg_last 都是 1, 老判据一个都发现不了。
    //   补的办法是数块: pg_cnt 记本页真正写进来的 PC 块数(全屏应 1200, 四宫格
    //   应 900)。判据只加在"写到了末块但块数不够"这一种情况上(pg_hole_*) ——
    //   那才是中间缺; 而"没写到末块"是缺尾, 按 v28 的决定照旧放行, 否则
    //   tb_droplast(每帧丢末块)那种场景会冻屏。
    //   实测: 中间丢 21 块 -> cnt=1179 & last=1 -> ok=0 (判残, 不上屏);
    //         丢末块      -> cnt=1199 & last=0 -> ok=1 (放行, 只缺底部半行)。
    //------------------------------------------------------------------
    // ★v33: "中间缺块"和"缺尾"必须分开判★
    //   写到末块了, 块数却不够 -> 中间丢了块, DDR 里那几块还是上一页的旧像素,
    //     切到二值化时它们仍是彩色 —— 现场那条"彩色条纹"就是它。这种页不能上屏。
    //   没写到末块 -> 只是缺尾(底部半行), 按 v28 的决定可以接受。
    //   这样既挡住了条纹, 又不会因为"丢一个帧末包"就把画面冻住
    //   (tb_droplast 就是这个场景, 它必须继续翻)。
    // ★v34: 全屏不再要求 pg_last 先置位★
    //   原来写成 "pg_started & pg_last & (cnt<1200)", 意思是"写到末块了但块数
    //   不够 = 中间缺" 。问题在于末块和中间块一起丢的时候 pg_last=0, 这条判据
    //   直接不成立, "中间缺块"就从旁边溜过去了 —— 现场"切到二值化后顶部还
    //   压着一条彩色带"就是这个: 那一页的块数是 1180 左右, 但末块也丢了,
    //   于是被当成"只是缺尾"放行, 缺的那 20 块保留着上一页(彩色)的像素。
    //   改成只数块: 缺 8 块以内算缺尾(屏幕最底下几行, 看不出来), 超过就是
    //   中间缺, 一律不发布。tb_droplast 每帧丢末块 -> cnt=1199 >= 1192 放行;
    //   tb_drophole 中间丢 21 块 -> cnt=1179 < 1192 判残。
    //   四宫格那条不动(v30 的结论: 四宫格节拍和 PC 不同步, 只要求起过帧首块)。
    //   ★v34: 认两个"合法块数档", 而不是死认 1200★
    //   PC 端发多少块由它自己的格式决定: 全屏原生是 1200, 四宫格布局是 900。
    //   两种都可能是"完整的一页", 只有"块数掉在两个档之间"才是中间丢块。
    //   死认 1200 的话, 万一 PC 只发 900 块, 全屏会每页判残 -> 永远定格;
    //   死认 900 的话, 1200 块缺 20 又抓不住(条纹照样出现)。
    //   ★v35: 换成一把尺子量两种模式, 而且加了一条"必须从帧首块起头"★
    //   现场实测(2026-11-03 12:20, 板子遥测): 四宫格稳态下板子每秒只"收下"
    //   16625/18000 包 = 92.4%, 丢的 7.6% 不是随机丢, 而是**集中在每页末尾**:
    //   一页 PC 写完之后 pc_gate 关闸等 cam_vs(约 3.7ms), 这 3.7ms 里
    //   写侧一个块都不消费, PC FIFO(8192 字 = 16 块)瞬间灌满, 后面到的包
    //   被 udp_video_rx 整包丢掉(room=0) —— 丢掉的正好是**下一帧的开头**
    //   (dst=1,3,5,...), 也就是右上格最上面那几百行。
    //   然后 pc_align 等不到 dst==1, 100ms 超时后硬对齐, 这一页就从帧中间起头,
    //   顶上那几十行永远写不到 -> 切二值化之后它们还是彩色的, 就是那条
    //   "右上格顶部的彩色横带"(而且每页都这样, 所以永远不消失)。
    //
    //   所以判据要能挡住"起头不对"的页, 光数块数不够(跨两帧的页块数也能凑够):
    wire [10:0] cnt_min   = full_scr ? 11'd1192 : 11'd892;
    wire        pg_hole   = pg_started & ((pg_cnt < cnt_min) | ~pg_head_ok);

    wire        page_ok_raw = ~pg_pc_any | (pg_started & ~pg_hole);
    wire        page_ok     = page_ok_raw | (bad_cnt >= 3'd3);

    wire flip_ok = (st == ST_IDLE) & ((ad_level <= 5'd2) | flip_timeout) & pg_ready;
    wire do_flip = flip_pend & flip_ok;

    //------------------------------------------------------------------
    // v23: "屏幕可以显示了" 的标志
    //   上电时 DDR 里是随机内容, 读侧一上电就开始读, 屏幕上就是满屏雪花。
    //   这里在"第一次真正翻页、且那一页确实写过东西"之后置起 frame_live,
    //   顶层拿它把 LCD 数据口门成黑色: 上电先黑 1~2 秒(等摄像头配置完成),
    //   之后第一帧画面直接就是完整的。
    //   ★比"复位时主动清 1.2MB DDR"简单得多, 也不用动 DDR 控制器★
    //------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            frame_live <= 1'b0;
        else if (do_flip & page_dirty & page_ok)   // v29: 只有真的上屏了才算活
            frame_live <= 1'b1;
    end

    //------------------------------------------------------------------
    // 读使能
    //------------------------------------------------------------------
    // v12 的节奏: 一个块走 513 拍
    //   拍 0            : 读第 1 个像素(标签字在同一拍被 ST_IDLE 取走)
    //   拍 1 .. 511     : 读第 2..512 个像素
    //   拍 1 .. 512     : 写第 1..512 个像素  <- 比读晚 1 拍, 这是流水线的代价
    //   拍 512          : 只写不读, 把流水线里最后一个像素吐出来
    // 多出来的这 1 拍对时序毫无影响(每块 513 拍 vs 512 拍, 差 0.2%)。
    wire rd_cam = ((st == ST_IDLE) & can_start & cam_have & ~do_flip)
                | ((st == ST_RUN) & (src == 1'b0) & (pcnt < CHUNK))
                | ((st == ST_SKIP) & ~skip_pc);   // v26: 丢错位字(摄像头那一路)
    wire rd_pc  = ((st == ST_IDLE) & can_start & pc_have & ~cam_have & ~do_flip)
                | ((st == ST_RUN) & (src == 1'b1) & (pcnt < CHUNK))
                | ((st == ST_SKIP) &  skip_pc)    // v26: 丢错位字(PC 那一路)
                | ((st == ST_DROP) & ~pc_empty);  // v27: 整块丢掉(上一帧的尾巴)

    assign cam_rd = rd_cam;
    assign pc_rd  = rd_pc;

    assign busy = (st != ST_IDLE) | (ad_level != 5'd0);

    // ★注意★ ST_IDLE 起块那一拍 rd_cam 也有效, 但那一拍的 cam_word 还是
    // 标签字(bit16=1), 根本不是像素。所以数据通路不能用 rd_cam 当"有效像素",
    // 必须用下面这个只覆盖真正像素拍的信号, 否则每块第一个像素都会变成
    // 那个 0x1xxxx 的标签值 —— 屏幕上就是每 512 像素冒一个亮点。
    wire px_valid = (st == ST_RUN) & (pcnt < CHUNK);

    //------------------------------------------------------------------
    // 档位锁存: 只在翻页那一刻采信
    //------------------------------------------------------------------
    // 如果直接用 mode_sel, 用户恰好在写一页写到一半时按下按钮, 这一页就会
    // 上半截灰度下半截二值, 翻页后屏幕上能看到一条很明显的分界线。
    // 锁存到 do_flip 之后, 切换点永远落在页边界上, 最多晚 1 帧生效(约 45ms)。
    reg [2:0] mode_lat;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            mode_lat <= M_COLOR;
        else if (do_flip)
            mode_lat <= mode_sel;
    end

    //------------------------------------------------------------------
    // 第 0 级(纯组合): RGB565 拆成 8bit + 亮度 Y + 色度 Cb/Cr
    //------------------------------------------------------------------
    // 放写通路的原因:
    //   写: 每个像素只经过一次 (摄像头 22fps + PC 24fps, 约 8.6M px/s)
    //   读: 屏幕 60Hz 全屏反复读, 37M px/s
    // 而且四格在这里汇合, 一处改动四格全变, 读通路一行都不用碰。
    //
    // 同一时刻只有一路在搬(src 二选一), 所以只需要一组运算。
    //------------------------------------------------------------------
    wire [15:0] px_in = (src == 1'b0) ? cam_word[15:0] : pc_word[15:0];

    // 5/6/5 直接左移 3 位只能到 248, 白会变暗; 必须用 {R5, R5[4:2]} 才能到 255。
    //   ★补的是"该通道自身的高位", 位段要跟着通道走★
    //   R5 在 px_in[15:11] -> 高位是 R5[4:2], 即 px_in[15:13]
    //   G6 在 px_in[10:5]  -> 高位是 G6[5:4], 即 px_in[10:9]
    //   B5 在 px_in[4:0]   -> 高位是 B5[4:2], 即 px_in[4:2]
    //   原来 R/G 两行误取成 px_in[13:11] / px_in[6:5] —— 那是通道的低位,
    //   等于把像素的原始低位又贴到了高位上, 颜色越深偏得越多。这种错
    //   只测 0xFFFF / 纯色几个点看不出来(纯色的低位刚好凑巧), 全值域
    //   一跑 65536 个码就有 16869 个对不上。
    wire [7:0]  c_r = {px_in[15:11], px_in[15:13]};
    wire [7:0]  c_g = {px_in[10:5],  px_in[10:9] };
    wire [7:0]  c_b = {px_in[4:0],   px_in[4:2] };

    // Y = 0.299R + 0.587G + 0.114B, 乘 256 取整 -> (77, 150, 29)
    // 三者相加正好 256, 所以纯白算出来还是 255, 不会整屏发闷。
    // 最大 256*255 = 65280 < 65536, 16bit 不溢出。
    wire [15:0] y_sum = ({8'd0, c_r} * 16'd77)
                      + ({8'd0, c_g} * 16'd150)
                      + ({8'd0, c_b} * 16'd29);
    wire [7:0]  y_val = y_sum[15:8];

    // ---- Cb / Cr ----
    // 标准公式做定点会出负数, 负数在无符号减法里会绕回, 综合器重排运算
    // 顺序时哪一步先算是不确定的, 很容易埋一个只在特定颜色出现的坑。
    // 所以这里改成"差值 + 偏置", 全程无符号, 中间值永远为正:
    //
    //   Cb = 128 + (B - Y) * 144/256        (144/256 = 0.5625, 标准值是 0.5641)
    //   Cr = 128 + (R - Y) * 182/256        (182/256 = 0.7109, 标准值是 0.7130)
    //
    //   bm = B - Y + 256       范围 [1, 511], 10bit 装得下且不会负
    //   cb_acc = bm * 144 + 61440
    //          = 65536 + 32768 + (B-Y)*144
    //   取 cb_acc[15:8] 时, 65536+32768 里的 384 截成低 8 位正好是 128,
    //   于是 cb_acc[15:8] 就是 Cb。61440 = 65536 - 256*144。
    //   cr_acc 同理, 51712 = 65536 - 256*182。
    wire [9:0]  bm = {1'b0, c_b} + 10'd256 - {1'b0, y_val};
    wire [9:0]  rm = {1'b0, c_r} + 10'd256 - {1'b0, y_val};

    wire [17:0] cb_acc = {8'd0, bm} * 18'd144 + 18'd61440;
    wire [17:0] cr_acc = {8'd0, rm} * 18'd182 + 18'd51712;
    wire [7:0]  cb_val = cb_acc[15:8];
    wire [7:0]  cr_val = cr_acc[15:8];

    //------------------------------------------------------------------
    // 1x3 中值 (去噪)
    //------------------------------------------------------------------
    // 为什么只做水平, 不做 3x3:
    //   3x3 要缓存上一整行, 但写通路的块是按"谁来谁先搬"交错的 ——
    //   摄像头和 PC 交替, 块号也不是顺序到达, 想拼齐"上一行"就得加一套
    //   512x16 的行缓存 + 块号比对 + 跨格边界保护, 复杂度翻几倍。
    //   1x3 只需要 2 个 8bit 寄存器, 对传感器噪声和行方向条纹足够有效,
    //   而且它天然不会跨块污染(块首把历史清零即可)。
    //
    // m2 是前前一个, m1 是前一个, y_val 是当前, 三点取中值:
    //   lo = min(m1, y), hi = max(m1, y)
    //   med = clamp(m2, lo, hi)
    reg  [7:0] m1, m2;
    wire [7:0] m_lo = (y_val < m1) ? y_val : m1;
    wire [7:0] m_hi = (y_val < m1) ? m1    : y_val;
    wire [7:0] m_med = (m_hi < m2) ? m_hi
                     : ((m_lo < m2) ? m2 : m_lo);

    // 块首两个像素没有"前一个", 直接透传。硬要拿上一块最后一个像素当
    // 邻居的话, 每 512 像素的交界处会被拉黑或拉亮, 屏幕上是一条竖着的
    // 麻花。透传两个像素看不出来(512 里的 2 个)。
    wire [7:0] med_val = (pcnt <= 10'd1) ? y_val : m_med;

    //------------------------------------------------------------------
    // 自适应二值化阈值
    //------------------------------------------------------------------
    // 用最亮/最暗的中点 (min+max)/2, 不用平均值: 平均值要除以像素数,
    // 硬件除法很贵; min/max 只要比较器, 而且对"暗背景 + 亮目标"这种
    // 识别场景效果更好(平均法会被大片背景压得偏低, 目标整个变白)。
    //
    // 摄像头格和 PC 三格分开统计: 摄像头格是真实光照, PC 视频是压缩过的,
    // 两者亮度分布差很多, 共用一个阈值必然一边全黑或全白。
    // 而 PC 三格画面内容相同, 共用一套统计就够, src 一位就能区分。
    //
    // 用上一帧的统计结果处理当前帧(延迟 1 帧, 45ms), 画面不会突变, 无感。
    reg [7:0] cam_ymin, cam_ymax, pc_ymin, pc_ymax;
    reg [7:0] thr_cam,  thr_pc;

    wire [7:0] thr_now = (src == 1'b0) ? thr_cam : thr_pc;

    //------------------------------------------------------------------
    // 第 1 级流水线: 寄存上面的组合结果
    //------------------------------------------------------------------
    // 为什么必须打拍:
    //   第 0 级是 3 个 8x8 乘法 + 2 个 8x8 乘法 + 加法树 + 中值比较网络,
    //   50MHz 只有 20ns, 全塞进一拍太勉强。寄存后:
    //     第 0 级 = 乘法 + 中值  (约 10ns)
    //     第 1 级 = 比较/选择/拼位 (约 4ns)
    //   两边都很松, 时序不用赌。
    reg [15:0] q_px;         // 原始彩色
    reg [7:0]  q_y;          // 未滤波亮度
    reg [7:0]  q_med;        // 中值滤波后的亮度
    reg [7:0]  q_cb, q_cr;   // 色度

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            q_px  <= 16'd0;
            q_y   <= 8'd0;
            q_med <= 8'd0;
            q_cb  <= 8'd128;
            q_cr  <= 8'd128;
            m1    <= 8'd0;
            m2    <= 8'd0;
        end else if (px_valid) begin
            q_px  <= px_in;
            q_y   <= y_val;
            q_med <= med_val;
            q_cb  <= cb_val;
            q_cr  <= cr_val;
            // 块首把历史堵成自己, 让 m_med 在 pcnt=0/1 时也是自己,
            // 这样即使透传窗口没盖住也不会串味到上一块。
            if (pcnt == 10'd0) begin
                m1 <= y_val;
                m2 <= y_val;
            end else begin
                m1 <= y_val;
                m2 <= m1;
            end
        end
    end

    //------------------------------------------------------------------
    // 第 1 级(组合): 按档位选出最终落盘的 RGB565
    //------------------------------------------------------------------
    wire [15:0] o_color  = q_px;
    wire [15:0] o_gray   = {q_y[7:3],   q_y[7:2],   q_y[7:3]};
    wire [15:0] o_denois = {q_med[7:3], q_med[7:2], q_med[7:3]};
    wire [15:0] o_binary = (q_med >= thr_now) ? 16'hFFFF : 16'h0000;
    // YCbCr 伪彩: Y 当红, Cb 当绿, Cr 当蓝。中性灰时 Cb=Cr=128, 显示成
    // 偏青的灰; 肤色区域 Cr 明显偏高, 屏幕上会跳出橙红色, 便于肉眼确认
    // "色度分量确实算对了", 后面做肤色分割也是同一套分量。
    wire [15:0] o_ycbcr  = {q_y[7:3], q_cb[7:2], q_cr[7:3]};

    reg [15:0] px_out;
    always @(*) begin
        case (mode_lat)
            M_GRAY   : px_out = o_gray;
            M_DENOIS : px_out = o_denois;
            M_BINARY : px_out = o_binary;
            M_YCBCR  : px_out = o_ycbcr;
            default  : px_out = o_color;
        endcase
    end

    //------------------------------------------------------------------
    // 红绿灯检测 + 画框 (v13)
    //------------------------------------------------------------------
    // 坐标还原:
    //   块号 dst = row*2 + half  (row 是**屏幕**行 0..599, half 是左右半屏)
    //   一格高 300 行, 所以格内行 = row>=300 ? row-300 : row
    //     右上格: half=1, row 0..299   -> 左上角那个摄像头格是 half=0, 不参与
    //     左下/右下: half=0/1, row 300..599
    //   块内像素序号 = pcnt (读) / pcnt-1 (写, 因为写比读晚一拍)
    //
    // 只拿右上格那 300 行做检测 —— 三格画面内容完全一样, 框可以直接复用,
    // 免得同一帧被统计三遍(命中数翻 3 倍, 阈值全得跟着改)。
    //------------------------------------------------------------------
    wire [10:0] blk_row = cur_dst[10:1];
    wire [8:0]  cur_row = (blk_row >= 11'd300) ? (blk_row - 11'd300)
                                              : blk_row[8:0];
    wire        cur_half = cur_dst[0];

    // ---- 送给检测模块的坐标 (v15 统一 10 位) ----
    //   四宫格 -> x = 块内偏移 0..511,  y = 格内行 0..299
    //   全屏   -> x = {左右半, 块内偏移} 0..1023, y = 屏幕行 0..599
    wire [9:0]  tl_px = full_scr ? {cur_half, pcnt[8:0]} : {1'b0, pcnt[8:0]};
    wire [9:0]  tl_py = full_scr ? {1'b0, blk_row}       : {1'b0, cur_row};

    // ---- 检测区 (v15 起, v37 加 y 门限) ----
    //   四宫格 -> 只检测右上格 (half=1, row<300)。三格画面内容完全一样, 框可以
    //             复用, 免得同一帧被统计三遍(命中数翻 3 倍, 阈值全得跟着改)。
    //   全屏   -> 整屏 1024x600 都参与, 框直接画在全屏上。
    //
    //   ★v37: 只扫上半屏★
    //     红绿灯挂在杆子上, 位置必然在画面上半部; 而最容易冒充红灯的是
    //     前车尾灯和湿路面上的红色倒影, 它们都在下半部。
    //     实测 红绿灯3.mp4: 真红灯和青绿箭头全部落在 y<=170, 而右侧那片
    //     尾灯反光在 y>200。切掉下半屏等于免费消掉一大类误检。
    //     全 8 个素材核过: 绿像素在 y<=170 内的占比 红绿灯3/5 是 100%,
    //     其余素材下方那些检出经确认是未点亮的灯珠和背景绿植。
    //
    //   四宫格一格 300 行(全屏 600 的 1/2 缩放), 所以 170 <-> 340 一一对应。
    localparam [9:0] TL_YMAX   = 10'd170,   // 四宫格: 格内行门限
                     TL_YMAX_F = 10'd340;   // 全屏:   屏幕行门限

    wire        tl_zone  = full_scr ? (tl_py <= TL_YMAX_F)
                                    : ((cur_half == 1'b1) && (blk_row < 11'd300)
                                                        && (tl_py <= TL_YMAX));

    // ★全屏一行是两块 512 拼起来的★ 只有 half=0 的块才算"行首"。
    //   不做这个限定的话, 每块都触发一次"换行", 跨屏幕中线的目标会被从
    //   中间切成两个 blob, 框变成半个。
    wire        tl_line = full_scr ? (cur_half == 1'b0) : 1'b1;

    // 新一帧的起点:
    //   四宫格 -> PC 第 0 行右半 = 块号 1 (左上格是摄像头, PC 不发这一块)
    //   全屏   -> 块号 0 (PC 发满 1200 块, 从第 0 行左半开始)
    //   ★v26: 定义已上移到 pc_have 那一块(闸门要用它), 这里不再重复声明★
    wire pc_start    = (st == ST_IDLE) & can_start & pc_have & ~cam_have & ~do_flip;
    wire tl_frame_st = pc_start & (pc_word[10:0] == tl_start_blk);

    // v17: 一帧最多 4 个框, 每个打包成 {y1, x1, y0, x0}
    wire [39:0] tl_xy0, tl_xy1, tl_xy2, tl_xy3;
    // ★v19: 这里必须是 3 位★ K_LEFT=4 用 2 位装不下, 截断后低 2 位正好是 0,
    //   表现就是"箭头框画出来了, 但框变白、没有文字", 而且编译/仿真都不报错。
    wire [2:0]  tl_bk0, tl_bk1, tl_bk2, tl_bk3;
    wire [3:0]  tl_bv;                 // 4 个框各自有效
    wire        tl_busy;

    traffic_light u_traffic_light(
        .clk         (clk                       ),
        .rst_n       (rst_n                     ),
        .full        (full_scr                  ),
        .px_en       (px_valid & (src == 1'b1) & tl_zone),
        .px_x        (tl_px                     ),
        .px_y        (tl_py                     ),
        .line_flag   (tl_line                   ),
        .px565       (px_in                     ),
        .frame_start (tl_frame_st               ),
        .bxy0        (tl_xy0                    ),
        .bxy1        (tl_xy1                    ),
        .bxy2        (tl_xy2                    ),
        .bxy3        (tl_xy3                    ),
        .bk0         (tl_bk0                    ),
        .bk1         (tl_bk1                    ),
        .bk2         (tl_bk2                    ),
        .bk3         (tl_bk3                    ),
        .bv          (tl_bv                     ),
        .busy        (tl_busy                   )
    );

    // 写第 k 个像素那一拍 pcnt = k+1, 所以坐标要减 1。
    // ★这里必须用 10 位的 pcnt 直接减★ pcnt 最大 512, 取 pcnt[8:0] 会变成 0,
    //   512-1 就下溢成 1023, 最后一个像素会跑到画面右边外面去。
    wire [9:0] wx_off = pcnt - 10'd1;                       // 块内偏移 0..511
    // 全屏的 x 是"半屏号 + 块内偏移", 拼成 0..1023
    wire [9:0] wx = full_scr ? {cur_half, wx_off[8:0]} : wx_off;
    wire [9:0] wy = full_scr ? {1'b0, blk_row}         : {1'b0, cur_row};

    //==================================================================
    // v34: 车道线检测 -> 决策 + OSD 叠加   (数据源 = PC 视频)
    //------------------------------------------------------------------
    // ★这是 v34 最大的一处改动★
    //   v31 把 lane_detect 挂在 cam_pclk 域的摄像头像素上, 结果经 lane_cdc
    //   过域送过来。但赛题要认的是"PC 发过来的那段视频", 而 PC 全屏时
    //   写通路只搬 PC 像素(src 恒 1), 摄像头一个像素都不在通路上 ——
    //   屏幕上当然什么都不会出现。
    //
    //   现在直接挂在写通路的像素流上, 同域同拍, CDC 整个删掉。
    //   PC 块流里坐标全都现成, 不用自己数:
    //     blk_row  行号 0..599        (块号 >> 1)
    //     cur_half 左半/右半          (块号 & 1)
    //     pcnt     块内像素序号
    //
    // 只在【PC 全屏】识别:
    //   四宫格里 PC 被抽成 512x300(一块 = 一格一行), 垂直分辨率减半,
    //   而且三格反复发同一幅图。全屏是 1024x600 原图, 精度最高, 也正是
    //   赛题演示的那一档。别的档干脆不开, 省得画出一堆假点。
    //==================================================================
    wire        lane_src_ok = (src == 1'b1) & full_scr;
    // ★v51: 检测流水常开, 开关只管"看不看得见"★
    //   v50 曾经把 px_en 和行首脉冲一起门控, 那是"真停检测"。现在按需求改成
    //   只关显示: 像素照进 lane_detect, 游程/跟踪/判型/变道决策全部照跑,
    //   LED 上的报警灯和车态灯继续反映真实状态, 只是 OSD 那层不画了。
    //   好处是重新打开的一瞬间画面就是对的, 不存在"要等几帧收敛"的空窗。
    wire        lane_px_en  = px_valid & lane_src_ok;
    // 行首: 全屏时 half=0 的块才是"左半", 取它块内第 0 拍作行首
    //   (那一拍 px_valid 已经是 1, 但 wd_data 还没开始写, 正好当同步点)
    wire        lane_line   = full_scr & (cur_half == 1'b0) & (pcnt == 10'd0);

    wire [1:0]  ld_ltyp , ld_rtyp , ld_cdir, ld_offl;
    wire [10:0] ld_lpos , ld_rpos , ld_offv;
    wire [2:0]  ld_lstate;
    wire [87:0] ld_anch ;
    // v46: 列投影抽头
    wire        ld_pj_vld;
    wire [5:0]  ld_pj_bkt;
    wire [7:0]  ld_pj_g;

    lane_detect u_lane_detect(
        .clk      (clk                  ),
        .rst_n    (rst_n                ),
        .vsync    (tl_frame_st          ),   // 帧首块那一拍
        .px_en    (lane_px_en           ),
        .px565    (px_in                ),
        .line_st  (lane_line            ),
        .px_row   (blk_row[9:0]         ),   // 0..599
        .ltyp     (ld_ltyp              ),
        .rtyp     (ld_rtyp              ),
        .lpos     (ld_lpos              ),
        .rpos     (ld_rpos              ),
        .offv     (ld_offv              ),
        .offl     (ld_offl              ),
        .lstate   (ld_lstate            ),
        .cdir     (ld_cdir              ),
        .anch     (ld_anch              ),
        .proj_vld (ld_pj_vld            ),
        .proj_bkt (ld_pj_bkt            ),
        .proj_g   (ld_pj_g              )
    );

    // 结算脉冲: 帧首块后第 3 拍 —— lane_detect 是两段式, 结算在 vs_pulse
    //   那一拍写(非阻塞), 第 2 拍才看得见, 第 3 拍取最稳。
    reg [4:0] lane_fst_d;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) lane_fst_d <= 5'd0;
        else        lane_fst_d <= {lane_fst_d[3:0], tl_frame_st};
    end
    wire lane_vld_i = lane_fst_d[2] & ~lane_fst_d[3];

    wire [127:0] lane_bus_i = {18'd0,
                               ld_ltyp, ld_rtyp, ld_cdir,
                               ld_lstate, ld_offl, ld_offv,
                               ld_anch};

    wire [21:0] lane_st  = lane_bus_i[109:88];
    wire [1:0]  ln_ltyp   = lane_st[21:20];   // 左线 0 判不出 1 实线 2 虚线
    wire [1:0]  ln_rtyp   = lane_st[19:18];
    wire [1:0]  ln_cdir   = lane_st[17:16];   // 变道方向 1 右 2 左
    wire [2:0]  ln_lstate = lane_st[15:13];   // 0 居中 1 偏左 2 偏右 3 变道 7 无效
    wire [1:0]  ln_offl   = lane_st[12:11];   // {左有效, 右有效}
    wire [10:0] ln_offv   = lane_st[10:0];    // 车道中心 - 512 (11 位补码)
    wire [87:0] ln_anch   = lane_bus_i[87:0];  // 8 个锚点

    wire [3:0] lane_dec;
    wire [1:0] lane_lvl;
    wire [1:0] lane_cross;
    wire       lane_alarm;

    lane_decision u_lane_decision(
        .clk      (clk                      ),
        .rst_n    (rst_n                    ),
        .tick     (lane_vld_i               ),
        .ltyp     (ln_ltyp                  ),
        .rtyp     (ln_rtyp                  ),
        .offl     (ln_offl                  ),
        .offv     (ln_offv                  ),
        .lstate   (ln_lstate                ),
        .cdir     (ln_cdir                  ),
        // 红绿灯: 用 1 号框的结果, 没认出来就传 0(决策里当"无灯")
        .tl_kind  (tl_bv[0] ? tl_bk0 : 3'd0),
        // v39 模拟强制命令
        .force_go (force_go                 ),
        .force_l  (force_l                  ),
        .force_r  (force_r                  ),
        .dec      (lane_dec                 ),
        .lvl      (lane_lvl                 ),
        .lc_cross (lane_cross               ),
        .alarm    (lane_alarm               )
    );

    // v39: 报警灯直接送到顶层
    //   v51: 不再跟显示开关门控 —— 板上的 LED 属于"后台结果", 关掉屏幕显示
    //        不等于关掉报警。只有在【图层】总闸 lane_en 落下时才静音。
    assign alarm = lane_en & lane_alarm;

    //------------------------------------------------------------------
    // v45: 车辆行驶状态 (直行 / 左转 / 右转) —— 判据换人
    //
    //   v44 用的是"车道中心 offv 的每帧差分", 上板一直判直行。用真实视频帧
    //   跑 RTL 后发现原因: offv 在 14 / 36 / -120 / -123 之间乱跳, 单帧差分
    //   全是噪声。根源是 offv = (cur_l + cur_r)/2, 而 cur 是"本帧最后一次
    //   命中的位置" —— 任何一行跟错(路口斑马线、对面车灯、右侧路缘), 整帧
    //   的中心就被带跑 150 像素。
    //
    //   现在的判据只看【左线底部锚点】anch[43:33]:
    //     dx = 左线 x(t) - 左线 x(t-8)
    //     dx < 0 : 左线在画面里左移 -> 景物左移 -> 车向右转  -> 右转
    //     dx > 0 : 左线右移                                -> 左转
    //   为什么挑左线: 实测这两年素材里右线会在"车道右边线 / 路缘 / 对面
    //   导流线"之间来回锁, R@599 在 570/830/985 之间跳; 而左线是双黄线,
    //   L@599 在直道上稳在 263~273, 弯道上单向滑到 137, 干净得多。
    //
    //   为什么用 8 帧差分而不是 1 帧: 单帧位移只有 1~2 像素, 和噪声同量级;
    //   8 帧(约 0.33 s)累计 20~40 像素, 信噪比够。
    //------------------------------------------------------------------
    wire [1:0] drv_state_w;

    //------------------------------------------------------------------
    // v46: 列投影 —— 路口内唯一还看得见"车在往哪拐"的证据
    //------------------------------------------------------------------
    wire signed [4:0] pj_dx;
    wire              pj_dx_vld, pj_dx_conf;

    proj_shift u_proj_shift (
        .clk     (clk        ),
        .rst_n   (rst_n      ),
        .px_vld  (ld_pj_vld  ),
        .px_bkt  (ld_pj_bkt  ),
        .px_g    (ld_pj_g    ),
        .frm_end (lane_vld_i ),      // 帧首块后第 3 拍: 上一帧像素已全部流过
        .dx      (pj_dx      ),
        .dx_vld  (pj_dx_vld  ),
        .dx_conf (pj_dx_conf )
    );

    ego_state #(
        .DX_TH  (10'd24),          // 8 帧内左线横移 > 24 像素 = 在转向
        .ACC_TH (5'd12),           // 累积到 12 帧算转向(实测扫描: 12 是这组素材的最优)
        .ACC_HY (5'd4  ),          // 退出阈值 = ACC_TH-4, 防抖
        .LOCK_N (5'd12),           // 锚点连续 12 帧不变 = 锁死, 切投影
        .DTH_P  (4'd2 )            // 投影位移阈值 2 桶 = 32 像素
    ) u_ego_state (
        .clk      (clk           ),
        .rst_n    (rst_n         ),
        .tick     (lane_vld_i    ),
        .lane_x   (ln_anch[43:33]),   // 左线底部锚点 {valid, x}, 见 lane_detect
        .proj_dx  (pj_dx         ),
        .proj_vld (pj_dx_vld     ),
        .ego      (drv_state_w   )
    );

    //   v51: 保持原样送出去 —— 三个状态灯是板上的 LED, 不是屏幕上的东西,
    //        关掉 OSD 显示以后它们照样要如实反映车态。
    assign drv_state = drv_state_w;

    // ---- v34: 叠加画在【PC 像素】上, 而且只在 PC 全屏 ----
    //   坐标直接用 wx/wy(全屏 = 原图坐标 1024x600, 一个像素都不缩放),
    //   所以红点落在哪就是检测到的哪一列, 不再有"四宫格坐标减半"那套换算。
    //   lane_en=0 时整层关闭(按键2 切换), 画面恢复成纯显示效果。
    //   v51: lane_osd_en 是 PC 面板上的"显示开关" —— 只管这一层画不画,
    //        检测本身照跑(见上面 lane_px_en)。关掉后画面上红点/色块/文字全消失,
    //        但 lane_dec、锚点、LED 都在正常更新, 重新打开当帧即正确。
    wire        cam_osd = (src == 1'b1) & full_scr & lane_en & lane_osd_en;
    wire [9:0]  osd_x   = wx;
    wire [9:0]  osd_y   = wy;

    // 锚点是否落在当前像素上 (3x3 的点, 用 11 位比较避免 ±1 下溢)
    // ★函数里不声明局部 reg★ 全部写成表达式: 有些综合工具对 function 内部
    //   的局部变量支持不一致, 这个工程里其它函数(glyph/edge_hit)也都是纯表达式,
    //   保持一致最省事。
    function dot_hit;
        input [10:0] a;        // {有效, x[9:0]}  —— 原图坐标
        input [9:0]  ay;       // 该锚点的原图 y
        input        shr;      // 1 = 四宫格(坐标减半)
        input [9:0]  px, py;
        begin
            dot_hit = a[10] &&
                      (py == (shr ? {1'b0, ay[9:1]} : ay)) &&
                      (({1'b0, px} + 11'd1) >=
                       (shr ? {1'b0, a[9:1]} : {1'b0, a[9:0]})) &&
                      ({1'b0, px} <=
                       ((shr ? {1'b0, a[9:1]} : {1'b0, a[9:0]}) + 11'd1));
        end
    endfunction

    // v34: 只在全屏画, 坐标不缩(原来四宫格要减半, 现在那套不用了)
    wire shr = 1'b0;
    wire d0 = dot_hit(ln_anch[10:0],  10'd420, shr, osd_x, osd_y);
    wire d1 = dot_hit(ln_anch[21:11], 10'd480, shr, osd_x, osd_y);
    wire d2 = dot_hit(ln_anch[32:22], 10'd540, shr, osd_x, osd_y);
    wire d3 = dot_hit(ln_anch[43:33], 10'd599, shr, osd_x, osd_y);
    wire d4 = dot_hit(ln_anch[54:44], 10'd420, shr, osd_x, osd_y);
    wire d5 = dot_hit(ln_anch[65:55], 10'd480, shr, osd_x, osd_y);
    wire d6 = dot_hit(ln_anch[76:66], 10'd540, shr, osd_x, osd_y);
    wire d7 = dot_hit(ln_anch[87:77], 10'd599, shr, osd_x, osd_y);
    wire lane_dot = cam_osd & (d0 | d1 | d2 | d3 | d4 | d5 | d6 | d7);

    // ---- 三个 12x12 状态块 (左上角), 演示时一眼能看出"能不能变道" ----
    // ★v36: 语义从"线型"改成"能不能变道"★
    //   原来块 0/1 报的是"实线/虚线", 得自己换算成"能不能变" —— 演示时要解释
    //   半天。现在直接报结论: 绿=可以变过去, 红=不行, 白=这条线判不出。
    //   块 0: 左线 -> 能不能向左变道   绿=能(虚线) 红=不能(实线) 白=判不出
    //   块 1: 右线 -> 能不能向右变道   同上
    //   块 2: 综合结论   青=能变(含左右都行) 红=都不能/红灯/丢线 黄=判不出
    wire blk_area = cam_osd & (osd_y >= 10'd4) & (osd_y <= 10'd15);
    wire b0 = blk_area & (osd_x >= 10'd4)  & (osd_x <= 10'd15);
    wire b1 = blk_area & (osd_x >= 10'd20) & (osd_x <= 10'd31);
    wire b2 = blk_area & (osd_x >= 10'd36) & (osd_x <= 10'd47);

    function [15:0] typ_col;                     // v36: 线型 -> 能不能变道
        input [1:0] t;
        begin
            typ_col = (t == 2'd1) ? 16'hF800 :    // 实线   红 = 不能变
                      (t == 2'd2) ? 16'h07E0 :    // 虚线   绿 = 可以变
                                    16'hFFFF;     // 判不出 白
        end
    endfunction

    //------------------------------------------------------------------
    // v49: LOST 并入 BOTH —— 左上角不再出现 "LOST" 这一类
    //------------------------------------------------------------------
    //   原来丢线单独报一格: 文字 "LOST" + 红块, 和 "NONE"(都不能变) 摆在
    //   一起时两个红块、两个四字母词, 演示时观众分不清哪个是"看不见"、
    //   哪个是"不让变"。
    //   现在把丢线并到"左右都能变"那一类: 文字 "BOTH"、颜色青。
    //   语义上说得通 —— 看不见线就不做限制, 左右都可以变。
    //
    //   ★只改显示层★
    //     lane_decision 内部的状态机、上报节奏 (LOST 快报 / 恢复慢报)、
    //     lstate、以及送出去给别的模块的 lane_dec 本体全部不动,
    //     仍然是 4'd7。这里只是在"取字形/取颜色/取词长"之前做一次
    //     4'd7 -> 4'd9 的映射, 后面三个函数共用 lane_dsp。
    //     这样以后想把丢线单独播出来, 删掉这一根 wire 就恢复了。
    wire [3:0] lane_dsp = (lane_dec == 4'd7) ? 4'd9 : lane_dec;

    function [15:0] dec_col;
        input [3:0] d;
        begin
            dec_col = (d == 4'd0) ? 16'h8410 :    // 保持       灰
                      (d == 4'd9) ? 16'h07FF :    // 左右都能变 青
                      (d == 4'd10)? 16'h07FF :    // 只能向左   青
                      (d == 4'd11)? 16'h07FF :    // 只能向右   青
                      (d == 4'd12)? 16'hF800 :    // 都不能     红
                      (d == 4'd2) ? 16'hF800 :    // 红灯       红
                      (d == 4'd7) ? 16'hF800 :    // 丢线 (v49 起不再命中)
                                    16'hFFE0;     // 其余       黄
        end
    endfunction

    wire        lane_blk     = b0 | b1 | b2;
    wire [15:0] lane_blk_col = b0 ? typ_col(ln_ltyp) :
                               b1 ? typ_col(ln_rtyp) : dec_col(lane_dsp);

    //------------------------------------------------------------------
    // v31: 决策文字 (左上角, 三个色块右边)
    //   把决策码直接写成英文, 演示时不用背色块含义。
    //   5x7 字模放大 2 倍: 字宽 10, 字高 14, 步进 12 —— 和红绿灯那套完全一致。
    //   字符编码沿用 glyph(): 0=S 1=T 2=O 3=P 4=G 5=W 6=A 7=I 8=L 9=E 10=F
    //   11=D 12=H 13=N 14=R (v31 新增)
    //------------------------------------------------------------------
    function [3:0] dchr;               // 决策码 + 第 i 个字符 -> 字符编码
        input [3:0] d;
        input [2:0] i;
        begin
            case (d)
                4'd0: dchr = (i == 3'd0) ? 4'd12 : (i == 3'd1) ? 4'd2 :
                              (i == 3'd2) ? 4'd8  : 4'd11;                    // HOLD
                4'd1: dchr = (i == 3'd0) ? 4'd4  : 4'd2;                      // GO
                4'd2: dchr = (i == 3'd0) ? 4'd0  : (i == 3'd1) ? 4'd1 :
                              (i == 3'd2) ? 4'd2  : 4'd3;                     // STOP
                4'd3: dchr = (i == 3'd0) ? 4'd8  : (i == 3'd1) ? 4'd6 :
                              (i == 3'd2) ? 4'd13 : 4'd9;                     // LANE
                4'd4: dchr = (i == 3'd0) ? 4'd0  : (i == 3'd1) ? 4'd2 :
                              (i == 3'd2) ? 4'd8  : (i == 3'd3) ? 4'd7 : 4'd11; // SOLID
                4'd5: dchr = (i == 3'd0) ? 4'd8  : (i == 3'd1) ? 4'd9 :
                              (i == 3'd2) ? 4'd10 : 4'd1;                     // LEFT
                4'd6: dchr = (i == 3'd0) ? 4'd14 : (i == 3'd1) ? 4'd7 :
                              (i == 3'd2) ? 4'd4  : (i == 3'd3) ? 4'd12 : 4'd1; // RIGHT
                4'd7: dchr = (i == 3'd0) ? 4'd8  : (i == 3'd1) ? 4'd2 :
                              (i == 3'd2) ? 4'd0  : 4'd1;                     // LOST
                // ---- v36: 变道许可四态 ----
                4'd9: dchr = (i == 3'd0) ? 4'd15 : (i == 3'd1) ? 4'd2 :
                              (i == 3'd2) ? 4'd1  : 4'd12;                    // BOTH
                4'd10: dchr = (i == 3'd0) ? 4'd8 : (i == 3'd1) ? 4'd9 :
                              (i == 3'd2) ? 4'd10 : 4'd1;                     // LEFT
                4'd11: dchr = (i == 3'd0) ? 4'd14 : (i == 3'd1) ? 4'd7 :
                              (i == 3'd2) ? 4'd4  : (i == 3'd3) ? 4'd12 : 4'd1; // RIGHT
                4'd12: dchr = (i == 3'd0) ? 4'd13 : (i == 3'd1) ? 4'd2 :
                              (i == 3'd2) ? 4'd13 : 4'd9;                     // NONE
                default: dchr = (i == 3'd0) ? 4'd5 : (i == 3'd1) ? 4'd6 :
                                (i == 3'd2) ? 4'd7 : 4'd1;                    // WAIT
            endcase
        end
    endfunction

    function [2:0] dlen;               // 这个词有几个字符
        input [3:0] d;
        begin
            dlen = (d == 4'd1) ? 3'd2 :
                   ((d == 4'd4) || (d == 4'd6) || (d == 4'd11)) ? 3'd5 : 3'd4;
        end
    endfunction

    wire [9:0] ltx  = 10'd56;
    wire [9:0] lty  = 10'd4;
    wire       lth  = cam_osd & (osd_x >= ltx) & (osd_x < (ltx + 10'd60)) &
                      (osd_y >= lty) & (osd_y <= (lty + 10'd13));
    wire [9:0] ltu  = osd_x - ltx;
    wire [9:0] ltv  = osd_y - lty;
    wire [9:0] ltu2 = {1'b0, ltu[9:1]};
    wire [2:0] ltv2 = ltv[3:1];        // 0..6
    wire [3:0] lci  = (ltu2 < 10'd6)  ? 4'd0 :
                      (ltu2 < 10'd12) ? 4'd1 :
                      (ltu2 < 10'd18) ? 4'd2 :
                      (ltu2 < 10'd24) ? 4'd3 : 4'd4;
    wire [9:0] ltbase = {6'd0, lci} * 10'd6;
    wire [3:0] ltcu   = ltu2 - ltbase;                       // 0..5, 5 是字间空隙
    wire [4:0] lt_row = glyph_all(dchr(lane_dsp, lci), ltv2);
    wire [2:0] ltcol  = (ltcu >= 10'd5) ? 3'd0 : (3'd4 - ltcu[2:0]);
    wire       lt_on  = lth && (lci < dlen(lane_dsp)) &&
                        (ltcu < 10'd5) && lt_row[ltcol];

    // 叠加输出: 锚点红点优先(调阈值全靠它), 其次决策文字, 最后状态块
    wire        lane_on  = lane_dot | lane_blk | lt_on;
    wire [15:0] lane_col = lane_dot ? 16'hF800 :
                           (lt_on ? dec_col(lane_dsp) : lane_blk_col);


    //==================================================================
    // v41: 摄像头帧率显示 (画面右上角)
    //------------------------------------------------------------------
    // 需求: 在摄像头画面右上角实时显示帧率 "FPS 22"。
    //
    // 坐标系要按档位分开算, 这是最容易踩空的一处:
    //   四宫格  : 摄像头被 cam_line_pick 抽成 512x300, 只占左上那一格,
    //             wx/wy 正好就是格内坐标(0..511 / 0..299), 直接能用。
    //   摄像头全屏: 1024x600 原样送, 一屏幕行是两块(左半 + 右半)拼起来的。
    //             此时 full_scr=0, 于是 wx 只剩块内偏移、wy 是"格内行"——
    //             直接拿它画会把字画到两半屏各自的 x=433 处, 屏幕上出现
    //             两个一样的框。所以这里必须自己拼: x={半屏, 块内偏移}。
    //
    // 模块 fps_osd 放在本文件末尾(和 lane_decision 一样), 单独一个 TB 能测,
    // 不用非得上板看。
    //==================================================================
    wire [9:0] fps_px = cam_full ? {cur_half, wx_off[8:0]} : wx_off;
    wire [9:0] fps_py = cam_full ? {1'b0, blk_row}         : {1'b0, cur_row};

    wire        fps_on;
    wire [15:0] fps_col;

    fps_osd u_fps_osd(
        .clk      (clk                    ),
        .rst_n    (rst_n                  ),
        .cam_vs   (cam_vs                 ),   // 摄像头场同步, 1 拍脉冲
        .cam_full (cam_full               ),
        .src      (src                    ),   // 只在摄像头像素上画
        .px_x     (fps_px                 ),
        .px_y     (fps_py                 ),
        .osd_on   (fps_on                 ),
        .osd_col  (fps_col                )
    );


    //------------------------------------------------------------------
    // 框叠加 (v17: 一帧最多 4 个框, 不再只画一个)
    //   每个框打包成 {y1, x1, y0, x0} 40 位, 这里拆成 4 组坐标逐个判边。
    //------------------------------------------------------------------
    wire [9:0] q0x0 = tl_xy0[ 9: 0];
    wire [9:0] q0y0 = tl_xy0[19:10];
    wire [9:0] q0x1 = tl_xy0[29:20];
    wire [9:0] q0y1 = tl_xy0[39:30];
    wire [9:0] q1x0 = tl_xy1[ 9: 0];
    wire [9:0] q1y0 = tl_xy1[19:10];
    wire [9:0] q1x1 = tl_xy1[29:20];
    wire [9:0] q1y1 = tl_xy1[39:30];
    wire [9:0] q2x0 = tl_xy2[ 9: 0];
    wire [9:0] q2y0 = tl_xy2[19:10];
    wire [9:0] q2x1 = tl_xy2[29:20];
    wire [9:0] q2y1 = tl_xy2[39:30];
    wire [9:0] q3x0 = tl_xy3[ 9: 0];
    wire [9:0] q3y0 = tl_xy3[19:10];
    wire [9:0] q3x1 = tl_xy3[29:20];
    wire [9:0] q3y1 = tl_xy3[39:30];

    // 这个像素落在框的四条边带上吗?
    // ★必须同时判 x 和 y 都在框内★ 只判 x 会画出一条横贯整屏的线 (v14 踩过)。
    // 加 2 而不是减 2: y0 可能小于 2, 直接减会下溢成大数。
    function edge_hit;
        input [9:0] x0, y0, x1, y1;
        input [9:0] px, py;
        begin
            edge_hit = (px >= x0) && (px <= x1) && (py >= y0) && (py <= y1) &&
                       ((py <= (y0 + 10'd2)) || ((py + 10'd2) >= y1) ||
                        (px <= (x0 + 10'd2)) || ((px + 10'd2) >= x1));
        end
    endfunction

    // 框色/文字色跟着灯色走: 红 -> 红, 绿 -> 绿, 黄 -> 黄, 判不出 -> 白。
    // 现场一眼就能看出"它认成了什么", 比清一色白框有用得多。
    // v19: 左箭头和普通绿灯一样用绿色 —— 区别只在文字 (LEFT / GO)
    function [15:0] kind_col;
        input [2:0] k;
        begin
            kind_col = (k == 3'd1) ? 16'hF800 :
                       (k == 3'd2) ? 16'h07E0 :
                       (k == 3'd3) ? 16'hFFE0 :
                       (k == 3'd4) ? 16'h07E0 : 16'hFFFF;
        end
    endfunction

    wire e0 = tl_bv[0] & edge_hit(q0x0, q0y0, q0x1, q0y1, wx, wy);
    wire e1 = tl_bv[1] & edge_hit(q1x0, q1y0, q1x1, q1y1, wx, wy);
    wire e2 = tl_bv[2] & edge_hit(q2x0, q2y0, q2x1, q2y1, wx, wy);
    wire e3 = tl_bv[3] & edge_hit(q3x0, q3y0, q3x1, q3y1, wx, wy);

    // 四个框理论上互不重叠; 万一挨在一起, 先编号小的那个赢, 颜色不至于乱闪
    reg [15:0] box_col;
    always @(*) begin
        box_col = 16'hFFFF;
        if (e0)      box_col = kind_col(tl_bk0);
        else if (e1) box_col = kind_col(tl_bk1);
        else if (e2) box_col = kind_col(tl_bk2);
        else if (e3) box_col = kind_col(tl_bk3);
    end
    wire draw_box = (src == 1'b1) & (e0 | e1 | e2 | e3);

    //------------------------------------------------------------------
    // 文字提示 (v16): 框上方显示 STOP / GO / WAIT
    //------------------------------------------------------------------
    // 5x7 点阵, 放大 2 倍 -> 字高 14, 字宽 10, 字符步进 12 (10 + 2 像素间隔)。
    // 为什么不用现成的字库 IP: 只有 8 个字母 (S T O P G W A I), 用纯组合的
    // case 比引一个 ROM 简单, 也不占 BRAM。
    //
    // 字符编码: 0=S 1=T 2=O 3=P 4=G 5=W 6=A 7=I 8=L 9=E 10=F
    // 词:  K_RED -> STOP(0 1 2 3)   K_GRN -> GO(4 2)   K_YEL -> WAIT(5 6 7 1)
    //      K_LEFT -> LEFT(8 9 10 1)  <- v19
    //------------------------------------------------------------------
    function [4:0] glyph;              // 返回某字符某一行的 5 位点阵
        input [3:0] ch;                // v19: 3 位 -> 4 位 (要装下 10)
        input [2:0] row;
        begin
            case (ch)
                3'd0: case (row)                    // S
                    3'd0: glyph = 5'h0E;  3'd1: glyph = 5'h10;
                    3'd2: glyph = 5'h10;  3'd3: glyph = 5'h0E;
                    3'd4: glyph = 5'h01;  3'd5: glyph = 5'h01;
                    default: glyph = 5'h0E;
                endcase
                3'd1: case (row)                    // T
                    3'd0: glyph = 5'h1F;
                    default: glyph = 5'h04;
                endcase
                3'd2: case (row)                    // O
                    3'd0: glyph = 5'h0E;  3'd1: glyph = 5'h11;
                    3'd2: glyph = 5'h11;  3'd3: glyph = 5'h11;
                    3'd4: glyph = 5'h11;  3'd5: glyph = 5'h11;
                    default: glyph = 5'h0E;
                endcase
                3'd3: case (row)                    // P
                    3'd0: glyph = 5'h1E;  3'd1: glyph = 5'h11;
                    3'd2: glyph = 5'h11;  3'd3: glyph = 5'h1E;
                    default: glyph = 5'h10;
                endcase
                3'd4: case (row)                    // G
                    3'd0: glyph = 5'h0E;  3'd1: glyph = 5'h11;
                    3'd2: glyph = 5'h10;  3'd3: glyph = 5'h17;
                    3'd4: glyph = 5'h11;  3'd5: glyph = 5'h11;
                    default: glyph = 5'h0E;
                endcase
                3'd5: case (row)                    // W
                    3'd0: glyph = 5'h11;  3'd1: glyph = 5'h11;
                    3'd2: glyph = 5'h11;  3'd3: glyph = 5'h15;
                    3'd4: glyph = 5'h15;  3'd5: glyph = 5'h1B;
                    default: glyph = 5'h11;
                endcase
                3'd6: case (row)                    // A
                    3'd0: glyph = 5'h0E;  3'd1: glyph = 5'h11;
                    3'd2: glyph = 5'h11;  3'd3: glyph = 5'h1F;
                    default: glyph = 5'h11;
                endcase
                default: case (row)                 // I
                    3'd0: glyph = 5'h1F;  3'd1: glyph = 5'h04;
                    3'd2: glyph = 5'h04;  3'd3: glyph = 5'h04;
                    3'd4: glyph = 5'h04;  3'd5: glyph = 5'h04;
                    default: glyph = 5'h1F;
                endcase
            endcase
        end
    endfunction

    // v19 新增的三个字母 (LEFT 用)。单独写一个函数再合并, 原因很实际:
    //   上面那个 case 里 I 是 default 分支, 直接往里塞 8/9/10 会把 I 顶掉,
    //   而 I 只出现在 WAIT 的最后一个字符上, 少了它 WAIT 会变成 "WAT".
    //   ★不是不能写 "3'd8, 3'd9:", 是不想让 default 失去意义★
    function [4:0] glyph2;
        input [3:0] ch;
        input [2:0] row;
        begin
            case (ch)
                4'd8: case (row)                    // L
                    3'd0: glyph2 = 5'h10;  3'd1: glyph2 = 5'h10;
                    3'd2: glyph2 = 5'h10;  3'd3: glyph2 = 5'h10;
                    3'd4: glyph2 = 5'h10;  3'd5: glyph2 = 5'h10;
                    default: glyph2 = 5'h1F;
                endcase
                4'd9: case (row)                    // E
                    3'd0: glyph2 = 5'h1F;  3'd1: glyph2 = 5'h10;
                    3'd2: glyph2 = 5'h10;  3'd3: glyph2 = 5'h1E;
                    3'd4: glyph2 = 5'h10;  3'd5: glyph2 = 5'h10;
                    default: glyph2 = 5'h1F;
                endcase
                default: case (row)                 // F
                    3'd0: glyph2 = 5'h1F;  3'd1: glyph2 = 5'h10;
                    3'd2: glyph2 = 5'h10;  3'd3: glyph2 = 5'h1E;
                    default: glyph2 = 5'h10;
                endcase
            endcase
        end
    endfunction

    function [4:0] glyph3;
        input [3:0] ch;
        input [2:0] row;
        begin
            case (ch)
                4'd11: case (row)                   // D
                    3'd0: glyph3 = 5'h1E;  3'd1: glyph3 = 5'h11;
                    3'd2: glyph3 = 5'h11;  3'd3: glyph3 = 5'h11;
                    3'd4: glyph3 = 5'h11;  3'd5: glyph3 = 5'h11;
                    default: glyph3 = 5'h1E;
                endcase
                4'd12: case (row)                   // H
                    3'd0: glyph3 = 5'h11;  3'd1: glyph3 = 5'h11;
                    3'd2: glyph3 = 5'h11;  3'd3: glyph3 = 5'h1F;
                    3'd4: glyph3 = 5'h11;  3'd5: glyph3 = 5'h11;
                    default: glyph3 = 5'h11;
                endcase
                4'd13: case (row)                   // N
                    3'd0: glyph3 = 5'h11;  3'd1: glyph3 = 5'h19;
                    3'd2: glyph3 = 5'h19;  3'd3: glyph3 = 5'h15;
                    3'd4: glyph3 = 5'h13;  3'd5: glyph3 = 5'h13;
                    default: glyph3 = 5'h11;
                endcase
                default: case (row)                 // R
                    3'd0: glyph3 = 5'h1E;  3'd1: glyph3 = 5'h11;
                    3'd2: glyph3 = 5'h11;  3'd3: glyph3 = 5'h1E;
                    3'd4: glyph3 = 5'h14;  3'd5: glyph3 = 5'h12;
                    default: glyph3 = 5'h11;
                endcase
            endcase
        end
    endfunction

    // v36: 再加一层放 B (显示 BOTH), 同理 glyph3 的 default 是 R。
    function [4:0] glyph4;
        input [3:0] ch;
        input [2:0] row;
        begin
            case (ch)
                default: case (row)                 // B
                    3'd0: glyph4 = 5'h1E;  3'd1: glyph4 = 5'h11;
                    3'd2: glyph4 = 5'h11;  3'd3: glyph4 = 5'h1E;
                    3'd4: glyph4 = 5'h11;  3'd5: glyph4 = 5'h11;
                    default: glyph4 = 5'h1E;
                endcase
            endcase
        end
    endfunction

    // 取字模: ch<=7 走老字库, 8..10 走 glyph2, 11..14 走 glyph3, 15 走 glyph4
    //   v31 新增 D/H/N/R 四个字母, 为了显示 HOLD/SOLID/LANE/RIGHT。
    //   ★为什么又开一个 glyph3 而不并进 glyph2★ glyph2 的 default 分支是 F,
    //   往里塞新字母会把 F 顶掉, 而 F 在 LEFT 里; 同理 glyph 的 default 是 I。
    //   每个函数只留一个 default, 加字母就再加一层, 逻辑最不容易错。
    function [4:0] glyph_all;
        input [3:0] ch;
        input [2:0] row;
        begin
            glyph_all = (ch >= 4'd15) ? glyph4(ch, row) :
                        (ch >= 4'd11) ? glyph3(ch, row) :
                        (ch >= 4'd8 ) ? glyph2(ch, row) : glyph(ch, row);
        end
    endfunction


    function [3:0] word_ch;            // 第 idx 个字符是哪个字母
        input [2:0] kind;
        input [1:0] idx;
        begin
            case (kind)
                3'd1: case (idx)                       // STOP
                    2'd0: word_ch = 4'd0;  2'd1: word_ch = 4'd1;
                    2'd2: word_ch = 4'd2;  default: word_ch = 4'd3;
                endcase
                3'd2: case (idx)                       // GO
                    2'd0: word_ch = 4'd4;  default: word_ch = 4'd2;
                endcase
                3'd3: case (idx)                       // WAIT
                    2'd0: word_ch = 4'd5;  2'd1: word_ch = 4'd6;
                    2'd2: word_ch = 4'd7;  default: word_ch = 4'd1;
                endcase
                default: case (idx)                    // LEFT (v19)
                    2'd0: word_ch = 4'd8;  2'd1: word_ch = 4'd9;
                    2'd2: word_ch = 4'd10; default: word_ch = 4'd1;
                endcase
            endcase
        end
    endfunction

    // 每个框各自有一块文字区。位置: 优先放框上方(留 3 像素空隙); 框离画面顶
    //   太近就放框下方, 否则贴到 y=0 边界会被裁掉一半, 看起来像"乱码"。
    //   GO 只有 2 个字符 = 24 像素, 其余 4 个 = 48 像素。
    wire [9:0] t0x = (q0x0 <= 10'd975) ? q0x0 : 10'd975;
    wire [9:0] t0y = (q0y0 >= 10'd20) ? (q0y0 - 10'd19) : (q0y1 + 10'd4);
    wire [9:0] t0w = (tl_bk0 == 3'd2) ? 10'd24 : 10'd48;   // 只有 GO 是 2 个字符
    wire [9:0] t1x = (q1x0 <= 10'd975) ? q1x0 : 10'd975;
    wire [9:0] t1y = (q1y0 >= 10'd20) ? (q1y0 - 10'd19) : (q1y1 + 10'd4);
    wire [9:0] t1w = (tl_bk1 == 3'd2) ? 10'd24 : 10'd48;   // 只有 GO 是 2 个字符
    wire [9:0] t2x = (q2x0 <= 10'd975) ? q2x0 : 10'd975;
    wire [9:0] t2y = (q2y0 >= 10'd20) ? (q2y0 - 10'd19) : (q2y1 + 10'd4);
    wire [9:0] t2w = (tl_bk2 == 3'd2) ? 10'd24 : 10'd48;   // 只有 GO 是 2 个字符
    wire [9:0] t3x = (q3x0 <= 10'd975) ? q3x0 : 10'd975;
    wire [9:0] t3y = (q3y0 >= 10'd20) ? (q3y0 - 10'd19) : (q3y1 + 10'd4);
    wire [9:0] t3w = (tl_bk3 == 3'd2) ? 10'd24 : 10'd48;   // 只有 GO 是 2 个字符

    wire h0 = tl_bv[0] && (wx >= t0x) && (wx < (t0x + t0w)) &&
              (wy >= t0y) && (wy <= (t0y + 10'd14));
    wire h1 = tl_bv[1] && (wx >= t1x) && (wx < (t1x + t1w)) &&
              (wy >= t1y) && (wy <= (t1y + 10'd14));
    wire h2 = tl_bv[2] && (wx >= t2x) && (wx < (t2x + t2w)) &&
              (wy >= t2y) && (wy <= (t2y + 10'd14));
    wire h3 = tl_bv[3] && (wx >= t3x) && (wx < (t3x + t3w)) &&
              (wy >= t3y) && (wy <= (t3y + 10'd14));

    // 命中哪个文字块就取哪个框的位置和颜色 —— 只保留一套字模取点逻辑,
    //   不然要例化 4 份 glyph(), 白占 LUT。
    reg [9:0] tx_s, ty_s;
    reg [2:0] tk_s;
    reg       hit_s;
    always @(*) begin
        tx_s  = t0x;
        ty_s  = t0y;
        tk_s  = tl_bk0;
        hit_s = h0;
        if (h1) begin tx_s = t1x; ty_s = t1y; tk_s = tl_bk1; hit_s = 1'b1; end
        if (h2) begin tx_s = t2x; ty_s = t2y; tk_s = tl_bk2; hit_s = 1'b1; end
        if (h3) begin tx_s = t3x; ty_s = t3y; tk_s = tl_bk3; hit_s = 1'b1; end
    end

    // 像素级取点: 坐标 -> 缩小 2 倍 -> (字符号, 列, 行) -> 字模某一位
    //
    // ★v19 修了横向放大 2 倍的老 bug★
    //   原来写的是 tci 按 12 分档、列索引取 tcu[3:1], 而 tcu 本身已经是
    //   "tu2 = tu>>1" 的单位 —— 等于横向缩了两次(共 4 倍), 纵向只缩了一次
    //   (tv2 = tv>>1, 2 倍)。结果字是 20x14 的扁字, 一个字符步进 24 像素,
    //   48 像素的文字区只塞得下 2 个字符: 板子上 STOP 一直显示成 "ST"、
    //   WAIT 显示成 "WA" (GO 只有 2 个字符, 所以看着是对的, 一直没人发现)。
    //   现在横向纵向统一 2 倍: 字宽 10, 字高 14, 步进 12, 和 pc/tl_preview.py
    //   的 draw_text() 完全一致。
    wire [9:0] tu   = wx - tx_s;        // 0..47
    wire [9:0] tv   = wy - ty_s;        // 0..13
    wire [9:0] tu2  = {1'b0, tu[9:1]};  // 0..23 (2 倍放大: 每 2 像素一格)
    wire [3:0] tv2  = tv[3:1];          // 0..6
    // 字符步进 6 格 (= 12 像素): 前 5 格是字身, 第 6 格留空
    wire [1:0] tci  = (tu2 < 10'd6)  ? 2'd0 :
                      (tu2 < 10'd12) ? 2'd1 :
                      (tu2 < 10'd18) ? 2'd2 : 2'd3;
    wire [9:0] tbase= {8'd0, tci} * 10'd6;    // 常数乘法, 综合成 tci*4 + tci*2
    wire [3:0] tcu  = tu2 - tbase;            // 0..5, 前 5 格是字, 第 6 格留空
    // ★不能写成 glyph(...)[idx]★ Verilog-2001 不允许对函数调用结果做位选
    //   (ModelSim: Illegal bit-select expression), 必须先落到一根 wire 上。
    wire [4:0] t_row = glyph_all(word_ch(tk_s, tci), tv2[2:0]);
    // tcu 可能等于 5, 这时 4-tcu 会下溢成越界索引 —— 先把列号钳到 0,
    // t_on 再被 (tcu < 5) 挡掉, 双保险。
    wire [2:0] tcol = (tcu >= 10'd5) ? 3'd0 : (3'd4 - tcu[2:0]);
    wire       t_on = (tcu < 10'd5) && t_row[tcol];

    // hit_s 之外 tu/tv 是下溢的大数, tcu<10 会把它挡掉, 不会画出杂点
    wire draw_txt = hit_s & t_on & (src == 1'b1);
    wire [15:0] txt_col = kind_col(tk_s);

    // 叠加优先级: 文字盖在框上(两者本来就很少重叠), 颜色各取自己的
    wire        draw_px  = draw_box | draw_txt;
    wire [15:0] px_over  = draw_txt ? txt_col : box_col;

    //------------------------------------------------------------------
    // 换页请求
    //   四宫格: 摄像头场同步到来时置起。摄像头是主节拍, 它一帧正好 300 行,
    //           所以 vsync 来的时候这一页刚好写完。
    //   全屏  : v28 起改成"帧末块写到了"驱动(见下面 pg_last), 不再用"块 0 到了"。
    //           ★不能继续用 cam_vs★ 全屏一帧是 1200 块 = 48ms, 而 cam_vs 是
    //           摄像头自己的 20~30fps (33~50ms), 两者不同步时 vsync 会在 PC
    //           帧写到一半时翻页 —— 屏幕上就是一条横贯的撕裂线。
    //------------------------------------------------------------------
    // v28: 下面这根线现在没人用了, 保留只为说明"块 0 到了"这个条件本身没错,
    //      错的是用它当翻页请求(它和"起一块"同拍, 块 0 必然先被写进上一页)。
    // wire pc_new_frame = (st == ST_IDLE) & can_start & pc_have & ~cam_have &
    //                     (pc_word[10:0] == tl_start_blk);

    //---- 全屏断流保底节拍 (v16) --------------------------------------
    // 全屏模式完全由 PC 数据驱动: PC 一停, 就再没有翻页请求, 画面定格在
    // 最后一页。这里在"连续 50ms 没等到任何 PC 块"之后, 按 20Hz 自己产生
    // 翻页请求, 作用有两条:
    //   1) 画面不会永久定格 —— 至少翻页动作在走, 不会给人"板子死了"的印象;
    //   2) 按键换档位能在下一帧生效(mode_lat 只在 do_flip 时采样), 否则
    //      全屏下按按键 1 是彻底没反应的。
    // 没有新数据时 page_dirty=0, 翻页不会真的切 buffer, 所以也不会闪黑。
    // ★v28: 这根节拍线还要过 pg_ready 那一关 —— 一页没写完照样不许翻。★
    reg [21:0] pc_starve;
    reg [19:0] beat_cnt;
    wire pc_block_in = (st == ST_IDLE) & can_start & pc_have & ~cam_have & ~do_flip;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            pc_starve <= 22'd0;
        else if (pc_block_in | flip_pend)
            // v29: 翻页挂起期间写侧本来就被 can_start 停住了, 这不是"PC 断流",
            //      计时器必须跟着清, 否则 beat_req 会被自己拱出来, 越等越乱。
            pc_starve <= 22'd0;
        else if (pc_starve != 22'd2_499_999)     // 2.5M / 50MHz = 50ms
            pc_starve <= pc_starve + 22'd1;
    end
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            beat_cnt <= 20'd0;
        else if (beat_cnt == 20'd124_999)        // 125k / 50MHz = 2.5ms -> 20Hz
            beat_cnt <= 20'd0;
        else
            beat_cnt <= beat_cnt + 20'd1;
    end
    wire pc_starved = full_scr & (pc_starve == 22'd2_499_999);
    wire beat_req   = pc_starved & (beat_cnt == 20'd124_999);

    //------------------------------------------------------------------
    // ★v28: 全屏的翻页请求改成"这一帧写完了"驱动, 不再用"下一帧的块 0 到了"★
    //   为什么必须换:
    //     原来用 pc_new_frame(队首是块 0)当翻页请求。这一拍和"起一块"是同一拍,
    //     而 do_flip 最快也要下一拍才可能成立(flip_pend 是寄存器) —— 于是块 0
    //     永远先被写进**上一页**, 新页从块 1 开始。一页少一块, 屏幕最上面
    //     那半行永远是旧内容; 再叠上"翻页被等地址排空拖后", 就成了现场看到的
    //     "顶部一条旧画面横带"。
    //   换成 pg_last 之后:
    //     帧末块 1199 一开始写, 翻页请求就置起; 等这 512 个像素搬完(513 拍)
    //     回到 ST_IDLE 才真正翻 —— 这时下一帧的块 0 还在队首、一个像素都没被
    //     消费, 新页从块 0 开始, 一页正好一帧。
    //   兜底三条(缺一条就可能冻屏):
    //     1) beat_req      : PC 彻底不发时的 20Hz 自走拍(换档/换模式要生效)
    //     2) pg_force      : 这一页 100ms 还没写完(丢了帧末包), 强制翻过去
    //     3) flip_timeout  : 地址 FIFO 一直排不空(见上面 v16 那段)
    //------------------------------------------------------------------
    wire pg_force = (pg_to == 24'd4_999_999);

    // & ~do_flip: 翻页那一拍把请求一起撤掉, 免得 pg_last 还挂着又触发第二次
    // (第二次 page_dirty=0 是空翻, 不会出错, 但会把 pc_align 又置起来, 白耽误
    //  一个块的时间)
    // v29: pc_next_frame 是"帧末包丢了"的逃生口 —— 见 pc_next_frame 那一段。
    //      没有它, 一次丢帧末包就是永久定格。
    // ★v35: 四宫格的翻页不再只等 cam_vs★
    //   原因(现场遥测 + 复现台 tb_quad_ovf): 一页 PC 只要 41.7ms 就写完了,
    //   而 cam_vs 是 45.45ms 才来一次 —— 中间 3.7ms 写侧一个块都不消费,
    //   PC FIFO 灌满, 后面到的包被整包丢掉, 丢的正好是下一帧的开头
    //   (右上格最上面那几十行), 于是切二值化后顶部永远压着一条彩色横带。
    //   改成"帧末块写到就翻 + cam_vs 兜底": 写侧一刻不停, FIFO 不再溢出。
    //   cam_vs 留着是因为 PC 断流时还得靠它把摄像头那格翻上去(pg_ready 会
    //   放行 pg_started=0 的纯摄像头页)。
    //   ★代价★ 翻页节拍从此跟着 PC 帧(41.7ms)走, 摄像头那格是 45.45ms 一帧,
    //   所以左上格最下面十几行会比本页晚一帧 —— 那是摄像头预览, 静止场景下
    //   根本看不出来; 换成"右上格顶部一条彩色横带"才是真问题。
    wire flip_req_pc = pg_last | pc_next_frame | beat_req | pg_force;
    wire flip_req    = (flip_req_pc | (~full_scr & cam_vs)) & ~do_flip;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            flip_pend <= 1'b0;
        else if (flip_req)
            flip_pend <= 1'b1;
        else if (do_flip)
            flip_pend <= 1'b0;
    end

    //------------------------------------------------------------------
    // v26: PC 帧闸门 —— 一页只放一整帧 PC 画面
    //   开闸: 翻页那一拍(do_flip)。关闸: 看到下一帧的首块(dst == tl_start_blk)。
    //   关闸期间 pc_have = 0, 写控制器不再消费 PC 字, PC 端的信用窗口
    //   (pc_fifo 积压超过 4096 字就等)会自然把它按住, 一帧都不会多发。
    //   兜底: 闸门关着超过 100ms 强制打开 —— 摄像头掉线(没有 cam_vs)时
    //   绝不能把 PC 饿死, 那种情况下宁可画面撕裂也要继续出图。
    //------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            full_d  <= 1'b0;
        end else begin
            full_d <= full_scr;
        end
    end
    wire mode_chg = full_scr ^ full_d;      // 全屏/四宫格 切换那一拍

    //------------------------------------------------------------------
    // v27: 翻页以后先对齐到"帧首块"
    //   现场(烧了 v26 之后)还剩一个现象: 右上格一大片画面不更新, 只有一条
    //   窄带在动。原因不是丢包 —— 是翻页那一刻 FIFO 队首还停在上一帧的后半段,
    //   新页就从"上一帧的尾巴"接着写, 前 880 块压根没被本帧覆盖, 屏幕上就是
    //   "整片旧画面 + 末尾一小条新的"。
    //   仿真读数(PC 比页慢 3%): 一页 880 块是最新帧、下一页只有 20 块, 两页交替。
    //   做法: 翻页后只认块号 == tl_start_blk 的块首, 前面的一律整块丢掉。
    //   这样每页的 PC 内容一定从画面顶部开始, 供不上时缺的是末尾(屏幕最底部)。
    //------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            pc_align <= 1'b0;
            align_to <= 23'd0;
        end else if (do_flip | mode_chg) begin
            pc_align <= 1'b1;               // 新的一页: 必须先见到帧首块
            align_to <= 23'd0;
        end else if (pc_blk_first & pc_is_start) begin
            pc_align <= 1'b0;               // 对上了, 后面正常写
            align_to <= 23'd0;
        end else if (pc_align) begin
            if (align_to == 23'd4_999_999) begin   // 100ms 还等不到就放弃
                pc_align <= 1'b0;                  // (PC 断流/换模式时不至于死等)
                align_to <= 23'd0;
            end else
                align_to <= align_to + 23'd1;
        end
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            pc_gate <= 1'b1;
            pc_seen <= 1'b0;
            gate_to <= 22'd0;
        end else if (do_flip | mode_chg) begin
            pc_gate <= 1'b1;                // 新的一页(或刚换模式), 开闸
            pc_seen <= 1'b0;
            gate_to <= 23'd0;
        end else if (pc_wrap) begin
            pc_gate <= 1'b0;                // 这一帧写完了, 关闸等翻页
            pc_seen <= 1'b0;
            gate_to <= 23'd0;
        end else if (pc_start) begin
            // ★必须用"真的起了一块"(pc_start) 来置位★
            //   用 pc_blk_first 会自锁: 那只是"队首是块首", 翻页后 pc_align 还要
            //   再等一拍才放开, 队首那块 dst=1 还在原地 —— 下一拍 pc_seen 已经
            //   是 1, 紧接着"帧首块到达"成立 -> 闸门立刻关死, 整页 PC 一块都
            //   没写。仿真里就是这样: 一页 874 块、下一页 0 块, 来回跳。
            pc_seen <= 1'b1;
            gate_to <= 23'd0;
        end else if (!pc_gate) begin
            if (gate_to == 23'd4_999_999) begin      // 100ms
                pc_gate <= 1'b1;
                gate_to <= 23'd0;
            end else
                gate_to <= gate_to + 23'd1;
        end
    end

    //------------------------------------------------------------------
    // 主状态机
    //------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            st           <= ST_IDLE;
            pcnt         <= 10'd0;
            src          <= 1'b0;
            cur_dst      <= 11'd0;
            ad_data      <= 28'd0;
            ad_wr        <= 1'b0;
            wr_page      <= 1'b0;
            wr_done_page <= 1'b0;
            page_dirty   <= 1'b0;
            wd_data      <= 16'd0;
            wd_en        <= 1'b0;
            cam_px       <= 32'd0;
            pc_px        <= 32'd0;
            chunk_cnt    <= 16'd0;
            cam_ymin     <= 8'hFF;
            cam_ymax     <= 8'h00;
            pc_ymin      <= 8'hFF;
            pc_ymax      <= 8'h00;
            thr_cam      <= 8'd128;
            thr_pc       <= 8'd128;
            drop_cnt     <= 10'd0;      // v27: 只能在这一个 always 块里赋值(PDS 不许两处)
            skip_pc      <= 1'b0;
            pg_started   <= 1'b0;       // v28: 这两个只能在本 always 块里赋值
            pg_last      <= 1'b0;
            pg_to        <= 24'd0;
            pg_pc_any    <= 1'b0;       // v29
            pg_cnt       <= 11'd0;      // v33
            pg_head_ok   <= 1'b1;       // v35
            bad_cnt      <= 3'd0;
        end else begin
            ad_wr <= 1'b0;
            wd_en <= 1'b0;

            // ---- v28: 本页"写完整"的计时 ----
            //   ★计的是"距上一个 PC 块进来多久", 不是"这一页开了多久"★
            //   按页计时的话, 一帧本来就要 42ms, 发送端抖 60ms 就超过 100ms,
            //   会误判成"丢包"强制翻页 —— 仿真里就是这么丢掉最后 49 块的
            //   (屏幕上变成底部 24 行是旧画面)。按"无进展"计时才对: 正常每
            //   35us 就有一个块进来, 计时永远回 0; 只有真的一个块都进不来才涨。
            if (do_flip | pc_start)
                pg_to <= 24'd0;
            else if (~pg_started | pg_last)
                pg_to <= 24'd0;
            else if (pg_to != 24'd4_999_999)
                pg_to <= pg_to + 24'd1;

            // 亮度统计: 只统计真的读进来的像素
            if (px_valid) begin
                if (src == 1'b0) begin
                    if (y_val < cam_ymin) cam_ymin <= y_val;
                    if (y_val > cam_ymax) cam_ymax <= y_val;
                end else begin
                    if (y_val < pc_ymin) pc_ymin <= y_val;
                    if (y_val > pc_ymax) pc_ymax <= y_val;
                end
            end

            case (st)
                ST_IDLE : begin
                    if (do_flip) begin
`ifdef DBG_PAGE
                        $display("PAGE t=%0t cnt=%0d started=%b last=%b pany=%b ok=%b dirty=%b camfull=%b",
                                 $time, pg_cnt, pg_started, pg_last, pg_pc_any,
                                 page_ok, page_dirty, cam_full);
`endif
                        // 翻页: 只在块边界, 且本页确实写过东西。
                        //   ★wr_done_page 才是"可以显示的那一页"★
                        //   读侧必须读"已经写满的页", 不能读写到一半的页,
                        //   否则屏幕上永远有一条随机的撕裂线。
                        // v28: 翻过去就是新的一页, 完整性标志一起清
                        pg_started <= 1'b0;
                        pg_last    <= 1'b0;
                        pg_pc_any  <= 1'b0;     // v29
                        pg_cnt     <= 11'd0;    // v33
                        pg_head_ok <= 1'b1;     // v35: 新的一页, 重新看起头
                        if (page_dirty) begin
                            // ★v29: 残页不上屏★ 详细理由见 page_ok 那一段。
                            //   注意 wr_page 照样翻转 —— 残页里那半截数据必须
                            //   扔进别的 buffer, 否则下一帧会接着往里写, 越积
                            //   越乱。只是"不告诉读侧可以读它"。
                            if (page_ok) begin
                                wr_done_page <= wr_page;
                                bad_cnt      <= 3'd0;
                            end else if (bad_cnt != 3'd7) begin
                                bad_cnt      <= bad_cnt + 3'd1;
                            end
                            wr_page      <= ~wr_page;
                            page_dirty   <= 1'b0;
                            // 本帧统计结算成下一帧要用的阈值
                            // (min+max) 两个 8bit 相加会溢出, 补一位
                            thr_cam <= ({1'b0, cam_ymin} + {1'b0, cam_ymax}) >> 1;
                            thr_pc  <= ({1'b0, pc_ymin } + {1'b0, pc_ymax }) >> 1;
                            cam_ymin <= 8'hFF;
                            cam_ymax <= 8'h00;
                            pc_ymin  <= 8'hFF;
                            pc_ymax  <= 8'h00;
                        end
                    end
                    else if (can_start & cam_badtag) begin
                        // 块首不是标签 -> 字流错位, 丢掉这一个字重新对齐
                        skip_pc <= 1'b0;
                        st      <= ST_SKIP;
                    end
                    else if (can_start & cam_have) begin
                        src     <= 1'b0;
                        ad_data <= {wr_page, 10'd0, cam_word[10:0], 6'd0};
                        ad_wr   <= 1'b1;
                        pcnt    <= 10'd0;
                        cur_dst <= cam_word[10:0];
                        st      <= ST_RUN;
                    end
                    else if (can_start & pc_badtag) begin
                        // v26: 和摄像头完全对称 —— PC 字流错位时也丢掉这个字。
                        //   没有这一条的话 PC 一旦错位就永久错位: 每个"块号"
                        //   读到的都是像素值, 垃圾块号撒满整屏(连摄像头那一格
                        //   都会被覆盖), 屏幕上就是一堆横条 + 几帧画面拼在一起。
                        skip_pc <= 1'b1;
                        st      <= ST_SKIP;
                    end
                    else if (pc_drain) begin
                        // v35: 等翻页期间边等边丢, 见 pc_drain 那一段。
                        //   错位字(非标签)只丢一个字, 整块才走 ST_DROP。
                        if (pc_is_tag) begin
                            st       <= ST_DROP;
                            drop_cnt <= 10'd512;
                        end else begin
                            skip_pc <= 1'b1;
                            st      <= ST_SKIP;
                        end
                    end
                    else if (can_start & pc_align & pc_avail & pc_is_tag
                             & ~pc_is_start) begin
                        // v27: 翻页后还没对上帧首 —— 这一块是上一帧的尾巴。
                        //   整块读走扔掉(标签在这条分支里一起丢), 不写 DDR。
                        st       <= ST_DROP;
                        drop_cnt <= 10'd512;
                    end
                    else if (can_start & pc_have) begin
                        src     <= 1'b1;
                        ad_data <= {wr_page, 10'd0, pc_word[10:0], 6'd0};
                        ad_wr   <= 1'b1;
                        pcnt    <= 10'd0;
                        cur_dst <= pc_word[10:0];
                        st      <= ST_RUN;
                        // ★v28: 记住"这一页的 PC 帧从帧首开始了 / 已经写到帧末了"★
                        //   翻页的第三个条件全靠这两位, 详见 pg_ready 那一段注释。
                        // ★v29: 再记一位"这一页有 PC 参与"★ 没有它的话,
                        //   "PC 从中间开始写"的残页会被误判成"纯摄像头页"放上屏幕。
                        // ★v35: pg_pc_any 这里是"写之前"的值, 为 0 就说明这是
                        //   本页的第一个 PC 块 —— 它必须正好是帧首块。
                        if (!pg_pc_any)
                            pg_head_ok <= (pc_word[10:0] == tl_start_blk);
                        pg_pc_any <= 1'b1;
                        pg_cnt    <= (pg_cnt == 11'd2047) ? 11'd2047 : pg_cnt + 11'd1;  // v33
                        if (pc_word[10:0] == tl_start_blk) pg_started <= 1'b1;
                        if (pc_word[10:0] == last_blk)     pg_last    <= 1'b1;
                    end
                end
                ST_RUN : begin
                    // 512 个像素已经在 FIFO 里(起块时按 513 字准入),
                    // 这里只管一拍一个搬过去, 不存在"等"
                    if (pcnt != 10'd0) begin
                        // 框和文字同色: 文字优先(框顶边可能穿过字的上半截)
                        // v31: 车道线叠加只对摄像头像素, 两者互斥(src 二选一)
                        // v41: 帧率只画在摄像头像素上, 和上面两层也互斥
                        wd_data <= draw_px ? px_over :
                                   fps_on   ? fps_col :
                                   (lane_on ? lane_col : px_out);
                        wd_en   <= 1'b1;
                        if (src == 1'b0) cam_px <= cam_px + 32'd1;
                        else             pc_px  <= pc_px  + 32'd1;
                    end
                    pcnt <= pcnt + 10'd1;
                    if (pcnt == CHUNK) begin
                        st         <= ST_IDLE;
                        page_dirty <= 1'b1;
                        chunk_cnt  <= chunk_cnt + 16'd1;
                    end
                end
                ST_SKIP : begin
                    // 只丢一个字, 下一拍回到 IDLE 重新看队首是不是标签
                    st <= ST_IDLE;
                end
                ST_DROP : begin
                    // v27: 把一整块(标签 + 512 像素)读走扔掉。
                    //   rd_pc 在这个状态常为 1, 每拍读走一个字; FIFO 空了就停住等,
                    //   所以不会误伤后面的块。
                    if (~pc_empty) begin
                        if (drop_cnt != 10'd0)
                            drop_cnt <= drop_cnt - 10'd1;
                        else
                            st <= ST_IDLE;      // 513 个字丢完, 重新看队首
                    end
                end
                default : st <= ST_IDLE;
            endcase
        end
    end

endmodule

//=====================================================================
// traffic_light   (Verilog-2001)   50MHz
//---------------------------------------------------------------------
// ★这个模块和 quad_wr_ctrl 放在同一个文件里★
//   PDS 的工程文件列表 (prj/eth_ddr_lcd.pds) 是写死的, 新增 .v 要在 GUI 里
//   Add File 才会参与编译。合成一个文件之后, 还是那一条 sync_src.bat。
//
// 作用: 在写 DDR 之前, 从 PC 那一路视频里找出"点亮着的信号灯", 给出矩形框
//       和它的颜色(红/绿)。
//
// ---- 算法演进 ----
// v13 行列投影: 换素材就崩 (框横跨 288 像素; 绿灯数学上不可能通过)
// v14 连通段(blob): 2D 结构, 灯和远处反光天然分开; 小目标也能成团
// v15 支援全屏 1024x600 (本次改动, 算法判据不变)
//
// ---- v15: 坐标扩到全屏, 判据保持 RGB ----
// (1) 全屏支援: 四宫格格子是 512x300, 全屏是 1024x600, 所以
//     - 坐标从 9 位扩到 10 位 (x 0..1023, y 0..599)
//     - 面积/计数从 18 位扩到 20 位 (全屏最多 614400 像素)
//     - 尺寸类参数分两套 (全屏目标约放大 2 倍, 面积是 4 倍)
//     - 新增 line_flag: 全屏一行是"两块 512"拼起来的, 如果每个块都当新行,
//       跨屏幕中线的目标会被切成两个 blob。line_flag 只在 half=0 的块为 1。
//
// (2) ★颜色判据试过换成 YCbCr 色差 (R-Y / B-Y), 实测失败, 已回退到 RGB★
//               RGB 判据        R-Y/B-Y 判据
//   红绿灯.mp4   79% 框宽46      52~100% (看阈值)
//   红绿灯3.mp4  100% 框宽21     78~96%
//   d.mp4(橘猫)  95% 误检        35~65%      <- 唯一改善项
//   b.mp4(无灯)  0%               0%
//   两个致命点:
//     a) B-Y 判绿会把黄绿叶判成绿灯。实测树叶 R=106 G=88 B=51 -> B-Y=218,
//        真绿 LED 是青绿色 R=50 G=114 B=98 -> B-Y=261, 树叶反而更低!
//        Cb 判绿的前提"绿光 B 低"在 LED 上根本不成立。
//     b) R-Y 判红确实能压橘猫 (真红灯中位 338, 橘猫中位 271), 但会连带把
//        "没点亮的暗红灯箱"挡掉 (红绿灯.mp4 的灯箱 R-Y 中位只有 302),
//        红绿灯3 也从 100% 掉到 78%。
//   结论: 纯颜色判据到极限了, 要压 d.mp4 那种误检只能加形状/纹理判据。
//
// ---- 四步流程 (不变) ----
//   第 1 步 颜色判据(组合): R-Y / B-Y 阈值 -> hit
//   第 2 步 行内分段: 连续命中算一段, 允许 GAP_MAX 个空洞(抗噪); 跨度>=RUN_MIN
//   第 3 步 活动表: 8 个槽, 相邻行 x 区间重叠的段并进同一个 blob;
//           超过 RGAP 行没有新段就"定稿", 参与比较
//   第 4 步 帧末选优: 和上一帧框重叠的优先(最高位), 其次比"很亮像素数", 再比面积
//
// 为什么用"很亮像素个数"而不是"平均亮度":
//   平均要除法, 硬件要么用乘法器要么算不了; 数 mx>=200 的像素个数效果一样
//   (灯是自发光, 漫反射的红色反光到不了 200), 而且纯加法计数。
//
// 为什么重叠要放最高位而不是加一个常数:
//   试过 sc = nb*1000 + area, 再给重叠的 +4096, 结果 nb 的量级直接把 4096
//   盖过去了, 框在"灯"和"尾灯反光"之间来回跳。改成 {ov, nb, area} 打包排序,
//   重叠一旦成立就绝对优先。
//
// 资源量级: 8 个槽 x (4x10 + 3x20) 约 1100 个触发器, 比较/加法约 900 LUT。
//=====================================================================
module traffic_light #(
    // ---------------- 颜色判据 (全屏/四宫格共用) ----------------
    // ★v15 试过换成 YCbCr 色差 (R-Y / B-Y), 实测失败已回退, 原因见文件头★
    parameter [7:0]  MX_R     = 8'd140,   // 红: R 自身下限
    parameter [7:0]  R_DIFF   = 8'd50,    // 红: R 比 G/B 各高出多少
    // ★v18: MX_G 从 150 降到 115★
    //   远处的绿灯/暗环境下的绿灯, G 分量只有 110~130 (实测暗绿灯 R=50 G=114
    //   B=98), 按 150 判等于"物理上永不可能被检出"—— 这不是阈值调优问题,
    //   是那个像素根本不满足 G>=150。所以下限必须降到 115。
    //   ★G_R 保持 25 不动★ 本来想靠"提高差值"来补误检, 但绿灯环本来就薄
    //   (灯芯过曝成白, 只剩外圈一圈), 实测环上的 G-R 常有 25~30, 提到 35
    //   会把本来能检出的绿环一起削掉 —— 那是把问题从"太严"改成"更严"。
    // ★v37: MX_G 115 -> 110★
    //   v18 把这里从 150 降到 115, 目标就是让暗绿灯 (50,114,98) 能检出,
    //   但 114 < 115 —— 差一个点, 那盏灯其实一直没进来。降到 110 才真正覆盖。
    //   代价实测很小: 红绿灯.mp4(背景全是树叶, 误检最多) 51850 -> 53682 (+3.5%),
    //   d.mp4(橘猫) 6887 -> 7064 (+2.6%), 而真灯多检出 6%。
    parameter [7:0]  MX_G     = 8'd110,   // 绿: G 自身下限
    parameter [7:0]  G_R      = 8'd25,    // 绿: G 比 R 高出多少 (绿LED过曝泛白, 不能要太高)
    // ★v20: 青绿(teal)容差, 默认关闭★
    //   现场 LED 有一部分是青绿而不是"纯绿 B 很低": 红绿灯2.mp4 夜里左转箭头
    //   最亮像素 (173,255,248) g-b 只有 7; 用户截图上向箭头 (136,244,232)
    //   g-b 中位数才 2。旧判据 (g>=b 且 g-b>=20) 下一个都过不了 —— 实测那块
    //   区域 1094 个亮像素, 判成绿的是 0 个。
    //
    //   ★但放宽会付两个真实代价, 所以默认 0 不启用★ (实测 tlf060 = 红绿灯3
    //   带绿色"03"倒计时那一帧):
    //     1) 倒计时点阵全变绿并连成 62x52, 面积是旁边真绿灯(47x33)的 2 倍多,
    //        按面积排序把真绿灯挤到第 7 位 —— 真灯没框了。
    //     2) 自行车图标那片 56x31 会被判成 LEFT。
    //   根因: 青绿这一段里同时装着"箭头/青绿灯"和"倒计时数字", 而两者
    //   R/B 中位数完全一样 (R=90, B=173~189), 颜色分不开; 18x18 的灯面上
    //   形状信息也不够。要真分开得用实拍素材重新标定。
    //   0   = 关闭 (= 旧判据)
    //   1~31 = 开启, 允许 B 比 G 高这么多
    //
    // ★v37: 打开, G_BT = 12★
    //   现场素材实测把"开了会误检一片"的担心推翻了:
    //     红绿灯2.mp4 : 绿灯现状 0 个像素 -> 开 12 后 1899
    //     红绿灯3.mp4 : 0 -> 2682
    //     红绿灯4.mp4 : 2 -> 1604
    //     红绿灯5.mp4 : 66 -> 2449
    //     b.mp4(无灯): 0 -> 0        ← 零误检, 这是最关键的一条
    //     d.mp4(橘猫): 6887 -> 7064  ← 只多 2.6%
    //
    //   ★为什么必须开 G_BT, 而不是只降 G_B★
    //     实测那盏青绿箭头最亮像素 (189,255,254) / (193,255,255), G 已经饱和,
    //     但 G-B = 0~1, 中位 0, 最小 -12。把 G_B 降到 0 都救不回来 —— 必须允许
    //     B 反超 G。这就是 v20 早就发现的事实, 当时不敢开。
    //
    //   ★为什么是 12 而不是 v20 试过的 24★
    //     v20 当初放到 b<=g+24, 才出现"倒计时点阵连成 62x52 抢走前 4 名"和
    //     "自行车图标判成 LEFT"。现在只要 12(刚好覆盖那个 -12 的最小值),
    //     8 个素材扫下来最大行内连续段只有 15 像素, 没有复现 62 像素的大块。
    //     再加上 v37 的"只扫上半屏 y<=170"和"排序改 y 优先", 下方那些干扰
    //     已经进不了列表前几位。
    parameter [7:0]  G_BT     = 8'd12,
    parameter [7:0]  G_B      = 8'd20,    // 绿: G 比 B 高出多少 (仅在 G_BT=0 时生效)
    // ---------------- 黄灯判据 (v16) ----------------
    // 琥珀色 LED 的特征是 "R 和 G 都亮、B 很暗", 和红/绿的区分点在 G 的绝对值:
    //   红: G 很低 (30~80)          -> MX_YG=140 挡住
    //   绿: R 很低 (40~70)          -> MX_YR=170 挡住
    //   黄: R>=170 且 G>=140 且 B<=110
    // 不能靠 R-G 的差值分: 黄灯 R-G 约 60, 和暗红灯箱几乎一样。
    parameter [7:0]  MX_YR    = 8'd170,   // 黄: R 下限
    parameter [7:0]  MX_YG    = 8'd140,   // 黄: G 下限
    parameter [7:0]  MX_YB    = 8'd110,   // 黄: B 上限
    parameter [7:0]  Y_RB     = 8'd90,    // 黄: R 比 B 高出多少
    parameter [7:0]  Y_GB     = 8'd70,    // 黄: G 比 B 高出多少
    parameter [7:0]  Y_RG     = 8'd90,    // 黄: |R-G| 上限 (超过就说明红/绿哪边偏了)
    parameter [7:0]  BRIGHT   = 8'd200,   // 单像素"很亮"门限, 计入 nb

    // ---- 灯芯"过曝白"并入: v18 试过两版, 都验证无效, 已全部回退 ----
    // 现象是真的: 交通灯灯芯是 LED 直射, 一定过曝成白。实测圆灯剖面是
    //   "左边 16px 绿弧 | 13px 灯框暗边 | 白点阵灯芯 | 右边绿弧"
    // 一行的左右两条绿弧相距 60+ 像素, 而合并容忍度只有 1, 理论上会被拆成两团。
    //
    // 但★实测框本来就是对的★ 圆灯实际范围约 100x57, 现框 91x44 已经盖住 90%,
    // 不存在"只套住一段弧"。真正把框撑大的做法(亮像素参与成段 + GAP_MAX 提到
    // 16)会把"09"倒计时牌也连成一个 144x81 的大误框, 得不偿失, 已回退。
    // 结论: 不要再往"白芯并入"上花时间, 收益抵不上误检。
    // ---------------- 四宫格参数 (一格 512x300) ----------------
    parameter [10:0] RUN_MIN  = 11'd4,    // 段最小跨度
    parameter [19:0] AREA_MIN = 20'd40,   // blob 面积下限
    parameter [19:0] NB_MIN   = 20'd15,   // "很亮"像素个数下限
    parameter [9:0]  MAX_W    = 10'd90,   // 框尺寸上限
    parameter [9:0]  MAX_H    = 10'd90,
    parameter [9:0]  MIN_DIM  = 10'd6,    // 宽高各自下限 (一条线不算框)
    // ---------------- 全屏参数 (1024x600, 目标约 2 倍, 面积 4 倍) ----------------
    parameter [10:0] RUN_MIN_F  = 11'd8,
    parameter [19:0] AREA_MIN_F = 20'd160,
    parameter [19:0] NB_MIN_F   = 20'd60,
    parameter [9:0]  MAX_W_F    = 10'd180,
    parameter [9:0]  MAX_H_F    = 10'd180,
    parameter [9:0]  MIN_DIM_F  = 10'd12,
    // ---------------- 段/blob 容忍 ----------------
    parameter [2:0]  GAP_MAX  = 3'd2,     // 段内允许的空洞
    parameter [2:0]  RGAP     = 3'd2,     // blob 允许断几行
    parameter [3:0]  HOLD_N   = 4'd5,     // 连续几帧没检到才熄灭
    // 一帧最多输出几个框。4 = 列表槽数 (改这个只影响"插入时用不用得上后几格",
    //   不改变列表宽度)。现场嫌背景小亮块太多可以调成 2 或 3 —— 但注意:
    //   调小之后"大红灯旁边的小绿灯"也会被挤掉, 这正是 v16 的老毛病,
    //   所以默认给 4。
    parameter [2:0]  MAX_OUT  = 3'd4
)(
    input  wire        clk         ,
    input  wire        rst_n       ,
    input  wire        full        ,   // 1=全屏 1024x600, 0=四宫格 512x300
    // ---- 像素流 ----
    input  wire        px_en       ,
    input  wire [9:0]  px_x        ,   // 列 0..1023
    input  wire [9:0]  px_y        ,   // 行 0..599
    input  wire        line_flag   ,   // 本块是不是"一整行的起始块"
    input  wire [15:0] px565       ,
    input  wire        frame_start ,
    // ---- 结果 (屏幕坐标, v17: 一帧最多 4 个框) ----
    // 每个框打包成 {y1, x1, y0, x0} 共 40 位; 四组端口 + 各自颜色 + 有效位。
    // ★为什么不是数组端口★ Verilog-2001 不允许数组做端口 (那是 SystemVerilog),
    //   所以只能拆成 4 组平铺端口, 或者打包成矢量。这里用"打包成矢量 + 显式
    //   解包"的折中: 端口数从 24 个降到 8 个, 解包在下面一行行写清楚。
    output reg  [39:0] bxy0        ,   // 0 号框 {y1[9:0], x1[9:0], y0[9:0], x0[9:0]}
    output reg  [39:0] bxy1        ,   // 1 号框
    output reg  [39:0] bxy2        ,   // 2 号框
    output reg  [39:0] bxy3        ,   // 3 号框
    // ★v19: 2 位 -> 3 位★ 多了 K_LEFT=4 (向左箭头), 2 位装不下
    output reg  [2:0]  bk0         ,   // 0 号框颜色: 1=红 2=绿 3=黄 4=绿左箭头 0=未知
    output reg  [2:0]  bk1         ,
    output reg  [2:0]  bk2         ,
    output reg  [2:0]  bk3         ,
    output reg  [3:0]  bv          ,   // 4 个框各自有效
    output wire        busy
);

    // 种类编码: 0=无 1=红 2=绿 3=黄 4=绿左箭头。画框/文字都直接按这个编码取色和词。
    localparam [2:0] K_NONE = 3'd0,
                     K_RED  = 3'd1,
                     K_GRN  = 3'd2,
                     K_YEL  = 3'd3,
                     K_LEFT = 3'd4;

    // 整帧都在统计, 没有"结算期", busy 恒为 0 (端口保留以免改例化)
    assign busy = 1'b0;

    //------------------------------------------------------------------
    // 参数按模式选择 (parameter 不能运行时改, 所以用 wire 过一道)
    //------------------------------------------------------------------
    wire [10:0] p_run_min = full ? RUN_MIN_F  : RUN_MIN;
    wire [19:0] p_area    = full ? AREA_MIN_F : AREA_MIN;
    wire [19:0] p_nb      = full ? NB_MIN_F   : NB_MIN;
    wire [9:0]  p_max_w   = full ? MAX_W_F    : MAX_W;
    wire [9:0]  p_max_h   = full ? MAX_H_F    : MAX_H;
    wire [9:0]  p_min_dim = full ? MIN_DIM_F  : MIN_DIM;

    //------------------------------------------------------------------
    // 第 1 步: 颜色判据 (纯组合)
    //------------------------------------------------------------------
    // 5/6/5 -> 8bit 用位复制, 和 quad_wr_ctrl 里一致 (不能 v<<3, 31->248 而非 255)
    wire [7:0] c_r = {px565[15:11], px565[15:13]};
    wire [7:0] c_g = {px565[10:5],  px565[10:9] };
    wire [7:0] c_b = {px565[4:0],   px565[4:2] };

    wire r_is_max = (c_r >= c_g) && (c_r >= c_b);
    // ★v20: 青绿模式把 "G 必须是最大通道" 放宽成 "B 比 G 最多高 G_BT"★
    //   默认 G_BT=0 时两个分支综合出来和旧代码等价, 不留行为差异。
    //   ★必须扩到 9 位再比★ c_g 最大 255, 8 位做 c_g + G_BT 会回绕成 23,
    //   那样最亮的绿灯反而不满足 —— 这种 bug 编译不报错, 只在上板时表现为
    //   "某盏灯特别亮就不认"。
    wire [8:0] g_b_lim = {1'b0, c_g} + {1'b0, G_BT};
    wire g_is_max = (c_g >  c_r) &&
                    ((G_BT == 8'd0) ? (c_g >= c_b) : ({1'b0, c_b} <= g_b_lim));

    // 黄灯先判, 并且让红/绿都把它排除掉。
    //   ★为什么必须"排除"而不是"靠差值硬分"★ 实测黄灯 (255,190,20) 的
    //   R-G = 65, 完全满足红的 R_DIFF=50, 不排除的话黄灯永远被认成红灯。
    //   而把 R_DIFF 拉到 90 去硬分又会误伤: 暗红灯箱(红绿灯.mp4 里那种没
    //   点亮的灯箱) R-G 只有 60 左右, 拉高就把真红灯一起挡掉了。
    //   所以走"互斥", 三条判据各管一段, 不重叠。
    wire [7:0] rg_abs = (c_r >= c_g) ? (c_r - c_g) : (c_g - c_r);
    wire is_yel = (c_r >= MX_YR) && (c_g >= MX_YG) && (c_b <= MX_YB) &&
                  ((c_r - c_b) >= Y_RB) && ((c_g - c_b) >= Y_GB) &&
                  (rg_abs <= Y_RG);

    // 先判"谁是最大"再减: 这时被减数一定不小于减数, 无符号减法不会下溢。
    wire is_red = r_is_max && (c_r >= MX_R) && ~is_yel &&
                  ((c_r - c_g) >= R_DIFF) && ((c_r - c_b) >= R_DIFF);
    wire is_grn = g_is_max && (c_g >= MX_G) && ~is_yel &&
                  ((c_g - c_r) >= G_R) &&
                  ((G_BT == 8'd0) ? ((c_g - c_b) >= G_B) : 1'b1);
    wire w_hit  = is_red | is_grn | is_yel;

    wire [7:0] c_mx = (c_r >= c_g) ? ((c_r >= c_b) ? c_r : c_b)
                                   : ((c_g >= c_b) ? c_g : c_b);
    wire       w_bright = (c_mx >= BRIGHT);

    //------------------------------------------------------------------
    // 第 2 步: 行内分段
    //------------------------------------------------------------------
    reg        in_run;
    reg [9:0]  run_x0, run_x1, run_y;
    reg [10:0] run_len, run_nb, run_red, run_yw;   // 一行最多 1024 像素, 要 11 位
    reg [2:0]  run_gap;

    // px_en 的上升沿 = 本块第一个有效像素。
    // ★不能用 px_x==0 判行首★ 第一拍的 px_x 是 1 不是 0 (px_en 在 pcnt=1
    //   才拉高), 用 px_x==0 会一次都判不到, 段就跨行粘在一起了。
    reg        px_en_d;
    wire       rising = px_en & ~px_en_d;

    // ★重写为独立的 line_first★ 原来直接拿 rising 当行首, 但全屏一行是
    //   两块 512 拼的, 每块都有 rising, 跨中线的目标会被从中间切开。
    //   line_flag 由外部给: 四宫格恒 1, 全屏只有 half=0 的块为 1。
    wire       line_first = rising & line_flag;

    // 段跨度 = 首末命中之间的距离 (含中间的空洞), 和模型的 en-st+1 一致。
    // ★不要用"命中个数"判 RUN_MIN★ 带 2 个空洞的 2 个命中, 跨度是 4, 模型
    //   认为成段, 命中数只有 2 会被判成噪声 —— 两边会走岔。
    wire [10:0] run_span = {1'b0, run_x1} - {1'b0, run_x0} + 11'd1;

    wire fire = px_en & in_run &
                ( line_first | (px_x == 10'd0) | ((~w_hit) & (run_gap >= GAP_MAX)) );

    //------------------------------------------------------------------
    // 第 3 步: 活动表 (8 个槽)
    //------------------------------------------------------------------
    reg [7:0]  sl_v;                 // 每个槽有效
    reg [9:0]  sl_x0 [0:7];
    reg [9:0]  sl_x1 [0:7];
    reg [9:0]  sl_y0 [0:7];
    reg [9:0]  sl_yl [0:7];          // y_last
    reg [19:0] sl_area[0:7];
    reg [19:0] sl_nb  [0:7];
    reg [19:0] sl_nrd [0:7];         // 红像素数
    reg [19:0] sl_nyw [0:7];         // 黄像素数 (v16)

    integer k;

    // 找槽: 先找"x 区间重叠"的槽合并, 没有就占一个空槽
    reg [2:0] m_idx;
    reg       m_found;
    reg [2:0] f_idx;
    reg       f_found;
    always @(*) begin
        m_found = 1'b0;
        m_idx   = 3'd0;
        f_found = 1'b0;
        f_idx   = 3'd0;
        for (k = 7; k >= 0; k = k - 1) begin
            if (sl_v[k] &&
                ((run_x1 + 10'd1) >= sl_x0[k]) &&
                ((sl_x1[k] + 10'd1) >= run_x0))
            begin
                m_found = 1'b1;
                m_idx   = k;
            end
            if (!sl_v[k]) begin
                f_found = 1'b1;
                f_idx   = k;
            end
        end
    end

    //------------------------------------------------------------------
    // 定稿比较
    //   每 8 个像素轮询一个槽 -> 8 个槽 64 个像素转一圈 (约 1/16 行)。
    //   为什么要轮询而不是每行查 8 个: 8 个槽的"分数比较"就是 8 个 41 位
    //   比较器, 一拍做完太费; 摊到一个像素周期里只做 1 个。
    //------------------------------------------------------------------
    // ★一开始写的是每 64 像素推进一个槽 (转一圈要 512 像素 = 整行)★ 结果
    //   blob 该定稿的时候还没轮到, 又多吃了两三行的段, 框比模型大 2~3 像素。
    reg [2:0] chk_div;
    reg [2:0] chk;
    wire      tick = px_en & (chk_div == 3'd0);

    wire [9:0] cs_w = sl_x1[chk] - sl_x0[chk] + 10'd1;
    wire [9:0] cs_h = sl_yl[chk] - sl_y0[chk] + 10'd1;
    // ★v17 去掉了"和上一帧框重叠"的加分★
    //   原来靠它做帧间保持, 但它是"绝对优先级"的最高位: 一旦某一帧锁上了
    //   红灯, 后面所有别的灯都挤不进这个唯一的位置 —— 这正是"画面里有多个
    //   灯却只框红灯"的直接原因。现在一帧保留 4 个框, 不再需要这个抢占机制,
    //   帧间稳定性由"按面积排序 + HOLD"来保证。
    wire        cs_ok = (sl_area[chk] >= p_area) && (sl_nb[chk] >= p_nb) &&
                        (cs_w <= p_max_w) && (cs_h <= p_max_h) &&
                        (cs_w >= p_min_dim) && (cs_h >= p_min_dim);

    // "绿"不单独计数: 红和黄互斥, 剩下的命中就都是绿。
    //   必须钳位 —— 三色判据虽然互斥, 但面积和计数的累加不在同一拍完成,
    //   极端情况下 nrd+nyw 会比 area 大 1, 无符号减法一绕就变成天文数字,
    //   三色投票会永远判绿。
    wire [19:0] cs_ngn = (sl_area[chk] >= (sl_nrd[chk] + sl_nyw[chk]))
                       ? (sl_area[chk] - sl_nrd[chk] - sl_nyw[chk]) : 20'd0;
    wire [2:0]  cs_kc  = ((sl_nrd[chk] >= sl_nyw[chk]) && (sl_nrd[chk] >= cs_ngn))
                       ? K_RED : ((sl_nyw[chk] >= cs_ngn) ? K_YEL : K_GRN);

    //------------------------------------------------------------------
    // v19: 向左箭头 (只对绿灯做, 红/黄箭头照旧 STOP / WAIT)
    //------------------------------------------------------------------
    // 判据只两条, 都是"比例", 所以全屏/四宫格共用一套, 不需要两套参数:
    //   1) w*10 >= h*14         宽高比 >= 1.4   (左箭头一定是横向的)
    //   2) 0.40 <= area/(w*h) <= 0.72           (实心但不饱满)
    // ★判据为什么是这两条、另外两条候选怎么被数据否掉的, 全写在
    //   pc/tl_blob.py 文件头的 ARW_* 注释里, 改之前先读那一段★
    //
    // 为什么还要填充率的下界 0.40: 四宫格实测漏进过一批 47x33 / ratio 1.45
    // 的"绿框", fill 只有 0.15~0.37 —— 那是绿灯外圈的一段弧加倒计时点阵,
    // 稀疏得像网格, 不是实心箭头。上界 0.72 则挡住"实心方块/圆盘"(0.78)。
    wire [19:0] cs_wh    = cs_w * cs_h;                       // 最大 1023*599 < 2^20
    wire [23:0] cs_ar100 = {4'd0, sl_area[chk]} * 24'd100;
    wire [23:0] cs_wh72  = {4'd0, cs_wh} * 24'd72;
    wire [23:0] cs_wh40  = {4'd0, cs_wh} * 24'd40;
    wire [15:0] cs_w10   = {6'd0, cs_w} * 16'd10;
    wire [15:0] cs_h14   = {6'd0, cs_h} * 16'd14;

    wire        cs_wide  = (cs_w10 >= cs_h14);
    wire        cs_dens  = (cs_ar100 <= cs_wh72) && (cs_ar100 >= cs_wh40);
    // ★升格只发生在绿灯上★ 红/黄箭头不参与, 保持原来的 STOP / WAIT 语义
    wire [2:0]  cs_kg    = ((cs_kc == K_GRN) && cs_wide && cs_dens) ? K_LEFT : cs_kc;

    //------------------------------------------------------------------
    // 输出框列表 (v17): 4 个槽, 按面积从大到小排好
    //   0 号永远是最大的那个 —— tb_tl 拿 0 号和黄金模型比, 这一条必须保持,
    //   否则"同一张图 RTL 和模型选出的团块不同"这种问题会天天冒出来。
    //------------------------------------------------------------------
    reg [9:0]  l_x0 [0:3];
    reg [9:0]  l_y0 [0:3];
    reg [9:0]  l_x1 [0:3];
    reg [9:0]  l_y1 [0:3];
    reg [19:0] l_area[0:3];
    reg [2:0]  l_kind[0:3];
    reg [3:0]  l_v;

    // 插到第几格: 第一个"空着"或"比新团块小"的位置 (列表是降序的,
    //   所以一旦某格比新团块小, 它后面只会更小)。
    //   MAX_OUT 是常数比较, 综合时直接优化掉, 不产生逻辑。
    //
    //   ★v37 试过改成"y 优先、32 行一档、档内比面积", 已回退★
    //     想法是: 红绿灯在画面上方, 前车尾灯在下方, 按 y 排天然偏向真灯。
    //     实测下来反而更糟 —— tb_tl 的 tlf060 帧里, 画面顶部有一个 16x9
    //     的小绿点(面积 144, 刚好过 AREA_MIN=40 和 MIN_DIM=6), 按 y 排序
    //     它直接抢走 0 号位, 把下方 48x33 的真绿灯挤到后面。
    //     而"按面积"这一版在这个帧上选的是真灯 —— 因为真灯的像素数本来就
    //     远多于误检的小点。
    //     另外决策已经不看红绿灯了(v37), 0 号槽现在没有消费者, 改排序
    //     只增加风险不产生收益。所以保持面积优先。
    wire ins0 = (~l_v[0]) | (sl_area[chk] > l_area[0]);
    wire ins1 = (MAX_OUT >= 3'd2) & ~ins0 &
                ((~l_v[1]) | (sl_area[chk] > l_area[1]));
    wire ins2 = (MAX_OUT >= 3'd3) & ~ins1 & ~ins0 &
                ((~l_v[2]) | (sl_area[chk] > l_area[2]));
    wire ins3 = (MAX_OUT >= 3'd4) & ~ins2 & ~ins1 & ~ins0 &
                ((~l_v[3]) | (sl_area[chk] > l_area[3]));
    wire ins_any = ins0 | ins1 | ins2 | ins3;
    wire ins01  = ins0 | ins1;
    wire ins012 = ins01 | ins2;

    // 新团块的内容 (定稿那一拍从槽里取)
    wire [9:0]  nw_x0 = sl_x0[chk];
    wire [9:0]  nw_y0 = sl_y0[chk];
    wire [9:0]  nw_x1 = sl_x1[chk];
    wire [9:0]  nw_y1 = sl_yl[chk];
    wire [19:0] nw_ar = sl_area[chk];

    // 定稿这一拍: 这个槽过期了、尺寸合格、而且列表里还塞得下
    wire cs_put = tick & ~fire & sl_v[chk] & (px_y > (sl_yl[chk] + 10'd2)) &
                  cs_ok & ins_any;

    reg [3:0]  miss;

    //------------------------------------------------------------------
    // 主流程: 所有对槽/段的写都在这一个 always 里
    //   ★一个 reg 只能有一个 always 驱动★ v13 就是因为 y0c 被两个块赋值,
    //   PDS 报 Verilog-04086 编译不过。
    //------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            in_run  <= 1'b0;
            run_x0  <= 10'd0;
            run_x1  <= 10'd0;
            run_y   <= 10'd0;
            run_len <= 11'd0;
            run_nb  <= 11'd0;
            run_red <= 11'd0;
            run_yw  <= 11'd0;
            run_gap <= 3'd0;
            px_en_d <= 1'b0;
            chk_div <= 3'd0;
            chk     <= 3'd0;
            bxy0    <= 40'd0;
            bxy1    <= 40'd0;
            bxy2    <= 40'd0;
            bxy3    <= 40'd0;
            bk0     <= K_NONE;
            bk1     <= K_NONE;
            bk2     <= K_NONE;
            bk3     <= K_NONE;
            bv      <= 4'd0;
            l_v     <= 4'd0;
            miss    <= 4'd0;
            sl_v    <= 8'd0;
            for (k = 0; k < 8; k = k + 1) begin
                sl_x0[k]  <= 10'd0;
                sl_x1[k]  <= 10'd0;
                sl_y0[k]  <= 10'd0;
                sl_yl[k]  <= 10'd0;
                sl_area[k]<= 20'd0;
                sl_nb[k]  <= 20'd0;
                sl_nrd[k] <= 20'd0;
                sl_nyw[k] <= 20'd0;
            end
            for (k = 0; k < 4; k = k + 1) begin
                l_x0 [k]  <= 10'd0;
                l_y0 [k]  <= 10'd0;
                l_x1 [k]  <= 10'd0;
                l_y1 [k]  <= 10'd0;
                l_area[k] <= 20'd0;
                l_kind[k] <= K_NONE;
            end
        end else if (frame_start) begin
            // ---- 帧边界: 把这一帧收到的框**全部**交出去, 然后清空 ----
            // ★这是 v17 的核心改动★ 原来这里只有一个 best_v, 一帧只结算
            //   一个赢家; 现在把整个列表原样交出去, 屏幕上所有灯都能框出来。
            if (l_v != 4'd0) begin
                bxy0 <= {l_y1[0], l_x1[0], l_y0[0], l_x0[0]};
                bxy1 <= {l_y1[1], l_x1[1], l_y0[1], l_x0[1]};
                bxy2 <= {l_y1[2], l_x1[2], l_y0[2], l_x0[2]};
                bxy3 <= {l_y1[3], l_x1[3], l_y0[3], l_x0[3]};
                bk0  <= l_kind[0];
                bk1  <= l_kind[1];
                bk2  <= l_kind[2];
                bk3  <= l_kind[3];
                bv   <= l_v;
                miss <= 4'd0;
            end else if ((bv != 4'd0) && (miss < HOLD_N)) begin
                // 这一帧一个都没检到, 沿用上一帧的框 (最多 HOLD_N 帧), 避免闪断
                miss  <= miss + 4'd1;
            end else begin
                bv    <= 4'd0;
                miss  <= 4'd0;
            end
            l_v      <= 4'd0;
            // 列表内容一起清掉。不清也不影响功能 (画框只看 l_v/bv), 但残留值
            // 会出现在插入的移位链上 —— 调试时"LIST area = 3111 3111"就是
            // 上一帧的残影, 会让人误以为同一个团块被插了两次。
            l_area[0]<= 20'd0;
            l_area[1]<= 20'd0;
            l_area[2]<= 20'd0;
            l_area[3]<= 20'd0;
            sl_v     <= 8'd0;
            in_run   <= 1'b0;
            run_gap  <= 3'd0;
            chk      <= 3'd0;
            chk_div  <= 3'd0;
        end else if (px_en) begin
            px_en_d <= 1'b1;

            // ---- 轮询下标 ----
            chk_div <= chk_div + 3'd1;
            if (tick) chk <= chk + 3'd1;

            // ---- 段结束: 交给活动表 ----
            // ★必须过滤短段★ 1~3 像素的短段如果也合并进去, 框会被零星亮边
            //   一点点撑大 (实测比模型大 2~3 像素)。
            if (fire & (run_span >= p_run_min)) begin
                if (m_found) begin
                    if (run_x0 < sl_x0[m_idx]) sl_x0[m_idx] <= run_x0;
                    if (run_x1 > sl_x1[m_idx]) sl_x1[m_idx] <= run_x1;
                    sl_yl[m_idx]   <= run_y;
                    sl_area[m_idx] <= sl_area[m_idx] + {9'd0, run_span};
                    sl_nb[m_idx]   <= sl_nb[m_idx]   + {9'd0, run_nb};
                    sl_nrd[m_idx]  <= sl_nrd[m_idx]  + {9'd0, run_red};
                    sl_nyw[m_idx]  <= sl_nyw[m_idx]  + {9'd0, run_yw};
                end else if (f_found) begin
                    sl_v[f_idx]   <= 1'b1;
                    sl_x0[f_idx]  <= run_x0;
                    sl_x1[f_idx]  <= run_x1;
                    sl_y0[f_idx]  <= run_y;
                    sl_yl[f_idx]  <= run_y;
                    sl_area[f_idx]<= {9'd0, run_span};
                    sl_nb[f_idx]  <= {9'd0, run_nb};
                    sl_nrd[f_idx] <= {9'd0, run_red};
                    sl_nyw[f_idx] <= {9'd0, run_yw};
                end
            end

            // ---- 过期检查 (和交段同拍时跳过, 让新数据先落地) ----
            if (tick && !fire) begin
                if (sl_v[chk] && (px_y > (sl_yl[chk] + 10'd2))) begin
                    // 定稿: 按面积插进 4 格列表, 后面的整体往后挪一格。
                    //   "插到第 p 格" 时: 第 p 格 <= 新团块, 第 p 之后的格 <= 前一格,
                    //   第 p 之前的格不变。写成一串三目, 不用 case 也不用数组搬移。
                    if (cs_put) begin
                        l_v[0]    <= 1'b1;
                        l_v[1]    <= ins0  ? l_v[0] : (ins1 ? 1'b1 : l_v[1]);
                        l_v[2]    <= ins01 ? l_v[1] : (ins2 ? 1'b1 : l_v[2]);
                        l_v[3]    <= ins012? l_v[2] : 1'b1;

                        l_x0[0]   <= ins0   ? nw_x0 : l_x0[0];
                        l_x0[1]   <= ins0   ? l_x0[0] : (ins1 ? nw_x0 : l_x0[1]);
                        l_x0[2]   <= ins01  ? l_x0[1] : (ins2 ? nw_x0 : l_x0[2]);
                        l_x0[3]   <= ins012 ? l_x0[2] : nw_x0;

                        l_y0[0]   <= ins0   ? nw_y0 : l_y0[0];
                        l_y0[1]   <= ins0   ? l_y0[0] : (ins1 ? nw_y0 : l_y0[1]);
                        l_y0[2]   <= ins01  ? l_y0[1] : (ins2 ? nw_y0 : l_y0[2]);
                        l_y0[3]   <= ins012 ? l_y0[2] : nw_y0;

                        l_x1[0]   <= ins0   ? nw_x1 : l_x1[0];
                        l_x1[1]   <= ins0   ? l_x1[0] : (ins1 ? nw_x1 : l_x1[1]);
                        l_x1[2]   <= ins01  ? l_x1[1] : (ins2 ? nw_x1 : l_x1[2]);
                        l_x1[3]   <= ins012 ? l_x1[2] : nw_x1;

                        l_y1[0]   <= ins0   ? nw_y1 : l_y1[0];
                        l_y1[1]   <= ins0   ? l_y1[0] : (ins1 ? nw_y1 : l_y1[1]);
                        l_y1[2]   <= ins01  ? l_y1[1] : (ins2 ? nw_y1 : l_y1[2]);
                        l_y1[3]   <= ins012 ? l_y1[2] : nw_y1;

                        l_area[0] <= ins0   ? nw_ar : l_area[0];
                        l_area[1] <= ins0   ? l_area[0] : (ins1 ? nw_ar : l_area[1]);
                        l_area[2] <= ins01  ? l_area[1] : (ins2 ? nw_ar : l_area[2]);
                        l_area[3] <= ins012 ? l_area[2] : nw_ar;

                        l_kind[0] <= ins0   ? cs_kg : l_kind[0];
                        l_kind[1] <= ins0   ? l_kind[0] : (ins1 ? cs_kg : l_kind[1]);
                        l_kind[2] <= ins01  ? l_kind[1] : (ins2 ? cs_kg : l_kind[2]);
                        l_kind[3] <= ins012 ? l_kind[2] : cs_kg;
                    end
                    sl_v[chk] <= 1'b0;
                end
            end

            // ---- 段的维护 ----
            if (w_hit) begin
                if (in_run && !fire && !line_first) begin
                    run_x1  <= px_x;
                    run_len <= run_len + 11'd1;
                    run_nb  <= run_nb  + {10'd0, w_bright};
                    run_red <= run_red + {10'd0, is_red};
                    run_yw  <= run_yw  + {10'd0, is_yel};
                    run_gap <= 3'd0;
                end else begin
                    in_run  <= 1'b1;
                    run_x0  <= px_x;
                    run_x1  <= px_x;
                    run_y   <= px_y;
                    run_len <= 11'd1;
                    run_nb  <= {10'd0, w_bright};
                    run_red <= {10'd0, is_red};
                    run_yw  <= {10'd0, is_yel};
                    run_gap <= 3'd0;
                end
            end else begin
                if (in_run && !fire)
                    run_gap <= run_gap + 3'd1;
                else if (fire)
                    in_run  <= 1'b0;
            end
        end else begin
            px_en_d <= 1'b0;
        end
    end

endmodule

//=====================================================================
//  lane_decision  (v31)  ——  并在本文件里, 因为它只被 quad_wr_ctrl 例化
//  这样所有写通路的回归测试台只要编 quad_wr_ctrl.v 就能跑, 不用带顶层。
//=====================================================================

module lane_decision #(
    parameter [7:0]   HOLD_FRM  = 8'd5,       // 连续几帧一致才生效
    parameter [2:0]   LOST_FRM  = 3'd3        // 连续几帧判不出就报丢失
    // ★v36 删掉了 DRIFT_TH★ 偏离(DRIFT_L/DRIFT_R)不再作为一个决策上报。
    //   原值 11'd120 (+-120 像素算偏出中心)。如果以后要恢复, 从这里加回来,
    //   判据是 |offv| > DRIFT_TH, 注意 offv 是补码要符号扩展。
)(
    input  wire        clk       ,
    input  wire        rst_n     ,
    input  wire        tick      ,   // 车道结果更新单拍脉冲(每帧一次)
    // ---- 车道检测结果 ----
    input  wire [1:0]  ltyp      ,   // 左线 0 判不出 1 实线 2 虚线
    input  wire [1:0]  rtyp      ,
    input  wire [1:0]  offl      ,   // {左有效, 右有效}
    input  wire [10:0] offv      ,   // 车道中心 - 512 (11 位补码)
    input  wire [2:0]  lstate    ,   // 0 居中 1 偏左 2 偏右 3 变道 7 无效
    input  wire [1:0]  cdir      ,   // 1 向右 2 向左
    // ---- 红绿灯 (来自 traffic_light 的 bk0, 0 表示没认出来) ----
    input  wire [2:0]  tl_kind   ,
    // ---- v39 模拟强制命令 (来自顶层按键 k2/k3/k4) ----
    //   直行 / 左变道 / 右变道, 三个同时最多一个有效(互斥, 顶层保证),
    //   全 0 = 不强制, 按真实检测结果决策。
    input  wire        force_go  ,   // 强制直行 (k2)
    input  wire        force_l   ,   // 强制左变道 (k3)
    input  wire        force_r   ,   // 强制右变道 (k4)
    // ---- 决策输出 ----
    output reg  [3:0]  dec       ,
    output reg  [1:0]  lvl       ,   // 0 正常 1 注意 2 危险
    output wire [1:0]  lc_cross  ,   // 变道时跨越的线: 0 无 1 左 2 右
    output reg         alarm         // v39 报警灯: 危险指令冲突时亮
);

    //------------------------------------------------------------------
    // 决策码
    //------------------------------------------------------------------
    localparam [3:0] DEC_HOLD    = 4'd0;   // 保持(复位初值, 正常运行不可达)
    localparam [3:0] DEC_STOP    = 4'd2;   // 红灯, 停车
    localparam [3:0] DEC_LOST    = 4'd7;   // 车道线丢失
    localparam [3:0] DEC_SLOW    = 4'd8;   // 线型判不出(不知道能不能变)
    // ---- v36: 变道许可四态, 取代原来的 GO / LC_OK / LC_BAD / DRIFT_L / DRIFT_R ----
    //   为什么要换: 原来那套是"变道**过程中**才报"的判定 —— 只有 lstate==3 (已经在
    //   变道) 才出 LANE/SOLID, 平时只报 GO。演示时看不出"现在到底能不能变"。
    //   现在改成**静态许可**, 每帧都按当前左右线型直接给结论, 不看有没有在变道。
    //   旧的 1/3/4/5/6 五个码不再产生, 但 dchr/dec_col 里的分支留着(永不命中),
    //   这样万一以后要回退, 显示层不用动。
    localparam [3:0] DEC_LC_BOTH = 4'd9;   // 左右都能变(两边都虚线)
    localparam [3:0] DEC_LC_L    = 4'd10;  // 只能向左(左虚右实)
    localparam [3:0] DEC_LC_R    = 4'd11;  // 只能向右(左实右虚)
    localparam [3:0] DEC_LC_NO   = 4'd12;  // 都不能变(两边都实线)

    //------------------------------------------------------------------
    // 输入整理
    //------------------------------------------------------------------
    wire lane_ok   = (lstate != 3'd7) & (offl != 2'b00);
    wire lc_active = (lstate == 3'd3);

    // 变道方向 -> 跨越的是哪条线
    //   向右变道: 车身越过右边的线; 向左变道: 越过左边的线。
    //   cdir 的定义见 lane_detect: 1=中心左移(车向右) 2=中心右移(车向左)。
    wire [1:0] cross_sel = lc_active ? ((cdir == 2'd1) ? 2'd2 : 2'd1) : 2'd0;
    assign lc_cross = cross_sel;

    // ---- v36: 变道许可的直接判据 ----
    //   ltyp/rtyp: 0=判不出 1=实线 2=虚线。虚线能变, 实线不能。
    //   ★两边任一条判不出就整帧不表态★ 只报一边的另一边是瞎猜, 宁可显示"判不出"。
    wire lc_l_ok  = (ltyp == 2'd2);
    wire lc_r_ok  = (rtyp == 2'd2);
    wire lc_known = (ltyp != 2'd0) & (rtyp != 2'd0);

    //------------------------------------------------------------------
    // 组合决策 (next)
    //   优先级: 丢线 > 判不出 > 四态许可
    //
    //   ★v37: 红灯不再参与决策★
    //     原来第二级是 `tl_kind == K_RED -> DEC_STOP`, 现在整条删掉。
    //     理由: 这一路的职责是"判断车辆在当前道路上能不能变道", 红灯该不该停
    //     是另一条独立的信息, 不该混进来。而且红绿灯检测本身有误检(前车尾灯、
    //     广告牌), 把它塞进决策等于让一个不可靠的输入去否决可靠的车道线结果:
    //     实测出现过"车道线清清楚楚, 却因为远处一块红色反光报 STOP"。
    //     红绿灯仍然独立识别、独立画框, 只是不再影响决策。
    //
    //   ★DEC_STOP 保留不动★ 它现在是不可达码(没有任何分支产生它)。
    //     保留的原因: dec_col() / dchr() 里的 STOP 分支还留着, 以后要恢复
    //     "红灯停车"只需在这里加回一行, 显示层不用动。
    //     tl_kind 端口也保留 —— 以后接左转箭头(K_LEFT)时还要用。
    //
    //   ★v39: 模拟强制命令 (顶层按键 k2/k3/k4)★
    //     强制命令优先于自动检测: 任一强制位有效就直接覆盖决策结果,
    //     不再看车道线判没判出来。用途是"演示/测试" —— 模拟给车下指令,
    //     看它在危险场景下会不会触发报警。
    //        force_go  -> DEC_LC_NO  直行 = 不变道 = 不能变道
    //        force_l   -> DEC_LC_L   只能向左
    //        force_r   -> DEC_LC_R   只能向右
    //     三个位由顶层保证互斥(同时按下只认优先级最高的一个)。
    //------------------------------------------------------------------
    // ★v40 报警灯判据 (重写)★
    //   原 v39 的写法是 (按键 & 线型) 直接相或, 结果有三颗键各自接了
    //   led[1]/led[2]/led[3] 当"当前处于哪个强制态"的指示 —— 于是现场看到
    //   的现象就是"不管什么情况, 一按键就亮", 跟实线虚线毫无关系。
    //
    //   现在按用户要求拆成三步, 顺序不能颠倒:
    //     第一步: 先判环境 —— 左/右线到底是实线还是虚线, 灯到底是红不是红。
    //             这一步只看识别结果, 跟按键一点关系都没有。
    //     第二步: 再判按键 —— 现在被要求做的是 直行 / 左变道 / 右变道。
    //     第三步: 两者"打架"才报警 —— 想直行却是红灯、想左变却是实线、
    //             想右变却是实线。虚线能压、灯不是红能过, 这两种情况
    //             按了键也不亮灯。
    //   三颗键共用 led[0] 这【一个】报警灯, led[1:3] 留给用户自己用。
    //------------------------------------------------------------------
    // ---- 第一步: 判环境 (与按键无关) ----
    // 红绿灯红灯判据: traffic_light 的 bk0 颜色码, K_RED = 3'd1。
    //   (K_GRN=2 / K_YEL=3 / K_LEFT=4, 见 traffic_light 模块定义)
    wire tl_red = (tl_kind == 3'd1);

    // 线型判据 (ltyp/rtyp: 0=判不出 1=实线 2=虚线)
    //   ★判不出(0)不算实线★ 看不清就不报警, 否则线一丢灯就乱亮。
    wire l_is_solid = (ltyp == 2'd1);
    wire r_is_solid = (rtyp == 2'd1);

    // ---- 第二步: 判按键指令 (顶层已保证三选一, 这里再与一次保险) ----
    wire cmd_go = force_go;
    wire cmd_l  = force_l  & ~force_go;
    wire cmd_r  = force_r  & ~force_go & ~force_l;

    // ---- 第三步: 指令与路况冲突才报警 ----
    wire alarm_go = cmd_go & tl_red;       // 红灯还要直行   -> 闯红灯
    wire alarm_l  = cmd_l  & l_is_solid;   // 左线实线还要左变 -> 压实线
    wire alarm_r  = cmd_r  & r_is_solid;   // 右线实线还要右变 -> 压实线
    wire alarm_nx = alarm_go | alarm_l | alarm_r;

    reg [3:0] nx;
    always @(*) begin
        nx = DEC_HOLD;
        if (force_go)                     nx = DEC_LC_NO;     // 强制直行
        else if (force_l)                 nx = DEC_LC_L;      // 强制左变道
        else if (force_r)                 nx = DEC_LC_R;      // 强制右变道
        else if (!lane_ok)                nx = DEC_LOST;      // 两边都没线
        else if (!lc_known)               nx = DEC_SLOW;      // 线型判不出
        else if (lc_l_ok & lc_r_ok)       nx = DEC_LC_BOTH;   // 都虚线
        else if (lc_l_ok)                 nx = DEC_LC_L;      // 左虚右实
        else if (lc_r_ok)                 nx = DEC_LC_R;      // 左实右虚
        else                              nx = DEC_LC_NO;     // 都实线
    end

    //------------------------------------------------------------------
    // 报警灯的判据已在上面"三步法"里算好 (alarm_nx), 这里不再重复。
    //   历史: v39 在这里写过 (force_go&tl_red)|(force_l&l_solid)|(force_r&r_solid),
    //   v40 挪到上方并把"先判线型、再判按键"的顺序显式写出来, 便于对照。
    //------------------------------------------------------------------

    //------------------------------------------------------------------
    // 去抖: 同一结论连续 HOLD_FRM 帧才生效
    //   LOST 例外: 车道丢失要"快报"(LOST_FRM 帧), 恢复要"慢报"(HOLD_FRM),
    //   否则偶尔一帧判不出就闪"丢失", 现场看着像坏了。
    //------------------------------------------------------------------
    reg [3:0] cand;
    reg [7:0] cnt;
    reg [2:0] lost_cnt;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            cand     <= DEC_HOLD;
            cnt      <= 8'd0;
            lost_cnt <= 3'd0;
            dec      <= DEC_HOLD;
            lvl      <= 2'd0;
            alarm    <= 1'b0;
        end else if (tick) begin
            // ---- 丢失计数(单独一条, 因为它要走更短的去抖) ----
            if (!lane_ok) lost_cnt <= (lost_cnt == 3'd7) ? 3'd7 : lost_cnt + 3'd1;
            else          lost_cnt <= 3'd0;

            // ---- 普通结论去抖 ----
            if (nx == cand) begin
                if (cnt != 8'hFF) cnt <= cnt + 8'd1;
            end else begin
                cand <= nx;
                cnt  <= 8'd0;
            end

            // ---- 生效判决 ----
            //   v39: 强制命令直接生效(不等 HOLD_FRM 去抖)—— 按键指令是
            //   确定的模拟动作, 拖 5 帧反而让演示/测试有滞后感。
            if (force_go | force_l | force_r) begin
                dec <= nx;                          // 强制命令: 立即覆盖
            end else if ((lost_cnt >= LOST_FRM) && (nx == DEC_LOST)) begin
                dec <= DEC_LOST;                    // 丢失: 快速上报
            end else if (cnt >= HOLD_FRM) begin
                dec <= cand;                        // 其余: 连续确认
            end

            // ---- 告警等级 ----
            //   v36: "都不能变道"给 1(注意)而不是 2(危险)。长实线路段是常态,
            //   报危险会一直闪红, 反而让人忽略真正的危险。
            lvl <= (dec == DEC_LOST)  ? 2'd2 :
                   (dec == DEC_STOP)  ? 2'd2 :
                   (dec == DEC_LC_NO) ? 2'd1 :
                   (dec == DEC_SLOW)  ? 2'd1 : 2'd0;

            // ---- v39 报警灯 ----
            alarm <= alarm_nx;
        end
    end

endmodule


//=====================================================================
// lane_detect.v  ——  车道线检测 / 实线虚线判别 / 变道判断
//---------------------------------------------------------------------
// 数据源: 【PC 视频】的块流 (clk_50m 域, 1024x600, 一块 = 512 像素 = 半行)
// 输出  : 每帧结算一次的小结果 (线型 / 底部 x / 车道中心偏移 / 状态)
//
// ★v34 从摄像头改成 PC 视频★
//   赛题是"基于给定视频做自主决策", 那段视频从以太网进板子, 走的是 pc_word
//   这一路。v31 把它挂在摄像头像素上, 等于认错了对象 —— PC 全屏时 src 恒为
//   1, 摄像头一个像素都不在通路上, 屏幕上自然什么都画不出来。
//
//   移植代价比预想小得多, 因为 PC 块流里坐标全是现成的:
//     blk_row = cur_dst[10:1]   行号 0..599   (外部直接喂 px_row)
//     cur_half = cur_dst[0]     左半/右半
//     pcnt                      块内像素序号 (col 靠它推进)
//     tl_line / tl_frame_st     行首 / 帧首脉冲
//   traffic_light 早就吃的是这一套, 说明这条路本来就被验证过。
//
//   三个必须处理的地方:
//     ① 一行的两块之间有空隙, 但 col 只在 px_en 那一拍 +1, 空隙里不动 ——
//        不用管。块间写通路切去搬摄像头块时 src=0, px_en=0, 同样不动。
//     ② 半行丢了(右半块没到): col 会停 511, 下一行从 512 开始, 整行 x 全偏。
//        所以加了 line_st, 行首发现 col != 0 就强制归零。
//     ③ 行号不再自己数, 直接用块号 —— 丢块时 y 不会整体偏移。
//
//   同域之后 lane_cdc(128 位翻转握手)整个不需要了。
//
// 算法 (单遍, 1 px/clk, 无行缓存, 不用 DRM):
//   ① 取 G 通道 8bit 当亮度。白色车道线 R/G/B 都高, 只取 G 就够,
//      省掉 3 个乘法器(APM 只剩 36 个, 能省就省)。
//      注意重建方式必须和 quad_wr_ctrl 里的 c_g 一致:
//        g8 = {px565[10:5], px565[10:9]}  (高 6 位是原始 G, 低 2 位补精度)
//   ② 每帧统计 ROI 内的 gmin/gmax, 阈值 = (min+max)/2, 下一帧用。
//      帧延迟 45ms, 光照突变要一帧才跟上, 可接受。
//      用中点不用均值: 均值要除法; 而且"暗背景 + 亮目标"场景下均值会被
//      大片路面压低, 白线不够白 —— 这一点和 quad_wr_ctrl 里的取舍一致。
//   ③ 行内找"亮游程", 长度 3~56 的算候选, 取首尾中点当候选 x。不用除法。
//   ④ 两个跟踪器: 每行在候选里取"离预测位置最近"的那个。
//      左线只认 x < 512, 右线只认 x >= 512 (本车必然跨在画面中央,
//      这是相机安装决定的, 不是假设)。
//   ⑤ 每行命中/未命中 -> 统计命中数、最长连续命中、空段个数。
//   ⑥ 帧末结算: 线型 / 车道中心偏移 / 居中还偏 / 是否在变道。
//
// ★线型判据为什么用"最长连续命中"而不是"命中率"★
//   透视: 近处的线在图像里占的行多, 远处占的行少。虚线在命中率上会被
//   近处那一大段拉得很高, 单看命中率会把虚线判成实线。而实线的最长
//   连续命中 ≈ 整个 ROI, 虚线最长也就是"一个线段"那么长 —— 这是两者
//   唯一本质的区别。命中率只用来判"到底看不看得见"。
//
// ★变道判据★
//   车道中心 = (左线x + 右线x)/2, 偏移 = 中心 - 512。
//   车向右移 -> 车道在画面里向左移 -> 偏移变小。所以"8 帧内偏移变化量"
//   的符号就是变道方向, 比看单帧偏移量的绝对值可靠(后者对相机安装敏感)。
//   对称地, 只看到一条线时用上一次的车道宽度补出另一条, 否则变道过程中
//   正被跨越的那条线会跑出画面, 偏移直接失效 —— 那正是最需要判断的时刻。
//
// 版本: v1  2026-11-02  首次编写, 只做检测与判定, 不进 PDS 工程
//=====================================================================
module lane_detect #(
    // ---------------- 检测区 (1024x600 图像坐标) ----------------
    //   底部 240 行。太高(>420)远处线只有 2~3 像素宽, 噪声大;
    //   太低(<540)行数不够, 虚线可能一段都装不下, 判不出空段。
    parameter [9:0] Y0       = 10'd360,
    parameter [9:0] Y1       = 10'd599,
    // ---------------- 跟踪 ----------------
    parameter [9:0] WIN      = 10'd64,     // 正常跟踪窗
    parameter [9:0] WIN_LOST = 10'd192,    // 连续两帧看不到时放宽
    parameter [9:0] SEED_L   = 10'd384,    // 重捕时左线种子(ROI 首行附近)
    parameter [9:0] SEED_R   = 10'd640,
    // ---------------- 亮游程 ----------------
    parameter [5:0] RUN_MIN  = 6'd3,       // 太短: 噪点/虚线的点状虚线
    parameter [5:0] RUN_MAX  = 6'd56,      // 太长: 大面积白(天空/白车/墙)
    // ---------------- 线型判据 (以 ROI 240 行为基准) ----------------
    parameter [8:0] HIT_MIN  = 9'd70,      // 命中数低于这个 = 这条线没看见
    parameter [8:0] SOLID_ON = 9'd168,     // 最长连续命中 >= 这个 = 实线(70%)
    parameter [2:0] DASH_SEG = 3'd2,       // 空段 >= 这个 = 虚线
    parameter [7:0] GAP_MIN  = 8'd8,       // 多长的空才算"一段"(短了是噪点)
    // ---------------- 变道 ----------------
    parameter [9:0] OFF_TH   = 10'd120,    // |偏移| 超过 = 偏离车道中心
    parameter [9:0] CHG_TH   = 10'd56,     // 8 帧内偏移变化超过 = 正在变道
    // ---------------- 亮度 ----------------
    parameter [7:0] THR_MIN  = 8'd64,      // 阈值下限(全暗场景别把噪点当线)
    parameter [7:0] CT_MIN   = 8'd28       // 对比度下限(低于此本帧判不出)
)(
    input  wire        clk        ,   // v34: 与 OSD 叠加同域 (clk_50m)
    input  wire        rst_n      ,
    input  wire        vsync      ,   // 帧首脉冲 (块流: 帧首块那一拍)
    input  wire        px_en      ,   // 像素有效, 每像素一拍
    input  wire [15:0] px565      ,   // RGB565
    input  wire        line_st    ,   // v34: 行首重对齐(块流), 强制 col 归零
    input  wire [9:0]  px_row     ,   // v34: 行号 0..599, 由块号直接给出
    // ---------------- 结果 (帧边界更新, 稳定一整帧) ----------------
    output reg  [1:0]  ltyp       ,   // 左线: 0=判不出 1=实线 2=虚线
    output reg  [1:0]  rtyp       ,   // 右线
    output reg  [10:0] lpos       ,   // {有效, 左线在 ROI 最后一次命中的 x}
    output reg  [10:0] rpos       ,
    output reg  [10:0] offv       ,   // 车道中心 - 512 (11 位补码, 负=偏左)
    output reg  [1:0]  offl       ,   // {左线有效, 右线有效}
    output reg  [2:0]  lstate     ,   // 0居中 1偏左 2偏右 3变道中 7无效
    output reg  [1:0]  cdir       ,   // 变道方向: 1=向右 2=向左 (仅 state=3 有效)
    // ---------------- 调试锚点 (给 OSD 画点用) ----------------
    //   4 个行(420/480/540/599) x 2 条线, 每组 {有效, x[9:0]} 共 11 位。
    //   ★打包顺序是"先左后右", 不是左右交错★
    //     [10:0]=L@420  [21:11]=L@480  [32:22]=L@540  [43:33]=L@599
    //     [54:44]=R@420 [65:55]=R@480  [76:66]=R@540  [87:77]=R@599
    //   上板调阈值时全靠它: 屏幕上看到红点跟着线走, 就说明跟踪和阈值都对。
    output wire [87:0] anch,
    // ---------------- v46: 列投影抽头 (给 proj_shift 用) ----------------
    //   直接把"本拍是不是一个 ROI 内的白像素 / 落在第几桶 / 灰度值"送给
    //   proj_shift, 由它自己做 64 桶累加。这样 lane_detect 一行逻辑都不用改,
    //   只是把已有的判断多接出来三根线。
    output wire        proj_vld,   // 本拍是一个 ROI 内的白像素
    output wire [5:0]  proj_bkt,   // 桶号 = col[9:4], 一桶 16 像素
    output wire [7:0]  proj_g      // 灰度 (和阈值判断用的是同一个 g8)
);

    localparam [9:0] AY0 = 10'd420;
    localparam [9:0] AY1 = 10'd480;
    localparam [9:0] AY2 = 10'd540;
    localparam [9:0] AY3 = 10'd599;

    //==================================================================
    // 第一段: 像素级流水 (行/列计数, 亮度统计, 亮游程, 候选匹配)
    //==================================================================
    reg        vs_d;
    reg        vs_pulse;          // vsync 上升沿后一拍 (整帧结算点)
    reg [10:0] col;               // 0..1023
    // v34: 行号由外部直接给(块号就是行号), 丢块也不会让 y 整体偏移
    wire [9:0] row = px_row;

    wire       row_end = px_en & (col == 11'd1023);
    wire [7:0] g8      = {px565[10:5], px565[10:9]};
    wire       in_roi  = (row >= Y0) & (row <= Y1);

    reg  [7:0] gmin_c, gmax_c;    // 本帧实时最暗/最亮
    reg  [7:0] thr;               // 本帧使用的阈值(来自上一帧统计)
    reg  [9:0] win_l, win_r;      // 当前跟踪窗(丢失时放宽)

    reg        run_on;
    reg [10:0] run_st;
    reg [5:0]  run_len;

    wire        white_px = (g8 > thr);
    wire        cand     = run_on & (run_len >= RUN_MIN) & (run_len <= RUN_MAX);
    // 游程首尾中点; col 是非白的那一列, 所以最后一个白像素是 col-1
    wire [10:0] cand_x   = (run_st + col - 11'd1) >> 1;

    reg [10:0] pred_l, pred_r;    // 本行预测位置
    reg [10:0] best_lx, best_rx;  // 本行最佳候选
    reg [10:0] best_ld, best_rd;  // 对应距离 (2047 = 没有)

    wire [10:0] dl = (cand_x >= pred_l) ? (cand_x - pred_l) : (pred_l - cand_x);
    wire [10:0] dr = (cand_x >= pred_r) ? (cand_x - pred_r) : (pred_r - cand_x);

    // 下一帧的初值 (来自第二段的状态)
    reg [10:0] seed_l, seed_r;
    reg [2:0]  missf_l, missf_r;  // 连续几帧没看见这条线
    reg [8:0]  hits_l, hits_r;    // 本帧命中行数 (在第二段累加; 提前声明是因为
                                  //   下面的 missf_*_n 就在这里要用)

    // ★放宽判断必须用"结算后的" missf, 即 missf_*_n★
    //   win_l / seed_l 和 missf_l 是在同一个 vs_pulse 沿上一起赋值的,
    //   非阻塞赋值读到的 missf_l 还是上一帧的值 —— 于是"连续两帧没看见"
    //   会拖到第三帧结束才放宽, 白白多丢一帧(≈20ms), 参数注释就成了假话。
    //   这里直接用本帧 hits 推出的下一帧 missf, 语义与注释一致。
    wire [2:0]  missf_l_n = (hits_l < HIT_MIN) ? ((missf_l == 3'd7) ? 3'd7 : missf_l + 3'd1) : 3'd0;
    wire [2:0]  missf_r_n = (hits_r < HIT_MIN) ? ((missf_r == 3'd7) ? 3'd7 : missf_r + 3'd1) : 3'd0;
    wire [9:0]  win_l_n  = (missf_l_n >= 3'd2) ? WIN_LOST  : WIN;
    wire [9:0]  win_r_n  = (missf_r_n >= 3'd2) ? WIN_LOST  : WIN;
    wire [10:0] seed_l_n = (missf_l_n >= 3'd2) ? {1'b0, SEED_L} : seed_l;
    wire [10:0] seed_r_n = (missf_r_n >= 3'd2) ? {1'b0, SEED_R} : seed_r;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            vs_d     <= 1'b0;
            vs_pulse <= 1'b0;
            col      <= 11'd0;
            gmin_c   <= 8'hFF;
            gmax_c   <= 8'h00;
            run_on   <= 1'b0;
            run_st   <= 11'd0;
            run_len  <= 6'd0;
            pred_l   <= SEED_L;
            pred_r   <= SEED_R;
            win_l    <= WIN;
            win_r    <= WIN;
            best_lx  <= 11'd0;
            best_rx  <= 11'd0;
            best_ld  <= 11'd2047;
            best_rd  <= 11'd2047;
        end else begin
            vs_d     <= vsync;
            vs_pulse <= vsync & ~vs_d;

            // ---- 帧起点: 清统计, 装载本帧的预测初值与跟踪窗 ----
            if (vs_pulse) begin
                gmin_c <= 8'hFF;
                gmax_c <= 8'h00;
                win_l  <= win_l_n;
                win_r  <= win_r_n;
                pred_l <= seed_l_n;
                pred_r <= seed_r_n;
            end

            if (vsync) begin
                // 场消隐: 行列归零, 游程作废(不能跨帧连着算)
                col     <= 11'd0;
                run_on  <= 1'b0;
                run_len <= 6'd0;
            end else if (px_en) begin
                //---------------------------------------------
                // 本像素
                //---------------------------------------------
                if (in_roi) begin
                    if (g8 < gmin_c) gmin_c <= g8;
                    if (g8 > gmax_c) gmax_c <= g8;

                    if (white_px) begin
                        if (!run_on) begin
                            run_on  <= 1'b1;
                            run_st  <= col;
                            run_len <= 6'd1;
                        end else if (run_len != 6'd63)
                            run_len <= run_len + 6'd1;
                    end else begin
                        run_on <= 1'b0;
                        if (cand) begin
                            // 左线只认左半, 右线只认右半, 避免两线互换
                            if ((cand_x < 11'd512) & (dl <= win_l) & (dl < best_ld)) begin
                                best_ld <= dl;
                                best_lx <= cand_x;
                            end
                            if ((cand_x >= 11'd512) & (dr <= win_r) & (dr < best_rd)) begin
                                best_rd <= dr;
                                best_rx <= cand_x;
                            end
                        end
                    end
                end

                //---------------------------------------------
                // 列/行推进; 行尾更新预测 + 清最佳
                //---------------------------------------------
                if (line_st & (col != 11'd0)) begin
                    // v34: 半行丢了(右半块没到) -> col 停在 511, 不归零的话
                    //   下一行会从 512 开始, 整行 x 全偏而且永远对不回来。
                    //   正常情况下 col 已经是 0, 这条分支根本不进来。
                    col     <= 11'd0;
                    best_ld <= 11'd2047;
                    best_rd <= 11'd2047;
                    run_on  <= 1'b0;
                    run_len <= 6'd0;
                end else if (col == 11'd1023) begin
                    col <= 11'd0;
                    // 本行命中的话, 下一行的预测就跟着走
                    if (best_ld <= win_l) pred_l <= best_lx;
                    if (best_rd <= win_r) pred_r <= best_rx;
                    best_ld <= 11'd2047;
                    best_rd <= 11'd2047;
                    run_on  <= 1'b0;          // 游程不跨行
                end else
                    col <= col + 11'd1;
            end
        end
    end

    //==================================================================
    // 第二段: 行统计 + 帧结算
    //==================================================================
    reg [8:0]  cmax_l, cmax_r;        // 最长连续命中
    reg [8:0]  cont_l, cont_r;        // 当前连续命中
    reg [7:0]  gap_l,  gap_r;         // 当前连续未命中
    reg [2:0]  gseg_l, gseg_r;        // 空段个数
    reg        fhit_l, fhit_r;        // 本帧是否命中过
    reg [10:0] cur_l,  cur_r;         // 最后一次命中 x
    reg [10:0] lane_w;                // 车道宽度(像素), 跨帧保持
    reg [87:0] off_hist;              // 偏移量 8 帧历史
    reg [43:0] anc_l, anc_r;          // 调试锚点

    // 帧末把"还挂着的空段"也算进空段数
    // ★这里必须用 4 位★ gseg_l 在行统计里是饱和到 7 的, 再加 1 就溢出成 0,
    //   于是"空段很多"反而被判成"没有空段", 虚线会被误判成判不出。
    wire [3:0] gseg_l_e = {1'b0, gseg_l} + ((gap_l >= GAP_MIN) ? 4'd1 : 4'd0);
    wire [3:0] gseg_r_e = {1'b0, gseg_r} + ((gap_r >= GAP_MIN) ? 4'd1 : 4'd0);

    wire       l_ok   = (hits_l >= HIT_MIN);
    wire       r_ok   = (hits_r >= HIT_MIN);
    wire       lw_ok  = (lane_w >= 11'd120) & (lane_w <= 11'd1000);
    wire [10:0] lw_now = (cur_r > cur_l) ? (cur_r - cur_l) : 11'd0;

    // 车道中心: 两条线都在就用中点; 只看到一条就用上次的车道宽度补
    wire [10:0] ctr_c  = (l_ok & r_ok) ? ((cur_l + cur_r) >> 1)
                       : ((r_ok & lw_ok) ? (cur_r - (lane_w >> 1))
                       : ((l_ok & lw_ok) ? (cur_l + (lane_w >> 1)) : 11'd512));
    wire        pos_ok = (l_ok & r_ok) | ((l_ok | r_ok) & lw_ok);
    wire [10:0] off_c  = ctr_c - 11'd512;

    // ★这里必须做符号扩展, 不能写 {1'b0, off_c}★
    //   off_c 是 11 位补码, -38 是 11'h7DA。补一个 0 变成 12'h7DA,
    //   最高位是 0, 于是 -38 被当成 +2010 —— 一帧正常平移 40 像素会被判成
    //   "变道"。正确做法是把第 10 位再复制到第 11 位。
    wire signed [11:0] off_ext  = {off_c[10], off_c};
    wire signed [11:0] off8_ext = {off_hist[87], off_hist[87:77]};
    wire signed [11:0] dchg     = off_ext - off8_ext;
    wire [11:0]        dabs     = dchg[11] ? ((~dchg) + 12'd1) : dchg;
    wire signed [11:0] offs_s   = off_ext;
    wire signed [11:0] off_thp  = {2'b0, OFF_TH};
    wire signed [11:0] off_thn  = -{2'b0, OFF_TH};

    // 亮度统计 -> 阈值 + 对比度
    wire [8:0] thr_c  = ({1'b0, gmax_c} + {1'b0, gmin_c}) >> 1;
    wire [8:0] ct_c   = (gmax_c >= gmin_c) ? ({1'b0, gmax_c} - {1'b0, gmin_c}) : 9'd0;
    wire       ct_ok  = (ct_c >= {1'b0, CT_MIN});

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            hits_l <= 9'd0;  hits_r <= 9'd0;
            cmax_l <= 9'd0;  cmax_r <= 9'd0;
            cont_l <= 9'd0;  cont_r <= 9'd0;
            gap_l  <= 8'd0;  gap_r  <= 8'd0;
            gseg_l <= 3'd0;  gseg_r <= 3'd0;
            fhit_l <= 1'b0;  fhit_r <= 1'b0;
            cur_l  <= 11'd0; cur_r  <= 11'd0;
            seed_l <= SEED_L; seed_r <= SEED_R;
            missf_l<= 3'd7;  missf_r<= 3'd7;
            lane_w <= 11'd0;
            off_hist <= 88'd0;
            anc_l  <= 44'd0; anc_r  <= 44'd0;
            thr    <= THR_MIN;
            ltyp   <= 2'd0;  rtyp   <= 2'd0;
            lpos   <= 11'd0; rpos   <= 11'd0;
            offv   <= 11'd0; offl   <= 2'd0;
            lstate <= 3'd7;  cdir   <= 2'd0;
        end else if (vs_pulse) begin
            //================= 帧结算 (用刚结束那一帧的累加器) =========
            // ---- 阈值: 这一帧算, 下一帧用 ----
            thr <= (thr_c < {1'b0, THR_MIN}) ? THR_MIN : thr_c[7:0];

            // ---- 线型 ----
            if (!ct_ok | (hits_l < HIT_MIN))
                ltyp <= 2'd0;
            else if (cmax_l >= SOLID_ON)
                ltyp <= 2'd1;                     // 实线
            else if (gseg_l_e >= DASH_SEG)
                ltyp <= 2'd2;                     // 虚线
            else
                ltyp <= 2'd0;                     // 看不清, 不硬猜

            if (!ct_ok | (hits_r < HIT_MIN))
                rtyp <= 2'd0;
            else if (cmax_r >= SOLID_ON)
                rtyp <= 2'd1;
            else if (gseg_r_e >= DASH_SEG)
                rtyp <= 2'd2;
            else
                rtyp <= 2'd0;

            // ---- 位置 / 偏移 ----
            lpos <= {l_ok & ct_ok, cur_l[9:0]};
            rpos <= {r_ok & ct_ok, cur_r[9:0]};
            offl <= {l_ok & ct_ok, r_ok & ct_ok};
            offv <= off_c;

            if (l_ok & r_ok & ct_ok)
                lane_w <= lw_now;
            else if (!lw_ok)
                lane_w <= 11'd0;                  // 宽度离谱就丢掉重学

            off_hist <= {off_hist[76:0], off_c};

            // ---- 状态 ----
            if (!(pos_ok & ct_ok))
                lstate <= 3'd7;                   // 无效
            else if (dabs > {2'b0, CHG_TH}) begin
                lstate <= 3'd3;                   // 变道中
                cdir   <= dchg[11] ? 2'd1 : 2'd2; // 中心左移 = 车向右
            end
            else if (offs_s < off_thn) lstate <= 3'd1;   // 偏左
            else if (offs_s > off_thp) lstate <= 3'd2;   // 偏右
            else                       lstate <= 3'd0;   // 居中

            // ---- 清累加器 ----
            hits_l <= 9'd0;  hits_r <= 9'd0;
            cmax_l <= 9'd0;  cmax_r <= 9'd0;
            cont_l <= 9'd0;  cont_r <= 9'd0;
            gap_l  <= 8'd0;  gap_r  <= 8'd0;
            gseg_l <= 3'd0;  gseg_r <= 3'd0;
            fhit_l <= 1'b0;  fhit_r <= 1'b0;
            // 注意: anc_l/anc_r 不在这里清, 见下面 row==Y0-1 那一处

            // ---- 连续未命中帧数 (决定下一帧要不要放宽跟踪窗) ----
            //   与 win_*_n / seed_*_n 共用同一个表达式, 保证"判定"和"装窗"
            //   看的是同一个值(见第一段里的 missf_*_n)。
            missf_l <= missf_l_n;
            missf_r <= missf_r_n;

        end else if (row_end) begin
            //===================== 行尾统计 =====================
            // ★只在 ROI 内统计★ 否则第 0..359 行会一路累加 gap_l, 到 ROI
            //   第一行时 gap_l 已经是 359, 第一次命中就白送一个"空段";
            //   实线只要有一处漏检就被凑成 2 段, 直接误判成虚线。
            if (in_roi) begin
            // ---- 左线 ----
            if (best_ld <= win_l) begin
                hits_l <= hits_l + 9'd1;
                cont_l <= cont_l + 9'd1;
                if ((cont_l + 9'd1) > cmax_l) cmax_l <= cont_l + 9'd1;
                if (gap_l >= GAP_MIN) gseg_l <= (gseg_l == 3'd7) ? 3'd7 : gseg_l + 3'd1;
                gap_l  <= 8'd0;
                cur_l  <= best_lx;
                if (!fhit_l) begin
                    fhit_l <= 1'b1;
                    seed_l <= best_lx;            // 本帧顶部位置, 下一帧的预测初值
                end
                if (row == AY0) anc_l[10:0]  <= {1'b1, best_lx[9:0]};
                if (row == AY1) anc_l[21:11] <= {1'b1, best_lx[9:0]};
                if (row == AY2) anc_l[32:22] <= {1'b1, best_lx[9:0]};
                if (row == AY3) anc_l[43:33] <= {1'b1, best_lx[9:0]};
            end else begin
                if (gap_l != 8'hFF) gap_l <= gap_l + 8'd1;
                cont_l <= 9'd0;
            end

            // ---- 右线 ----
            if (best_rd <= win_r) begin
                hits_r <= hits_r + 9'd1;
                cont_r <= cont_r + 9'd1;
                if ((cont_r + 9'd1) > cmax_r) cmax_r <= cont_r + 9'd1;
                if (gap_r >= GAP_MIN) gseg_r <= (gseg_r == 3'd7) ? 3'd7 : gseg_r + 3'd1;
                gap_r  <= 8'd0;
                cur_r  <= best_rx;
                if (!fhit_r) begin
                    fhit_r <= 1'b1;
                    seed_r <= best_rx;
                end
                if (row == AY0) anc_r[10:0]  <= {1'b1, best_rx[9:0]};
                if (row == AY1) anc_r[21:11] <= {1'b1, best_rx[9:0]};
                if (row == AY2) anc_r[32:22] <= {1'b1, best_rx[9:0]};
                if (row == AY3) anc_r[43:33] <= {1'b1, best_rx[9:0]};
            end else begin
                if (gap_r != 8'hFF) gap_r <= gap_r + 8'd1;
                cont_r <= 9'd0;
            end
            end                                  // if (in_roi)

            // ROI 开始之前清掉上一帧的调试锚点。
            // ★绝不能放在 vs_pulse 里清★ 结算和"父模块来读"是同一拍,
            //   清了就等于永远读不到 —— 第一版锚点全是 0 就是这么来的。
            if (row == (Y0 - 10'd1)) begin
                anc_l <= 44'd0;
                anc_r <= 44'd0;
            end
        end
    end

    assign anch = {anc_r, anc_l};

    //------------------------------------------------------------------
    // v46: 列投影抽头
    //   只统计"亮于阈值"的像素, 和游程/线型判定用的是同一个 white_px。
    //   不在游程里的孤立噪点也算 —— 投影是统计量, 单个噪点摊到 64 个桶里
    //   几乎看不出来, 没必要再滤一道。
    //------------------------------------------------------------------
    assign proj_vld = px_en & in_roi & white_px;
    assign proj_bkt = col[9:4];
    assign proj_g   = g8;

endmodule




//=====================================================================
// fps_osd.v  ——  摄像头帧率 OSD (v41)
//---------------------------------------------------------------------
// 作用: 在摄像头画面右上角画 "FPS xx", 黑底黄字, 5x7 字模放大 2 倍。
//
// 为什么单独拆一个模块:
//   1) 它的坐标基准、刷新节奏(1 秒) 和车道线叠加完全无关, 混在 quad_wr_ctrl
//      里既难读也难测;
//   2) 拆出来以后 TB 可以直接给 px_x/px_y 扫描整个框, 不用喂整帧图像。
//
// 帧率怎么算(不写除法器):
//   开一个 1 秒窗口 (WIN_TICKS 个时钟), 窗口里用两个 BCD 计数器数 cam_vs
//   的个数; 窗口到点就把计数锁存给显示、计数器清零。
//   ★这样得到的值本身就是十进制的★ 不需要 二进制/10 的除法器(那玩意儿
//   要几十个 LUT 还拖时序), 只要两个 4 位计数器。
//   代价: 上电后第一秒显示 00, 之后每秒刷新一次 —— 帧率本来就是慢变量,
//   一秒一刷完全够看。
//
// 位置:
//   摄像头全屏(1024x600): 右边界 x=1016, 顶边 y=2..19
//   四宫格    (512x300)  : 右边界 x=504 , 顶边同上
//   6 个字符 x 步进 12 = 宽 72 像素; 右对齐, 所以左边 = 右边界 - 71。
//=====================================================================
module fps_osd #(
    parameter [25:0] WIN_TICKS = 26'd49_999_999     // 1 秒 @50MHz
)(
    input  wire        clk      ,
    input  wire        rst_n    ,
    input  wire        cam_vs   ,   // 摄像头场同步, 50MHz 域 1 拍脉冲
    input  wire        cam_full ,   // 1 = 摄像头全屏(1024x600) 0 = 四宫格(512x300)
    input  wire        src      ,   // 0 = 摄像头像素 (1 = PC, 不画)
    input  wire [9:0]  px_x     ,   // 摄像头画面坐标系
    input  wire [9:0]  px_y     ,
    output wire        osd_on   ,   // 该像素属于帧率框(黑底或字)
    output wire [15:0] osd_col      // RGB565
);

    //------------------------------------------------------------------
    // 1) 1 秒窗口 + BCD 帧计数
    //    win  : 窗口计时
    //    c_o/c_t : 本窗口内的个位/十位
    //    d_o/d_t : 上一秒的结果, 显示用
    //------------------------------------------------------------------
    reg [25:0] win;
    reg [3:0]  c_o, c_t;
    reg [3:0]  d_o, d_t;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            win <= 26'd0;
            c_o <= 4'd0;  c_t <= 4'd0;
            d_o <= 4'd0;  d_t <= 4'd0;
        end else if (win == WIN_TICKS) begin
            win <= 26'd0;
            d_o <= c_o;                 // 锁存上一秒的计数
            d_t <= c_t;
            c_o <= 4'd0;                // 重新开始数
            c_t <= 4'd0;
        end else begin
            win <= win + 26'd1;
            if (cam_vs) begin
                // ★到 99 就停住, 不能回绕★ 回绕会把 105 帧显示成 05,
                //   看着像"掉帧" —— 虽然真实摄像头 22 帧/秒永远碰不到,
                //   但一条错的值比一条不动的值更容易误事。
                if ((c_t != 4'd9) || (c_o != 4'd9)) begin
                    if (c_o == 4'd9) begin
                        c_o <= 4'd0;
                        c_t <= c_t + 4'd1;
                    end else
                        c_o <= c_o + 4'd1;
                end
            end
        end
    end

    //------------------------------------------------------------------
    // 2) 字符框定位
    //------------------------------------------------------------------
    wire [9:0] xr = cam_full ? 10'd1016 : 10'd504;
    wire [9:0] xl = xr - 10'd71;                   // 宽 72 = 6 字符 x 12

    // 黑底: 比文字四周各多 3 像素 / 上下多 3 像素, 亮背景上也能看清
    wire box = (src == 1'b0) &
               (px_x >= (xl - 10'd3)) & (px_x <= (xr + 10'd3)) &
               (px_y >= 10'd2)        & (px_y <= 10'd19);

    // 字身区: 高 14, 宽 72
    wire area = box & (px_x >= xl) & (px_x <= xr) &
                     (px_y >= 10'd5) & (px_y <= 10'd18);

    wire [9:0] fu = px_x - xl;                     // 0..71
    wire [9:0] fv = px_y - 10'd5;                  // 0..13

    // 横向放大 2 倍: 每 2 像素一格, 字符步进 6 格 (5 格字身 + 1 格间隔)
    wire [9:0] fu2 = fu[9:1];                      // 0..35
    wire [2:0] fci = (fu2 < 10'd6)  ? 3'd0 :
                     (fu2 < 10'd12) ? 3'd1 :
                     (fu2 < 10'd18) ? 3'd2 :
                     (fu2 < 10'd24) ? 3'd3 :
                     (fu2 < 10'd30) ? 3'd4 : 3'd5;
    wire [9:0] fbase = {7'd0, fci} * 10'd6;        // 常数乘 6 -> 移位加
    // ★这里必须用 10 位相减再截低位★ fbase 最大 30(第 5 个字符), 只取
    //   fbase[3:0] 会把 18/24/30 截成 2/8/14, 后三个字符的列号全错位。
    wire [9:0] fcu10 = fu2 - fbase;                // 0..5
    wire [3:0] fcu   = fcu10[3:0];                 // 0..5

    // 第 4 位起是个位/十位; 字符码: 0=F 1=P 2=S 3=空格 4..13='0'..'9'
    wire [4:0] fch = (fci == 3'd0) ? 5'd0 :
                     (fci == 3'd1) ? 5'd1 :
                     (fci == 3'd2) ? 5'd2 :
                     (fci == 3'd3) ? 5'd3 :
                     (fci == 3'd4) ? ({1'b0, d_t} + 5'd4) :
                                     ({1'b0, d_o} + 5'd4);

    // ★不能写成 fps_glyph(...)[idx]★ Verilog-2001 不允许对函数调用结果位选
    wire [4:0] frow = fps_glyph(fch, fv[3:1]);
    wire [2:0] fcol = (fcu >= 4'd5) ? 3'd0 : (3'd4 - fcu[2:0]);

    wire fpix = area & (fcu < 4'd5) & frow[fcol];

    assign osd_on  = box;
    assign osd_col = fpix ? 16'hFFE0 : 16'h0000;   // 字=黄, 底=黑

    //------------------------------------------------------------------
    // 3) 字模 (F P S 空格 0-9)
    //    5x7, bit4 = 最左一列。只做本模块要用的 14 个字符, 不复用 glyph_all
    //    —— 那套是 4 位编码且只有字母, 塞数字要改三层 default 分支, 风险更大。
    //------------------------------------------------------------------
    function [4:0] fps_glyph;
        input [4:0] ch;
        input [2:0] row;
        begin
            case (ch)
                5'd0: case (row)                        // F
                    3'd0: fps_glyph = 5'h1F;  3'd1: fps_glyph = 5'h10;
                    3'd2: fps_glyph = 5'h10;  3'd3: fps_glyph = 5'h1E;
                    default: fps_glyph = 5'h10;
                endcase
                5'd1: case (row)                        // P
                    3'd0: fps_glyph = 5'h1E;  3'd1: fps_glyph = 5'h11;
                    3'd2: fps_glyph = 5'h11;  3'd3: fps_glyph = 5'h1E;
                    default: fps_glyph = 5'h10;
                endcase
                5'd2: case (row)                        // S
                    3'd0: fps_glyph = 5'h0E;  3'd1: fps_glyph = 5'h10;
                    3'd2: fps_glyph = 5'h10;  3'd3: fps_glyph = 5'h0E;
                    3'd4: fps_glyph = 5'h01;  3'd5: fps_glyph = 5'h01;
                    default: fps_glyph = 5'h0E;
                endcase
                5'd3: fps_glyph = 5'h00;                // 空格
                5'd4: case (row)                        // 0 (不加斜杠, 免得看成 Ø)
                    3'd0: fps_glyph = 5'h0E;  3'd1: fps_glyph = 5'h11;
                    3'd2: fps_glyph = 5'h11;  3'd3: fps_glyph = 5'h11;
                    3'd4: fps_glyph = 5'h11;  3'd5: fps_glyph = 5'h11;
                    default: fps_glyph = 5'h0E;
                endcase
                5'd5: case (row)                        // 1
                    3'd0: fps_glyph = 5'h04;  3'd1: fps_glyph = 5'h0C;
                    3'd2: fps_glyph = 5'h04;  3'd3: fps_glyph = 5'h04;
                    3'd4: fps_glyph = 5'h04;  3'd5: fps_glyph = 5'h04;
                    default: fps_glyph = 5'h0E;
                endcase
                5'd6: case (row)                        // 2
                    3'd0: fps_glyph = 5'h0E;  3'd1: fps_glyph = 5'h11;
                    3'd2: fps_glyph = 5'h01;  3'd3: fps_glyph = 5'h02;
                    3'd4: fps_glyph = 5'h04;  3'd5: fps_glyph = 5'h08;
                    default: fps_glyph = 5'h1F;
                endcase
                5'd7: case (row)                        // 3
                    3'd0: fps_glyph = 5'h1F;  3'd1: fps_glyph = 5'h02;
                    3'd2: fps_glyph = 5'h04;  3'd3: fps_glyph = 5'h02;
                    3'd4: fps_glyph = 5'h01;  3'd5: fps_glyph = 5'h11;
                    default: fps_glyph = 5'h0E;
                endcase
                5'd8: case (row)                        // 4
                    3'd0: fps_glyph = 5'h02;  3'd1: fps_glyph = 5'h06;
                    3'd2: fps_glyph = 5'h0A;  3'd3: fps_glyph = 5'h12;
                    3'd4: fps_glyph = 5'h1F;  3'd5: fps_glyph = 5'h02;
                    default: fps_glyph = 5'h02;
                endcase
                5'd9: case (row)                        // 5
                    3'd0: fps_glyph = 5'h1F;  3'd1: fps_glyph = 5'h10;
                    3'd2: fps_glyph = 5'h1E;  3'd3: fps_glyph = 5'h01;
                    3'd4: fps_glyph = 5'h01;  3'd5: fps_glyph = 5'h11;
                    default: fps_glyph = 5'h0E;
                endcase
                5'd10: case (row)                       // 6
                    3'd0: fps_glyph = 5'h06;  3'd1: fps_glyph = 5'h08;
                    3'd2: fps_glyph = 5'h10;  3'd3: fps_glyph = 5'h1E;
                    3'd4: fps_glyph = 5'h11;  3'd5: fps_glyph = 5'h11;
                    default: fps_glyph = 5'h0E;
                endcase
                5'd11: case (row)                       // 7
                    3'd0: fps_glyph = 5'h1F;  3'd1: fps_glyph = 5'h01;
                    3'd2: fps_glyph = 5'h02;  3'd3: fps_glyph = 5'h04;
                    default: fps_glyph = 5'h08;
                endcase
                5'd12: case (row)                       // 8
                    3'd0: fps_glyph = 5'h0E;  3'd1: fps_glyph = 5'h11;
                    3'd2: fps_glyph = 5'h11;  3'd3: fps_glyph = 5'h0E;
                    3'd4: fps_glyph = 5'h11;  3'd5: fps_glyph = 5'h11;
                    default: fps_glyph = 5'h0E;
                endcase
                default: case (row)                     // 9
                    3'd0: fps_glyph = 5'h0E;  3'd1: fps_glyph = 5'h11;
                    3'd2: fps_glyph = 5'h11;  3'd3: fps_glyph = 5'h0F;
                    3'd4: fps_glyph = 5'h01;  3'd5: fps_glyph = 5'h02;
                    default: fps_glyph = 5'h0C;
                endcase
            endcase
        end
    endfunction

endmodule


//=====================================================================
// proj_shift.v  ——  64 桶列投影帧间位移  (v46)
//---------------------------------------------------------------------
// 【为什么需要它】
//   ego_state(v45) 只看左线底部锚点。可十字路口里 y=420..599 一整段
//   没有任何车道线, 锚点整段失效, acc 冻结, 灯一直显示直行。
//   石2.0 帧 186..250 就是这个情况(实测 65 帧里 60 帧锚点无效)。
//
// 【为什么不用"白像素质心"】
//   试过, 不行。质心测的是"亮区重心", 一旦有车道线滑出视野, 剩下的
//   亮区会把重心拽向反方向: 石2.0 右弯段(帧 299..314)左线滑出左边、
//   右线滑出右边, 重心反而右移, 把右转报成左转。质心只在路口那段
//   "蒙对", 是集合变化恰好和运动同向, 不能当判据。
//
// 【为什么不用缓存图像做块匹配】
//   也算过账: ROI 全分辨率 1024x240 = 240KB, 而整片只剩 31 块 DRM18K
//   = 70KB, 差 17 倍。降到 128x30 能放下(3.75KB/帧), 但实测分块匹配
//   在路口内块一致度塌到 3/32 —— 空白沥青上 16x7 的小块里没有纹理,
//   SAD 曲线是平的, 32 个块各说各话, 中值就是随机数。
//   投影正好相反: 24 万像素压成 64 个统计量, 样本量大到空白路面也能
//   压出稳定值。石2.0 直道段位移恒为 0(精确的零), 路口段 -32->-160
//   单调不回头。
//
// 【怎么算】
//   proj[b] = 桶 b 内所有白像素的灰度之和         (b = 0..63, 一桶 16px)
//   每帧存一份, 存 9 份环形(1024x18 一块 DRM18K, 只用 576 字)。
//   帧末拿当前帧和 8 帧前那份做 SAD:
//       SAD(d) = sum_b |cur[b] - old[b+d]|      d = -6..+6  (±96 像素)
//   取 SAD 最小的 d。因为比的是"整个投影形状平移了多少", 线滑出视野
//   不会带偏方向 —— 这正是质心栽跟头的地方。
//
// 【符号】d > 0 表示 old 的特征出现在 cur 的右边, 即画面内容整体左移。
//   所以输出 dx = -d, 语义统一成"正 = 内容右移 = 车向左转"。
//
// 【资源】累加器 64x20 位 = 1280 FF, 投影缓存 1 块 DRM18K(用 576/1024),
//   状态机约 1024 拍/帧 (20.5us @50MHz, 一帧 45.8ms, 占 0.04%)。
//=====================================================================
module proj_shift #(
    parameter signed [3:0] SR   = 4'sd6,    // 搜索半径(桶), ±6 = ±96px
    parameter        [3:0] NP   = 4'd9      // 环形页数 = LAG+1
)(
    input  wire        clk,
    input  wire        rst_n,
    // 像素流 (来自 lane_detect 的抽头)
    input  wire        px_vld,
    input  wire [5:0]  px_bkt,
    input  wire [7:0]  px_g,
    // 帧边界: 帧首块后第 3 拍, 此时上一帧像素已全部流过
    input  wire        frm_end,
    // 结果
    output reg  signed [4:0] dx,        // 正 = 画面内容右移 = 车向左转
    output reg         dx_vld,          // 本帧结果已更新
    output reg         dx_conf          // 匹配可信 (最优点比 d=0 好 12.5% 以上)
);

    //------------------------------------------------------------------
    // 1) 像素累加: 64 个桶, 每个 20 位 (240 行 x 16 列 x 255 = 979200)
    //
    //   ★这里不能写 pb[px_bkt] <= pb[px_bkt] + g★
    //     动态索引会综合成"64 选 1 读 + 64 路写"的寄存器堆, 读通路是一个
    //     20 位 x 64 的 mux, 在 50MHz 下延迟很紧张。
    //     改成每个桶自己判断"是不是轮到我", 只有写使能要译码(6 位比较),
    //     读那一侧留到帧末串行做, 一次只读一个桶。
    //------------------------------------------------------------------
    reg [19:0] pb [0:63];
    integer    i;
    wire       pb_clr;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            for (i = 0; i < 64; i = i + 1)
                pb[i] <= 20'd0;
        end else if (pb_clr) begin
            for (i = 0; i < 64; i = i + 1)
                pb[i] <= 20'd0;
        end else if (px_vld) begin
            for (i = 0; i < 64; i = i + 1)
                if (px_bkt == i[5:0])
                    pb[i] <= pb[i] + 20'd1;      // 计"白像素个数", 不累加灰度
        end
    end

    //------------------------------------------------------------------
    // 2) 帧时序: 写 64 拍 -> 搜 832 拍 -> 收尾 1 拍
    //------------------------------------------------------------------
    reg        busy;
    reg [10:0] st;                 // 0..896
    reg [3:0]  wp;                 // 当前写页 0..8

    wire wr_ph = busy & (st < 11'd64);
    wire sr_ph = busy & (st >= 11'd64) & (st < 11'd896);
    wire fin_ph = busy & (st == 11'd896);

    assign pb_clr = fin_ph;        // 收尾那一拍把累加器清零, 给下一帧用

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            busy <= 1'b0;
            st   <= 11'd0;
            wp   <= 4'd0;
        end else if (frm_end & ~busy) begin
            busy <= 1'b1;
            st   <= 11'd0;
        end else if (busy) begin
            st <= st + 11'd1;
            if (fin_ph) begin
                busy <= 1'b0;
                wp   <= (wp == (NP - 4'd1)) ? 4'd0 : (wp + 4'd1);
            end
        end
    end

    //------------------------------------------------------------------
    // 3) 投影缓存: 9 页 x 64 桶, 只存 pb[19:2] (18 位, 丢低 2 位)
    //    读回来左移 2 位还原, 误差 <=3, 摊到 SAD 里可以忽略。
    //------------------------------------------------------------------
    reg [17:0] hram [0:575];

    // 读页 = 8 帧前那一页 = 写页 + 1 (环形)
    wire [3:0] rp  = (wp == (NP - 4'd1)) ? 4'd0 : (wp + 4'd1);
    wire [9:0] wad = {wp, 6'd0} + {5'd0, st[5:0]};

    always @(posedge clk) begin
        if (wr_ph)
            hram[wad] <= pb[st[5:0]][19:2];
    end

    // ---------------- 搜索坐标 ----------------
    wire [9:0]  si  = st - 11'd64;          // 0..831
    wire [5:0]  sb  = si[5:0];              // 桶号
    wire [3:0]  sd  = si[9:6];              // 0..12, 对应 d = sd - 6

    // 只统计 sb 在 [6,57] 的桶, 这样 13 个位移的样本数都是 52, 不用归一化
    wire        sb_use = (sb >= 6'd6) & (sb <= 6'd57);

    // 读地址: 8 帧前那一页的第 (sb + d) 桶
    //   ★必须用 9 位有符号算再截断★ 7 位直接相加时, d=-6 会变成 122,
    //   靠模 128 溢出碰巧得到正确结果 —— 只是运气, 换个边界就错。
    wire signed [7:0]  rd_off = {{4{sd[3]}}, sd} - 8'sd6;      // d = sd-6
    wire signed [7:0]  sb_s   = {2'b0, sb};
    wire signed [7:0]  rad_s  = sb_s + rd_off;
    wire [9:0]         rad    = {rp, 6'd0} + {4'd0, rad_s[5:0]};

    //------------------------------------------------------------------
    // 4) 流水: 给地址 -> 下一拍数据到 -> 算 |差| 累加
    //------------------------------------------------------------------
    reg [17:0] ram_q;
    reg [19:0] pb_q;
    reg [5:0]  sb_q;
    reg [3:0]  sd_q;
    reg        sr_q;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            ram_q <= 18'd0;
            pb_q  <= 20'd0;
            sb_q  <= 6'd0;
            sd_q  <= 4'd0;
            sr_q  <= 1'b0;
        end else begin
            sr_q <= sr_ph;
            if (sr_ph) begin
                ram_q <= hram[rad];
                pb_q  <= pb[sb];
                sb_q  <= sb;
                sd_q  <= sd;
            end
        end
    end

    wire [19:0] ram20 = {ram_q, 2'b00};
    wire [19:0] dabs  = (pb_q >= ram20) ? (pb_q - ram20) : (ram20 - pb_q);

    reg [27:0] sad_acc;
    reg [27:0] best_sad;
    reg [3:0]  best_sd;
    reg [27:0] sad0;
    reg        first_d;

    wire d_end = sr_q & (sb_q == 6'd63);

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            sad_acc  <= 28'd0;
            best_sad <= 28'hFFFFFFF;
            best_sd  <= 4'd6;
            sad0     <= 28'd0;
            first_d  <= 1'b1;
        end else if (frm_end & ~busy) begin
            sad_acc  <= 28'd0;
            best_sad <= 28'hFFFFFFF;
            best_sd  <= 4'd6;
            sad0     <= 28'd0;
            first_d  <= 1'b1;
        end else if (sr_q) begin
            // ★这里必须用 sb_q 而不是 sb★  dabs 是流水一拍之后的数据,
            //   用它对应的桶号 sb_q 判断才对齐; 用当前的 sb 会整体错一拍,
            //   SAD 里混进相邻桶的差值。
            if ((sb_q >= 6'd6) && (sb_q <= 6'd57))
                sad_acc <= sad_acc + {8'd0, dabs};

            if (d_end) begin
                // 一个位移搜完: 更新最优, 记录 d=0 的基准
                if (first_d || (sad_acc < best_sad)) begin
                    best_sad <= sad_acc;
                    best_sd  <= sd_q;
                    first_d  <= 1'b0;
                end
                if (sd_q == 4'd6)
                    sad0 <= sad_acc;
                sad_acc <= 28'd0;
            end
        end
    end

    //------------------------------------------------------------------
    // 5) 输出
    //   dx = -(d) = 6 - best_sd, 范围 -6..+6
    //   conf: sad0 比最优值高 12.5% 以上才算匹配可信
    //   预热: 环形缓冲要填满 9 页才拿得到 8 帧前的数据, 前 8 帧不输出
    //------------------------------------------------------------------
    reg [3:0] warm;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)      warm <= 4'd0;
        else if (fin_ph) warm <= (warm == 4'd9) ? 4'd9 : (warm + 4'd1);
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            dx      <= 5'sd0;
            dx_vld  <= 1'b0;
            dx_conf <= 1'b0;
        end else if (fin_ph) begin
            dx      <= 5'sd6 - {1'b0, best_sd};
            dx_vld  <= (warm >= 4'd8);
            dx_conf <= (sad0 > (best_sad + (sad0 >> 3)));
        end
    end

endmodule


//=====================================================================
// ego_state.v  ——  车辆行驶状态判定: 直行 / 左转 / 右转  (v45)
//---------------------------------------------------------------------
// 输入: 每帧一次 tick + 左线底部锚点 {valid, x}
// 输出: ego = 0 直行 / 1 左转 / 2 右转
//
// 【判据】只看一个量 —— 左线底部锚点的 8 帧差分:
//      dx = x_L(t) - x_L(t-8)
//    x 是左线在画面里的横坐标(anch[43:33], 采样行 y=599):
//      dx < -TH : 左线左移 -> 画面整体左移 -> 车头向右 -> 右转
//      dx > +TH : 左线右移                          -> 左转
//    |dx| <= TH 当作没在转(直道抖动/车道小幅修正)。
//
// 【为什么不用车道中心 offv (v44 的错法)】
//    v44 用 offv 的 1 帧差分, 上板一直判直行。跑真实视频帧才看清:
//    offv 在 14 / 36 / -120 / -123 之间跳, 单帧差分全是噪声。
//    根源是 offv = (cur_l + cur_r)/2, 而 cur 是"本帧最后一次命中的位置",
//    任何一行跟错就毁整帧。而左线锚点是固定行采样, 实测直道稳在
//    263~273、弯道单向滑到 137, 信噪比高一个数量级。
//
// 【为什么用累积器而不是"连续 N 帧计数"】
//    转弯时 dx 不会每帧都超阈值(车道线抖动、偶尔丢一两行都会打断计数),
//    用"必须连续 N 帧"很容易永远凑不满。改成带符号累积:
//      超阈值 -> acc 加/减 1;  没超 -> acc 慢慢回零
//    这样偶发的一帧不达标只是少加 1, 不会把前面的积累清零。acc 到
//    ±ACC_TH 才算转向, 天然就是"持续若干帧"的效果, 而且只要 6 个 FF。
//
// 【滞回】
//    进: |acc| >= ACC_TH
//    出: |acc| <  ACC_TH - ACC_HY
//    没有滞回的话, acc 在阈值上下抖一格, 灯就跟着闪。
//
// 【丢线时怎么办】
//    锚点无效(该行本帧没命中) 时 dx 不算, acc 回零, ego 保持上一次的值。
//    理由: 车不会因为相机一时看不见线就改变行驶方向, 保持比乱报好。
//    上电初值是 0(直行)。
//=====================================================================
module ego_state #(
    parameter [9:0]  DX_TH  = 10'd24,   // 8 帧内左线横移超过这个 = 在转向(像素)
    parameter [4:0]  ACC_TH = 5'd8,     // 累积到多少算转向(帧)
    parameter [4:0]  ACC_HY = 5'd3,     // 退出滞回(帧), 退出阈值 = ACC_TH-ACC_HY
    // ---------------- v46: 投影路的参数 ----------------
    parameter [4:0]  LOCK_N = 5'd12,    // 锚点连续多少帧一模一样 = 锁死, 交给投影
    parameter [3:0]  DTH_P  = 4'd2,     // 投影位移阈值(桶, 一桶 16px)
    parameter [4:0]  ACC_TH_P = 5'd12   // 投影路的累积阈值(比车道线的 12 低)
)(
    input  wire        clk   ,
    input  wire        rst_n ,
    input  wire        tick  ,      // 每帧一个脉冲
    input  wire [10:0] lane_x,      // 左线底部锚点 {valid, x[9:0]} = anch[43:33]
    // v46: 列投影给的帧间位移, 正 = 画面内容右移 = 车向左转
    input  wire signed [4:0] proj_dx,
    input  wire        proj_vld,
    output wire [1:0]  ego          // 0=直行 1=左转 2=右转
);

    reg [1:0] ego_line;             // 车道线路的结论


    // ---- 累积器上限: 比 ACC_TH 高 4 格, 够饱和又不浪费位宽 ----
    localparam signed [5:0] A_MAX = 6'sd12;

    reg  [87:0]       hist;        // 8 帧 x 11 位 的锚点历史
    reg  signed [5:0] acc;         // 带符号累积器 -12..+12

    // ---- 当前帧 / 8 帧前的锚点 ----
    wire        v_now = lane_x[10];
    wire        v_old = hist[87];
    wire [9:0]  x_now = lane_x[9:0];
    wire [9:0]  x_old = hist[86:77];

    // 两帧都有效才敢做差分, 否则"无效值 0"会算出几百像素的假位移
    wire ok = v_now & v_old;

    // ---- 8 帧差分 (12 位有符号, 范围 -1023..+1023) ----
    wire signed [11:0] dx = {2'b0, x_now} - {2'b0, x_old};

    // ---- 阈值也要声明成 signed, 否则和 dx 比较时会按无符号比(负数变巨大)----
    wire signed [11:0] dth = {2'b0, DX_TH};

    //  车右转 -> 画面整体左移 -> 左线 x 变小 -> dx < 0
    //  车左转 -> 画面整体右移 -> 左线 x 变大 -> dx > 0
    wire go_l_lane = ok && (dx >  dth);    // 左线右移 -> 左转
    wire go_r_lane = ok && (dx < -dth);    // 左线左移 -> 右转

    //------------------------------------------------------------------
    // v46: 锚点锁死检测
    //
    //   【为什么需要】路口里锚点不只是"失效", 还有更坏的一种情况: 锁到
    //   斑马线/停止线的某个边缘上, 然后就一动不动了。石2.0 帧 174..269
    //   的 L599 恒等于 284, 整整 96 帧一个像素都不变 —— 真实车道线在
    //   行驶中不可能这么静, 这一定是锁错了目标。
    //   这种时候 valid 是 1、8 帧差分是 0, 现有判据会得出"非常直"的
    //   错误结论, 而且越"稳"越可信, 完全没法用。
    //
    //   【判据】连续 LOCK_N 帧 x 完全相等 = 锁死。用一个计数器就够,
    //   比"看方差"省得多, 而且对付这种"死值"最直接。
    //------------------------------------------------------------------
    reg [4:0]  lock_cnt;
    reg [9:0]  x_prev;
    reg        x_prev_v;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            lock_cnt <= 5'd0;
            x_prev   <= 10'd0;
            x_prev_v <= 1'b0;
        end else if (tick) begin
            x_prev_v <= v_now;
            x_prev   <= x_now;
            if (!v_now)
                lock_cnt <= 5'd0;                       // 丢了就不算锁死
            else if (x_prev_v && (x_now == x_prev)) begin
                if (lock_cnt != 5'd31) lock_cnt <= lock_cnt + 5'd1;
            end else
                lock_cnt <= 5'd0;
        end
    end

    wire stuck    = (lock_cnt >= LOCK_N);

    //------------------------------------------------------------------
    // v46: 锚点跳变检测 (另一种不可信)
    //
    //   路口里还有第三种情况: 锚点在斑马线两头来回蹦。石3.0 帧 134..147
    //   的 L599 是 359 -> 176 -> 182 -> 13 -> 212 -> 162, 一帧能跳 180
    //   像素。真实车道线在 24fps 下每帧最多走 4~6 像素(弯道实测),
    //   跳 16 以上只可能是锁错了目标。
    //
    //   ★只靠"锁死"不够★ 石2.0 是锁死(96 帧恒等), 石3.0 是乱蹦,
    //   两种都得切到投影, 所以判据要两条都收。
    //------------------------------------------------------------------
    wire [9:0] x_diff = (x_now >= x_prev) ? (x_now - x_prev) : (x_prev - x_now);
    wire jump = x_prev_v & v_now & (x_diff > 10'd16);

    //------------------------------------------------------------------
    // ★跳变只持续一帧, 必须自己保持一段★
    //   jump 是"这一帧跳了"的脉冲, 下一帧 x_prev 已经更新, 脉冲就没了。
    //   如果拿脉冲直接当 use_proj, 投影只在零星的几帧生效, 累积器根本
    //   攒不到 ACC_TH(要连续 12 帧)。
    //   石3.0 帧 135/138/139/143 各跳一次, 中间隔着好几帧正常值 ——
    //   保持 8 帧刚好把这些缝补上, 又不至于路口外也常开。
    //------------------------------------------------------------------
    reg [3:0] jump_hold;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)          jump_hold <= 4'd0;
        else if (tick) begin
            if (jump)                 jump_hold <= 4'd8;
            else if (jump_hold != 0)  jump_hold <= jump_hold - 4'd1;
        end
    end

    wire jump_act = (jump_hold != 4'd0);

    //------------------------------------------------------------------
    // ★仲裁也要保持★
    //   投影路一旦判出转向, 就不能让 use_proj 掉回 0 —— 否则切回车道线
    //   的那一帧, 车道路正卡在"锚点不动所以很直"的错误结论上, 灯会闪回
    //   直行。石2.0 实测 192->202 断了 9 帧就是这么来的。
    //   只要 ego_p 还非零, 就一直听投影的。
    //------------------------------------------------------------------
    reg [1:0] ego_p;
    wire proj_busy = (ego_p != 2'd0);

    //------------------------------------------------------------------
    // ★冲突否决★
    //   投影有一个改不掉的毛病: 有亮线从画面里滑出去时, 64 个桶的分布
    //   被拽向剩下那一侧, SAD 就把"分布变了"读成"内容平移了", 方向正好
    //   反。石2.0 帧 260..330 就是这样 —— 进新路, 左侧双黄线一路往画面
    //   左边滑出, 投影报 +5(左转), 而真值是右弯(L599 从 315 掉到 137)。
    //
    //   但那种时候车道线是**有明确趋势**的(8 帧差分 -43 以上), 只是还没
    //   攒够 ACC_TH 而已。反过来, 石2.0 路口内(帧 180..220)和石3.0 路口
    //   内(帧 136..171)锚点要么锁死要么乱跳, 8 帧差分根本凑不出方向。
    //
    //   所以规则很简单: 车道线有明确趋势、而且趋势和投影**反号**时,
    //   判定投影被分布变化带偏, 这一帧不用它。不反号就照用。
    //------------------------------------------------------------------
    wire [11:0] dx_abs12  = dx[11] ? ((~dx) + 12'd1) : dx;
    wire        lane_trend = ok & (dx_abs12 > 12'd30);
    wire        conflict   = lane_trend & (dx[11] ^ proj_dx[4]);

    //------------------------------------------------------------------
    // ★冲突也要算"连续"★
    //   单帧冲突不能清零: 石3.0 路口内 L599 在 13/176/212/359 之间跳,
    //   8 帧差分时不时就凑出个 -197, 跟投影(+4)反号 —— 但那是锚点在
    //   换目标, 不是"线在滑出", 清零就把真的左转打断了。
    //   石2.0 出路口那段不一样: L599 从 315 一路掉到 137, 差分**连续**
    //   十几帧都是负的。所以要求连续 CONFLICT_N 帧才认。
    //------------------------------------------------------------------
    localparam [3:0] CONFLICT_N = 4'd6;

    reg [3:0] cft_cnt;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) cft_cnt <= 4'd0;
        else if (tick) begin
            // ★用"泄漏积分"而不是"连续计数"★
            //   两边的要求正好错开: 石2.0 出路口是连续十几帧反号,
            //   石3.0 路口内只是零散三四帧反号(锚点换目标)。
            //   纯连续计数调 6 会误伤石3.0, 调 10 又放过石2.0;
            //   改成"冲突 +1, 不冲突 -1"之后, 零星冲突涨不上去,
            //   持续冲突很快就满, 一个门限同时满足两边。
            if (conflict) begin
                if (cft_cnt != 4'd15) cft_cnt <= cft_cnt + 4'd1;
            end else
                cft_cnt <= 4'd0;
        end
    end

    wire cft_hard = (cft_cnt >= CONFLICT_N);

    // 主路不可用 / 锚点锁死 / 刚跳变过 / 投影正在报  -> 想用投影
    // 但和车道线的明确趋势打架时, 听车道线的
    wire want_proj = (~ok) | stuck | jump_act | proj_busy;
    wire use_proj  = want_proj & (~cft_hard);

    // ---------------- 投影路判据 ----------------
    //   proj_dx 已经是"正 = 左转"的语义, 和车道线那一路对齐, 直接比阈值。
    wire signed [4:0] dth_p = {1'b0, DTH_P};
    wire go_l_proj = proj_vld && (proj_dx >=  dth_p);
    wire go_r_proj = proj_vld && (proj_dx <= -dth_p);

    // ---- 滞回门限 ----
    wire signed [5:0] th_hi = {1'b0, ACC_TH};
    wire signed [5:0] th_lo = {1'b0, ACC_TH} - {1'b0, ACC_HY};
    // 投影路单独一套: 它的证据比"一条线的 8 帧差分"强(整幅画面在动),
    // 但幅度只有 ±6 桶, 攒得慢, 门限压低两格才追得上车道路的反应速度。
    wire signed [5:0] th_hi_p = {1'b0, ACC_TH_P};
    wire signed [5:0] th_lo_p = {1'b0, ACC_TH_P} - {1'b0, ACC_HY};

    //------------------------------------------------------------------
    // 0) 锚点历史 (每帧移一位, hist[87:77] 就是 8 帧前的值)
    //------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            hist <= 88'd0;
        else if (tick)
            hist <= {hist[76:0], lane_x};
    end

    //------------------------------------------------------------------
    // 1) 车道线路累积器 —— v45 原样, 一个字都不动
    //
    //   ★为什么先算 acc_nx 再判 ego★
    //   acc 和 ego 如果写在两个 always 里, ego 那一拍看到的是 acc 的"旧值",
    //   状态会整整晚一帧才变(10 帧的积累要第 11 帧才亮灯)。先组合算出
    //   acc_nx, 同一个时钟沿同时更新 acc 和 ego, 就没有这一帧延迟。
    //   这个坑是 tb_ego_state 抓出来的, 不是推出来的。
    //------------------------------------------------------------------
    reg signed [5:0] acc_nx;

    always @(*) begin
        if (!ok)
            acc_nx = acc;                  // 锚点无效(本帧或 8 帧前没命中): 冻结
                                           //   ★不能像 v44 那样慢慢滑回零★
                                           //   否则过一次路口(线丢了 1 秒)灯就自己
                                           //   熄成"直行", 看着像掉了。
        else if (go_l_lane)
            acc_nx = (acc < A_MAX) ? (acc + 6'sd1) : A_MAX;   // 往 + 走, 到上限停
        else if (go_r_lane)
            acc_nx = (acc > -A_MAX) ? (acc - 6'sd1) : -A_MAX;  // 往 - 走
        else if (acc > 6'sd0)
            acc_nx = acc - 6'sd1;          // 没在转: 缓慢回零
        else if (acc < 6'sd0)
            acc_nx = acc + 6'sd1;
        else
            acc_nx = 6'sd0;
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            acc      <= 6'sd0;
            ego_line <= 2'd0;
        end else if (tick) begin
            acc <= acc_nx;

            if (acc_nx >= th_hi)                      ego_line <= 2'd1;  // 进: 左转
            else if (acc_nx <= -th_hi)                ego_line <= 2'd2;  // 进: 右转
            else if ((ego_line == 2'd1) && (acc_nx >= th_lo))  ego_line <= 2'd1;
            else if ((ego_line == 2'd2) && (acc_nx <= -th_lo)) ego_line <= 2'd2;
            else                                      ego_line <= 2'd0;  // 直行
        end
    end

    //------------------------------------------------------------------
    // 2) 投影路累积器 (v46)
    //
    //   ★为什么这里要单独一套, 不跟车道线共用一个 acc★
    //   两路的量纲和节奏完全不同: 车道线 8 帧差分是 -200..+200 的连续量,
    //   投影是 -6..+6 的整桶。共用一个 acc 时, 切换那一帧会把另一路攒了
    //   半天的数当成自己的基础, 石2.0 实测出现过 LEFT 亮 6 帧后断掉 9 帧
    //   又亮回来的"闪灯"。分开之后各自的滞回互不干扰, 切换只是选值。
    //------------------------------------------------------------------
    reg signed [5:0] acc_p, acc_p_nx;

    //------------------------------------------------------------------
    // 死区保持 + 超时清除
    //
    //   【为什么不像车道路那样"没在转就回零"】
    //   石2.0 帧 187..201 投影位移在 2/0/0/-1/-1/-1/1/0/3 之间爬, 十五帧
    //   里没有一帧够阈值。车道路那套"每帧 -1"会把攒到 12 的累积器六帧
    //   就撸到 0 —— 灯在路口正中间熄掉, 看着像没认出来。
    //   投影是"整幅画面在动"的证据, 死区(小于阈值)只说明这一帧没测到,
    //   不代表车回正了, 所以保持不动。
    //
    //   【那怎么退出】靠超时: 连续 PROJ_IDLE 帧都落在死区, 认定已经不在
    //   转向, 清零。石2.0 出弯后 dx 持续在 0/-1, 24 帧(约 1.1 s)后熄灭。
    //------------------------------------------------------------------
    localparam [4:0] PROJ_IDLE = 5'd24;
    localparam [5:0] PROJ_MAX  = 6'd45;    // 单次转向最长保持 45 帧(约 2 s)

    reg  [4:0] idle_cnt;
    reg  [5:0] ehold;
    wire signed [4:0] dx_abs  = (proj_dx >= 0) ? proj_dx : -proj_dx;
    wire              proj_dead = (dx_abs < dth_p);

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) idle_cnt <= 5'd0;
        else if (tick) begin
            if (!proj_dead)           idle_cnt <= 5'd0;
            else if (idle_cnt != 5'd31) idle_cnt <= idle_cnt + 5'd1;
        end
    end

    //------------------------------------------------------------------
    // ★为什么还要一个"最长保持"★
    //   死区保持 + idle 超时能挡住"没证据", 但挡不住"一直在边缘给一点点
    //   证据"的情况: 石2.0 出路口后(帧 325 起) dx 稳定在 +2, 刚好等于阈值,
    //   idle 永远清不到 24, 于是 LEFT 一路亮到片子结束, 整整 74 帧。
    //   真实转弯没有超过 50 帧(2.3 s)的, 到点强制清零, 当保险丝用。
    //------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)      ehold <= 6'd0;
        else if (tick) begin
            if (ego_p == 2'd0)              ehold <= 6'd0;
            else if (ehold != 6'd63)        ehold <= ehold + 6'd1;
        end
    end

    always @(*) begin
        if (!proj_vld)
            acc_p_nx = acc_p;              // 投影还没预热完(前 8 帧): 冻结
        else if ((idle_cnt >= PROJ_IDLE) || (ehold >= PROJ_MAX))
            acc_p_nx = 6'sd0;              // 太久没证据 / 保持超时: 清零
        else if (cft_hard)
            acc_p_nx = 6'sd0;              // 连续和车道线趋势打架: 清零, 别硬扛
        else if (go_l_proj) begin
            // ★位移越大加得越快★ 石3.0 的左转只有 13 帧窗口, 而且位移
            //   在 3~6 桶之间摆动, 每帧 +1 要走 12 帧才够, 中间随便被
            //   打断一次就前功尽弃。>=4 桶的帧按 +2 计, 8 帧就能到。
            if (acc_p > A_MAX - 6'sd2)      acc_p_nx = A_MAX;
            else if (dx_abs >= 5'd4)        acc_p_nx = acc_p + 6'sd2;
            else                            acc_p_nx = acc_p + 6'sd1;
        end
        else if (go_r_proj) begin
            if (acc_p < -A_MAX + 6'sd2)     acc_p_nx = -A_MAX;
            else if (dx_abs >= 5'd4)        acc_p_nx = acc_p - 6'sd2;
            else                            acc_p_nx = acc_p - 6'sd1;
        end
        else
            acc_p_nx = acc_p;              // 死区: 保持, 不回零
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            acc_p <= 6'sd0;
            ego_p <= 2'd0;
        end else if (tick) begin
            acc_p <= acc_p_nx;

            if (acc_p_nx >= th_hi_p)                     ego_p <= 2'd1;
            else if (acc_p_nx <= -th_hi_p)               ego_p <= 2'd2;
            else if ((ego_p == 2'd1) && (acc_p_nx >= th_lo_p))  ego_p <= 2'd1;
            else if ((ego_p == 2'd2) && (acc_p_nx <= -th_lo_p)) ego_p <= 2'd2;
            else                                       ego_p <= 2'd0;
        end
    end

    //------------------------------------------------------------------
    // 3) 仲裁: 车道线可信就用车道线, 不可信就用投影
    //
    //   ★投影没数据时必须退回车道线路, 不能输出 ego_p★
    //   投影要预热 8 帧才有第一个结果, 上电后头 8 帧 proj_vld=0。这时候
    //   如果照 use_proj 选 ego_p, 输出就是 0(直行), 把 v45 那条"丢线时
    //   保持上一次结论"的规矩破坏了 —— tb_ego_state 就是这么报的 NG。
    //------------------------------------------------------------------
    assign ego = (use_proj & proj_vld) ? ego_p : ego_line;

endmodule
